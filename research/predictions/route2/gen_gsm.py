"""Emit a gsm registry for scenario S1 of the CouchDB model.

One enum variable, the revision tree, over the 36 trees closed under the raw
replicated update (leaf filter and merge, no stemming) and under stem_3.
Events: the raw replicated update of each of the four revisions.
Invariant: the tree is stemmed (stem T = T); repair: stem.
gsm's governed step (event, then repair to normal form) is then exactly
CouchDB's interactive replicated update; gsm's Build checks WFC and CC.

Writes gsm_couch/main.go. Run: cd gsm_couch && go run .
"""

import os

import compute as C
import couch_model as cm

K = 3
evs = C.events_for(C.H1, {"d"}, lambda r, d, L: L == d)

# States are taken up to shape (internal bodies erased, as compaction does):
# the steps respect shape (checked below), so the tables are well defined and
# a counterexample is a difference in keys, structure or leaf deletion flags.
SH = cm.shape
seen = [()]
idx = {SH(()): 0}
i = 0
while i < len(seen):
    T = seen[i]
    i += 1
    for _, e in evs:
        for T2 in (cm.replicated_update(T, e, K, False), cm.stem(T, K)):
            if SH(T2) not in idx:
                idx[SH(T2)] = len(seen)
                seen.append(T2)


def label(T):
    if not T:
        return "s0_empty"
    return "s%d_%s" % (idx[SH(T)], "_".join(
        "%d%s%s" % (p, r[0], "x" if d else "") for p, r, d in cm.obs_leaves(T)))


labels = [label(T) for T in seen]
ev_tab = {name.split("/")[0]: [idx[SH(cm.replicated_update(T, e, K, False))] for T in seen]
          for name, e in evs}
stem_tab = [idx[SH(cm.stem(T, K))] for T in seen]

# respect check: every state reached (with any internal bodies) maps like its
# representative
_all = {()}
_todo = [()]
while _todo:
    T = _todo.pop()
    for _, e in evs:
        for T2 in (cm.replicated_update(T, e, K, False), cm.stem(T, K)):
            if T2 not in _all:
                _all.add(T2)
                _todo.append(T2)
for T in _all:
    r = seen[idx[SH(T)]]
    for _, e in evs:
        assert SH(cm.replicated_update(T, e, K, False)) == SH(cm.replicated_update(r, e, K, False))
    assert SH(cm.stem(T, K)) == SH(cm.stem(r, K))
print("shape respected on", len(_all), "trees")


def golist(xs):
    return "{" + ", ".join(str(x) for x in xs) + "}"


go = '''// Generated by gen_gsm.py from couch_model.py (scenario S1, revs_limit %d).
package main

import (
	"fmt"

	"github.com/blackwell-systems/gsm"
)

var labels = []string{%s}

var stemTab = []int%s

var events = map[string][]int{
%s}

var order = []string{%s}

func main() {
	pos := map[string]int{}
	for i, l := range labels {
		pos[l] = i
	}
	r := gsm.NewRegistry("couchdb_revtree_S1")
	tree := r.Enum("tree", labels...)
	r.Invariant("stemmed_to_revs_limit").
		Watches(tree).
		Holds(func(s gsm.State) bool { i := pos[s.Get(tree)]; return stemTab[i] == i }).
		Repair(func(s gsm.State) gsm.State { return s.Set(tree, labels[stemTab[pos[s.Get(tree)]]]) }).
		Add()
	for _, name := range order {
		tab := events[name]
		r.Event("replicate_"+name).Writes(tree).
			Apply(func(s gsm.State) gsm.State { return s.Set(tree, labels[tab[pos[s.Get(tree)]]]) }).
			Add()
	}
	_, report, err := r.Build()
	fmt.Println("Build error:", err)
	fmt.Println(report)
}
''' % (K, ", ".join('"%s"' % l for l in labels), golist(stem_tab),
       "".join('\t"%s": %s,\n' % (n, "[]int" + golist(t)) for n, t in ev_tab.items()),
       ", ".join('"%s"' % n for n in ev_tab))

os.makedirs("gsm_couch", exist_ok=True)
with open("gsm_couch/main.go", "w") as f:
    f.write(go)
print("states:", len(seen))
