Section Sys.
  Variable S Act : Type.
  Variable eqs : S -> S -> Prop.
  Variable ok : Act -> Prop.
  Variable step : Act -> S -> S.

  Definition run (w : list Act) (s : S) : S := fold_left (fun s a => step a s) w s.
  Definition Quiet (s : S) : Prop := forall a, ok a -> eqs (step a s) s.
  Definition WN (s : S) : Prop := exists w, Forall ok w /\ Quiet (run w s).
  Definition UN (s : S) : Prop :=
    forall w1 w2, Forall ok w1 -> Forall ok w2 -> Quiet (run w1 s) -> Quiet (run w2 s) ->
      eqs (run w1 s) (run w2 s).
  Definition Conv : Prop := forall s, WN s /\ UN s.

  Lemma run_app : forall w1 w2 s, run (w1 ++ w2) s = run w2 (run w1 s).
  Proof. intros. unfold run. apply fold_left_app. Qed.
End Sys.

Arguments run {S Act} step w s.
Arguments Quiet {S Act} eqs ok step s.
Arguments WN {S Act} eqs ok step s.
Arguments UN {S Act} eqs ok step s.
Arguments Conv {S Act} eqs ok step.

Section Compose.
  Variables X Y AA AB : Type.
  Variable eqX : X -> X -> Prop.
  Variable eqY : Y -> Y -> Prop.
  Hypothesis eqX_refl : forall x, eqX x x.
  Hypothesis eqX_sym : forall x y, eqX x y -> eqX y x.
  Hypothesis eqX_trans : forall x y z, eqX x y -> eqX y z -> eqX x z.
  Hypothesis eqY_refl : forall x, eqY x x.
  Hypothesis eqY_sym : forall x y, eqY x y -> eqY y x.
  Hypothesis eqY_trans : forall x y z, eqY x y -> eqY y z -> eqY x z.

  Variable okA : AA -> Prop.
  Variable stepA : AA -> X -> X.
  Variable okB : AB -> Prop.
  Variable stepB : X -> AB -> Y -> Y.
  Hypothesis stepA_ext : forall a x x', eqX x x' -> eqX (stepA a x) (stepA a x').
  Hypothesis stepB_ext : forall b x x' y y', eqX x x' -> eqY y y' -> eqY (stepB x b y) (stepB x' b y').
  Variable y_inh : Y.

  (* The composite. *)
  Definition eqC (p q : X * Y) : Prop := eqX (fst p) (fst q) /\ eqY (snd p) (snd q).
  Definition okC (c : AA + AB) : Prop := match c with inl a => okA a | inr b => okB b end.
  Definition stepC (c : AA + AB) (p : X * Y) : X * Y :=
    match c with inl a => (stepA a (fst p), snd p) | inr b => (fst p, stepB (fst p) b (snd p)) end.

  Local Notation runA := (run stepA).
  Local Notation runB x := (run (stepB x)).
  Local Notation runC := (run stepC).
  Local Notation QA := (Quiet eqX okA stepA).
  Local Notation QB x := (Quiet eqY okB (stepB x)).
  Local Notation QC := (Quiet eqC okC stepC).

  Fixpoint projA (w : list (AA + AB)) : list AA :=
    match w with [] => [] | inl a :: r => a :: projA r | inr _ :: r => projA r end.
  Fixpoint projB (w : list (AA + AB)) : list AB :=
    match w with [] => [] | inr b :: r => b :: projB r | inl _ :: r => projB r end.

  Lemma projA_ok : forall w, Forall okC w -> Forall okA (projA w).
  Proof.
    induction w as [| c w IH]; intros H; [constructor |]. inversion H; subst.
    destruct c; simpl; [constructor; [assumption |] |]; apply IH; assumption.
  Qed.

  Lemma projB_ok : forall w, Forall okC w -> Forall okB (projB w).
  Proof.
    induction w as [| c w IH]; intros H; [constructor |]. inversion H; subst.
    destruct c; simpl; [| constructor; [assumption |]]; apply IH; assumption.
  Qed.

  Lemma fst_runC : forall w p, fst (runC w p) = runA (projA w) (fst p).
  Proof. induction w as [| c w IH]; intros [x y]; [reflexivity |]. destruct c; simpl; apply IH. Qed.

  Lemma runC_inl : forall w x y, runC (map inl w) (x, y) = (runA w x, y).
  Proof. induction w as [| a w IH]; intros x y; [reflexivity |]. simpl. apply IH. Qed.

  Lemma runC_inr : forall w x y, runC (map inr w) (x, y) = (x, runB x w y).
  Proof. induction w as [| b w IH]; intros x y; [reflexivity |]. simpl. apply IH. Qed.

  Lemma ok_inl : forall w, Forall okA w -> Forall okC (map inl w).
  Proof. induction w; intros H; inversion H; subst; constructor; simpl; auto. Qed.

  Lemma ok_inr : forall w, Forall okB w -> Forall okC (map inr w).
  Proof. induction w; intros H; inversion H; subst; constructor; simpl; auto. Qed.

  Lemma ok_app' : forall {T} (P : T -> Prop) l1 l2, Forall P l1 -> Forall P l2 -> Forall P (l1 ++ l2).
  Proof. intros T P l1 l2 H1 H2. apply Forall_app. split; assumption. Qed.

  Lemma runA_ext : forall w x x', eqX x x' -> eqX (runA w x) (runA w x').
  Proof. induction w as [| a w IH]; intros x x' H; [exact H |]. simpl. apply IH, stepA_ext, H. Qed.

  Lemma runB_ext : forall w x x' y y', eqX x x' -> eqY y y' -> eqY (runB x w y) (runB x' w y').
  Proof. induction w as [| b w IH]; intros x x' y y' Hx Hy; [exact Hy |]. simpl. apply IH; [exact Hx | apply stepB_ext; assumption]. Qed.

  Lemma runC_ext : forall w p q, eqC p q -> eqC (runC w p) (runC w q).
  Proof.
    induction w as [| c w IH]; intros [x y] [x' y'] [Hx Hy]; [split; assumption |].
    simpl. apply IH. destruct c; split; simpl; auto.
  Qed.

  Lemma QA_run : forall w x, QA x -> Forall okA w -> eqX (runA w x) x.
  Proof.
    induction w as [| a w IH]; intros x Hq Hw; [apply eqX_refl |]. inversion Hw; subst. simpl.
    eapply eqX_trans; [apply runA_ext; apply Hq; assumption |]. apply IH; assumption.
  Qed.

  Lemma QA_eq : forall x x', QA x -> eqX x x' -> QA x'.
  Proof.
    intros x x' Hq H a Ha. eapply eqX_trans; [apply stepA_ext, eqX_sym, H |].
    eapply eqX_trans; [apply Hq, Ha | exact H].
  Qed.

  Lemma QB_eq : forall x x' y y', QB x y -> eqX x x' -> eqY y y' -> QB x' y'.
  Proof.
    intros x x' y y' Hq Hx Hy b Hb. eapply eqY_trans; [apply stepB_ext; [apply eqX_sym, Hx | apply eqY_sym, Hy] |].
    eapply eqY_trans; [apply Hq, Hb | exact Hy].
  Qed.

  Lemma QC_iff : forall x y, QC (x, y) <-> QA x /\ QB x y.
  Proof.
    intros x y. split.
    - intros H. split.
      + intros a Ha. exact (proj1 (H (inl a) Ha)).
      + intros b Hb. exact (proj2 (H (inr b) Hb)).
    - intros [Ha Hb] [a | b] Hc; split; simpl; auto.
  Qed.

  Lemma eqC_sym : forall p q, eqC p q -> eqC q p.
  Proof. intros p q [A B]. split; [apply eqX_sym, A | apply eqY_sym, B]. Qed.

  Lemma QC_eq : forall p q, QC p -> eqC p q -> QC q.
  Proof.
    intros [x y] [x' y'] H [Hx Hy]. apply QC_iff in H. apply QC_iff. simpl in *.
    split; [exact (QA_eq x x' (proj1 H) Hx) | exact (QB_eq x x' y y' (proj2 H) Hx Hy)].
  Qed.

  (* From a quiet input, the composite only runs B at that input. *)
  Lemma runC_quiet : forall xs w x y y', QA xs -> eqX x xs -> eqY y y' -> Forall okC w ->
    eqX (fst (runC w (x, y))) xs /\ eqY (snd (runC w (x, y))) (runB xs (projB w) y').
  Proof.
    intros xs. induction w as [| c w IH]; intros x y y' Hq Hx Hy Hw; [split; assumption |].
    inversion Hw; subst. destruct c as [a | b]; simpl.
    - apply IH; [exact Hq | | exact Hy | assumption].
      eapply eqX_trans; [apply stepA_ext, Hx |]. apply Hq. assumption.
    - apply IH; [exact Hq | exact Hx | | assumption]. apply stepB_ext; assumption.
  Qed.

  (* ----- the interleaving relation ----- *)
  Inductive Lk (xs : X) : Y -> Y -> Prop :=
  | lk_base : forall x w b y, Forall okA w -> eqX (runA w x) xs -> okB b -> Lk xs y (stepB x b y)
  | lk_eq : forall y y', eqY y y' -> Lk xs y y'
  | lk_sym : forall y y', Lk xs y y' -> Lk xs y' y
  | lk_trans : forall y y' y'', Lk xs y y' -> Lk xs y' y'' -> Lk xs y y''.

  Lemma lk_index : forall xs xs' y y', eqX xs xs' -> Lk xs y y' -> Lk xs' y y'.
  Proof.
    intros xs xs' y y' He H. induction H.
    - eapply lk_base; [eassumption | eapply eqX_trans; eassumption | assumption].
    - apply lk_eq; assumption.
    - apply lk_sym; assumption.
    - eapply lk_trans; eassumption.
  Qed.

  (* Every composite run from (x, y) moves y within Lk of A's final state. *)
  Lemma lk_run : forall w x y, Forall okC w -> Lk (runA (projA w) x) y (snd (runC w (x, y))).
  Proof.
    induction w as [| c w IH]; intros x y Hw; [apply lk_eq, eqY_refl |]. inversion Hw as [| ? ? Hc Hw']; subst.
    destruct c as [a | b]; simpl.
    - apply IH. exact Hw'.
    - eapply lk_trans; [| apply IH; exact Hw'].
      eapply lk_base; [apply projA_ok; exact Hw' | apply eqX_refl | exact Hc].
  Qed.

  Definition WNB (xs : X) : Prop := forall y, WN eqY okB (stepB xs) y.
  Definition LkUnique (xs : X) : Prop :=
    forall y1 y2, QB xs y1 -> QB xs y2 -> Lk xs y1 y2 -> eqY y1 y2.

  (* ----- necessity ----- *)

  Lemma conv_A : Conv eqC okC stepC -> Conv eqX okA stepA.
  Proof.
    intros H x. split.
    - destruct (proj1 (H (x, y_inh))) as [w [Hw Hq]].
      exists (projA w). split; [apply projA_ok; exact Hw |].
      destruct (runC w (x, y_inh)) as [x1 y1] eqn:E. apply QC_iff in Hq. pose proof (fst_runC w (x, y_inh)) as F. rewrite E in F. simpl in F. rewrite <- F. exact (proj1 Hq).
    - intros w1 w2 H1 H2 Q1 Q2.
      set (x1 := runA w1 x). set (x2 := runA w2 x).
      destruct (proj1 (H (x1, y_inh))) as [v1 [Hv1 R1]].
      destruct (proj1 (H (x2, y_inh))) as [v2 [Hv2 R2]].
      assert (U := proj2 (H (x, y_inh)) (map inl w1 ++ v1) (map inl w2 ++ v2)
                 (ok_app' _ _ _ (ok_inl _ H1) Hv1) (ok_app' _ _ _ (ok_inl _ H2) Hv2)).
      rewrite !run_app, !runC_inl in U. specialize (U R1 R2).
      destruct (runC_quiet x1 v1 x1 y_inh y_inh Q1 (eqX_refl _) (eqY_refl _) Hv1) as [F1 _].
      destruct (runC_quiet x2 v2 x2 y_inh y_inh Q2 (eqX_refl _) (eqY_refl _) Hv2) as [F2 _].
      eapply eqX_trans; [apply eqX_sym, F1 |]. eapply eqX_trans; [apply (proj1 U) | exact F2].
  Qed.

  Lemma conv_WNB : Conv eqC okC stepC -> forall xs, QA xs -> WNB xs.
  Proof.
    intros H xs Hq y. destruct (proj1 (H (xs, y))) as [w [Hw Q]].
    exists (projB w). split; [apply projB_ok; exact Hw |].
    destruct (runC_quiet xs w xs y y Hq (eqX_refl _) (eqY_refl _) Hw) as [F S].
    destruct (runC w (xs, y)) as [x1 y1] eqn:E. simpl in F, S. apply QC_iff in Q.
    exact (QB_eq x1 xs y1 _ (proj2 Q) F S).
  Qed.

  (* All quiet states reachable from (xs, y) and from (xs, y') agree. *)
  Definition Agree (xs : X) (y y' : Y) : Prop :=
    forall w1 w2, Forall okC w1 -> Forall okC w2 -> QC (runC w1 (xs, y)) -> QC (runC w2 (xs, y')) ->
      eqC (runC w1 (xs, y)) (runC w2 (xs, y')).

  Lemma conv_LkUnique : Conv eqC okC stepC -> forall xs, QA xs -> LkUnique xs.
  Proof.
    intros H xs Hq.
    assert (Hag : forall y y', Lk xs y y' -> Agree xs y y').
    { intros y y' L. induction L as [x w b y Hw Hr Hb | y y' He | y y' _ IH | y y' y'' _ IH1 _ IH2].
      - intros w1 w2 H1 H2 Q1 Q2.
        (* from (x, y): w, then w1 reaches the first; b, w, then w2 reaches the second *)
        assert (E1 : eqC (runC (map inl w ++ w1) (x, y)) (runC w1 (xs, y))).
        { rewrite run_app, runC_inl. apply runC_ext. split; [exact Hr | apply eqY_refl]. }
        assert (E2 : eqC (runC ((inr b :: map inl w) ++ w2) (x, y)) (runC w2 (xs, stepB x b y))).
        { rewrite run_app. simpl. rewrite runC_inl. apply runC_ext. split; [exact Hr | apply eqY_refl]. }
        assert (O1 : Forall okC (map inl w ++ w1)) by (apply ok_app'; [apply ok_inl; exact Hw | exact H1]).
        assert (O2 : Forall okC ((inr b :: map inl w) ++ w2))
          by (apply ok_app'; [constructor; [exact Hb | apply ok_inl; exact Hw] | exact H2]).
        pose proof (proj2 (H (x, y)) _ _ O1 O2 (QC_eq _ _ Q1 (eqC_sym _ _ E1))
                      (QC_eq _ _ Q2 (eqC_sym _ _ E2))) as U.
        destruct E1 as [A1 B1]. destruct E2 as [A2 B2]. destruct U as [A B].
        split; [eapply eqX_trans; [apply eqX_sym, A1 | eapply eqX_trans; [exact A | exact A2]] |].
        eapply eqY_trans; [apply eqY_sym, B1 | eapply eqY_trans; [exact B | exact B2]].
      - intros w1 w2 H1 H2 Q1 Q2.
        assert (E : eqC (runC w2 (xs, y)) (runC w2 (xs, y'))) by (apply runC_ext; split; [apply eqX_refl | exact He]).
        pose proof (proj2 (H (xs, y)) w1 w2 H1 H2 Q1 (QC_eq _ _ Q2 (eqC_sym _ _ E))) as [A B].
        destruct E as [A' B']. split; [eapply eqX_trans; eassumption | eapply eqY_trans; eassumption].
      - intros w1 w2 H1 H2 Q1 Q2. destruct (IH w2 w1 H2 H1 Q2 Q1) as [A B].
        split; [apply eqX_sym, A | apply eqY_sym, B].
      - intros w1 w2 H1 H2 Q1 Q2. destruct (proj1 (H (xs, y'))) as [v [Hv Qv]].
        destruct (IH1 w1 v H1 Hv Q1 Qv) as [A1 B1]. destruct (IH2 v w2 Hv H2 Qv Q2) as [A2 B2].
        split; [eapply eqX_trans; eassumption | eapply eqY_trans; eassumption]. }
    intros y1 y2 Q1 Q2 L.
    assert (C1 : QC (runC [] (xs, y1))) by (apply QC_iff; split; assumption).
    assert (C2 : QC (runC [] (xs, y2))) by (apply QC_iff; split; assumption).
    exact (proj2 (Hag y1 y2 L [] [] (Forall_nil _) (Forall_nil _) C1 C2)).
  Qed.

  (* ----- sufficiency ----- *)

  Lemma compose_suff : Conv eqX okA stepA -> (forall xs, QA xs -> WNB xs) ->
    (forall xs, QA xs -> LkUnique xs) -> Conv eqC okC stepC.
  Proof.
    intros HA HW HL [x y]. split.
    - destruct (proj1 (HA x)) as [wa [Ha Qa]]. destruct (HW _ Qa y) as [wb [Hb Qb]].
      exists (map inl wa ++ map inr wb). split; [apply ok_app'; [apply ok_inl | apply ok_inr]; assumption |].
      rewrite run_app, runC_inl, runC_inr. apply QC_iff. split; assumption.
    - intros w1 w2 H1 H2 Q1 Q2.
      pose proof (lk_run w1 x y H1) as L1. pose proof (lk_run w2 x y H2) as L2.
      pose proof (fst_runC w1 (x, y)) as F1. pose proof (fst_runC w2 (x, y)) as F2. simpl in F1, F2.
      destruct (runC w1 (x, y)) as [x1 y1]. destruct (runC w2 (x, y)) as [x2 y2]. simpl in *.
      apply QC_iff in Q1. apply QC_iff in Q2. subst x1 x2.
      assert (Ex : eqX (runA (projA w1) x) (runA (projA w2) x)).
      { apply (proj2 (HA x)); [apply projA_ok; exact H1 | apply projA_ok; exact H2 | apply Q1 | apply Q2]. }
      split; [exact Ex |]. simpl.
      apply (HL _ (proj1 Q1)); [apply Q1 | exact (QB_eq _ _ _ _ (proj2 Q2) (eqX_sym _ _ Ex) (eqY_refl _)) |].
      eapply lk_trans; [apply lk_sym; exact L1 |]. apply (lk_index _ _ _ _ (eqX_sym _ _ Ex)). exact L2.
  Qed.

  (* Headline (a): the exact condition for a composite of two blocks with any engines. *)
  Theorem compose_exact :
    Conv eqC okC stepC <->
    Conv eqX okA stepA /\ (forall xs, QA xs -> WNB xs) /\ (forall xs, QA xs -> LkUnique xs).
  Proof.
    split.
    - intros H. split; [apply conv_A; exact H |]. split; [apply conv_WNB; exact H | apply conv_LkUnique; exact H].
    - intros [HA [HW HL]]. apply compose_suff; assumption.
  Qed.

  (* The collapse: the composite's normal form is computed block by block, B started from the
     ORIGINAL y at A's normal form. *)
  Theorem compose_collapse :
    Conv eqX okA stepA -> (forall xs, QA xs -> WNB xs) -> (forall xs, QA xs -> LkUnique xs) ->
    forall x y wa wb w, Forall okA wa -> QA (runA wa x) -> Forall okB wb ->
      QB (runA wa x) (runB (runA wa x) wb y) -> Forall okC w -> QC (runC w (x, y)) ->
      eqC (runC w (x, y)) (runA wa x, runB (runA wa x) wb y).
  Proof.
    intros HA HW HL x y wa wb w Ha Qa Hb Qb Hw Qw.
    pose proof (compose_suff HA HW HL) as HC.
    assert (O : Forall okC (map inl wa ++ map inr wb)) by (apply ok_app'; [apply ok_inl | apply ok_inr]; assumption).
    assert (R : runC (map inl wa ++ map inr wb) (x, y) = (runA wa x, runB (runA wa x) wb y))
      by (rewrite run_app, runC_inl, runC_inr; reflexivity).
    pose proof (proj2 (HC (x, y)) w _ Hw O Qw) as U. rewrite R in U. apply U.
    apply QC_iff. split; assumption.
  Qed.

  (* ----- the black-box interface ----- *)

  Variable KA : X -> X -> Prop.
  Variable KB : Y -> Y -> Prop.
  Hypothesis KA_eq : forall x x', eqX x x' -> KA x x'.
  Hypothesis KB_eq : forall y y', eqY y y' -> KB y y'.
  Hypothesis KA_sym : forall x x', KA x x' -> KA x' x.
  Hypothesis KA_trans : forall x x' x'', KA x x' -> KA x' x'' -> KA x x''.
  Hypothesis KB_sym : forall y y', KB y y' -> KB y' y.
  Hypothesis KB_trans : forall y y' y'', KB y y' -> KB y' y'' -> KB y y''.
  Hypothesis KA_step : forall a x, okA a -> KA x (stepA a x).
  Hypothesis KB_step : forall b x y, okB b -> KB y (stepB x b y).

  Definition KC (p q : X * Y) : Prop := KA (fst p) (fst q) /\ KB (snd p) (snd q).

  Lemma KB_run : forall w x y, Forall okC w -> KB y (snd (runC w (x, y))).
  Proof.
    induction w as [| c w IH]; intros x y Hw; [apply KB_eq, eqY_refl |]. inversion Hw as [| ? ? Hc Hw']; subst.
    destruct c as [a | b]; simpl; [apply IH; exact Hw' |].
    eapply KB_trans; [apply KB_step; exact Hc | apply IH; exact Hw'].
  Qed.

  Lemma lk_KB : forall xs y y', Lk xs y y' -> KB y y'.
  Proof.
    intros xs y y' L. induction L; [apply KB_step; assumption | apply KB_eq; assumption |
                                    apply KB_sym; assumption | eapply KB_trans; eassumption].
  Qed.

  (* A quiet input of A at which B settles in the interface's sense satisfies the interleaving
     conjunct: the interface is a sufficient black-box form of compose_exact's third conjunct. *)
  Theorem interface_lk : forall xs,
    (forall y1 y2, QB xs y1 -> QB xs y2 -> KB y1 y2 -> eqY y1 y2) -> LkUnique xs.
  Proof. intros xs H y1 y2 Q1 Q2 L. apply H; [exact Q1 | exact Q2 | exact (lk_KB _ _ _ L)]. Qed.

  (* The composite's interface is exactly the conjunction of its blocks' interfaces. *)
  Theorem interface_closed :
    ((forall p, WN eqC okC stepC p) /\ (forall p q, QC p -> QC q -> KC p q -> eqC p q)) <->
    ((forall x, WN eqX okA stepA x) /\ (forall x1 x2, QA x1 -> QA x2 -> KA x1 x2 -> eqX x1 x2)) /\
    (forall xs, QA xs -> WNB xs /\ (forall y1 y2, QB xs y1 -> QB xs y2 -> KB y1 y2 -> eqY y1 y2)).
  Proof.
    split.
    - intros [W U].
      assert (WA : forall x, WN eqX okA stepA x).
      { intros x. destruct (W (x, y_inh)) as [w [Hw Hq]]. exists (projA w).
        split; [apply projA_ok; exact Hw |]. destruct (runC w (x, y_inh)) as [x1 y1] eqn:E.
        apply QC_iff in Hq. pose proof (fst_runC w (x, y_inh)) as F. rewrite E in F. simpl in F. rewrite <- F. exact (proj1 Hq). }
      split; [split; [exact WA |] |].
      + intros x1 x2 Q1 Q2 K12.
        destruct (W (x1, y_inh)) as [v1 [Hv1 R1]]. destruct (W (x2, y_inh)) as [v2 [Hv2 R2]].
        destruct (runC_quiet x1 v1 x1 y_inh y_inh Q1 (eqX_refl _) (eqY_refl _) Hv1) as [F1 _].
        destruct (runC_quiet x2 v2 x2 y_inh y_inh Q2 (eqX_refl _) (eqY_refl _) Hv2) as [F2 _].
        pose proof (KB_run v1 x1 y_inh Hv1) as K1. pose proof (KB_run v2 x2 y_inh Hv2) as K2.
        assert (Kc : KC (runC v1 (x1, y_inh)) (runC v2 (x2, y_inh))).
        { split.
          - eapply KA_trans; [apply KA_eq, F1 |]. eapply KA_trans; [exact K12 | apply KA_eq, eqX_sym, F2].
          - eapply KB_trans; [apply KB_sym, K1 | exact K2]. }
        destruct (U _ _ R1 R2 Kc) as [A _].
        eapply eqX_trans; [apply eqX_sym, F1 | eapply eqX_trans; [exact A | exact F2]].
      + intros xs Qs. split.
        * intros y. destruct (W (xs, y)) as [w [Hw Q]]. exists (projB w). split; [apply projB_ok; exact Hw |].
          destruct (runC_quiet xs w xs y y Qs (eqX_refl _) (eqY_refl _) Hw) as [F S].
          destruct (runC w (xs, y)) as [x1 y1] eqn:E. simpl in F, S. apply QC_iff in Q.
          exact (QB_eq x1 xs y1 _ (proj2 Q) F S).
        * intros y1 y2 Q1 Q2 K.
          assert (C1 : QC (xs, y1)) by (apply QC_iff; split; assumption).
          assert (C2 : QC (xs, y2)) by (apply QC_iff; split; assumption).
          exact (proj2 (U _ _ C1 C2 (conj (KA_eq _ _ (eqX_refl _)) K))).
    - intros [[WA UA] HB]. split.
      + intros [x y]. destruct (WA x) as [wa [Ha Qa]]. destruct (proj1 (HB _ Qa) y) as [wb [Hb Qb]].
        exists (map inl wa ++ map inr wb). split; [apply ok_app'; [apply ok_inl | apply ok_inr]; assumption |].
        rewrite run_app, runC_inl, runC_inr. apply QC_iff. split; assumption.
      + intros [x1 y1] [x2 y2] Q1 Q2 [K1 K2]. apply QC_iff in Q1. apply QC_iff in Q2. simpl in *.
        assert (Ex : eqX x1 x2) by (apply UA; [apply Q1 | apply Q2 | exact K1]).
        split; [exact Ex |]. simpl.
        apply (proj2 (HB _ (proj1 Q1))); [apply Q1 | exact (QB_eq _ _ _ _ (proj2 Q2) (eqX_sym _ _ Ex) (eqY_refl _)) | exact K2].
  Qed.
End Compose.

(* A block meeting the interface converges (with K preserved by its steps). *)
Section SettlesConv.
  Variables S Act : Type.
  Variable eqs : S -> S -> Prop.
  Hypothesis eq_refl' : forall x, eqs x x.
  Variable ok : Act -> Prop.
  Variable step : Act -> S -> S.
  Variable K : S -> S -> Prop.
  Hypothesis K_eq : forall x y, eqs x y -> K x y.
  Hypothesis K_sym : forall x y, K x y -> K y x.
  Hypothesis K_trans : forall x y z, K x y -> K y z -> K x z.
  Hypothesis K_step : forall a s, ok a -> K s (step a s).

  Lemma K_run : forall w s, Forall ok w -> K s (run step w s).
  Proof.
    induction w as [| a w IH]; intros s Hw; [apply K_eq, eq_refl' |]. inversion Hw; subst. simpl.
    eapply K_trans; [apply (K_step a s); assumption | apply IH; assumption].
  Qed.

  Theorem settles_conv :
    (forall s, WN eqs ok step s) -> (forall s t, Quiet eqs ok step s -> Quiet eqs ok step t -> K s t -> eqs s t) ->
    Conv eqs ok step.
  Proof.
    intros W U s. split; [apply W |]. intros w1 w2 H1 H2 Q1 Q2. apply U; [exact Q1 | exact Q2 |].
    eapply K_trans; [apply K_sym, K_run, H1 | apply K_run, H2].
  Qed.
End SettlesConv.

(* ----- Part A instances: each conjunct of compose_exact is necessary ----- *)

Definition okT {T : Type} (_ : T) : Prop := True.

Lemma okT_all : forall {T : Type} (l : list T), Forall okT l.
Proof. intros T l. induction l; constructor; [exact I | assumption]. Qed.

Lemma okC_all : forall {AA AB : Type} (l : list (AA + AB)), Forall (okC AA AB okT okT) l.
Proof. intros AA AB l. induction l as [| [a | b] l IH]; constructor; try exact I; exact IH. Qed.

(* A: a flag that rises once. *)
Definition flipA (_ : unit) (x : bool) : bool := true.

Lemma flip_run : forall w x, run flipA w x = match w with [] => x | _ => true end.
Proof.
  intros w x. destruct w as [| a w]; [reflexivity |]. simpl. change (flipA a x) with true.
  clear a x. induction w as [| a w IH]; [reflexivity | exact IH].
Qed.

Lemma flip_conv : Conv (@eq bool) okT flipA.
Proof.
  intros x. split.
  - exists [tt]. split; [apply okT_all |]. intros a _. reflexivity.
  - intros w1 w2 _ _ Q1 Q2. pose proof (Q1 tt I) as A. pose proof (Q2 tt I) as B.
    transitivity true; [exact (eq_sym A) | exact B].
Qed.

(* The sticky block: y takes the input's value (2 or 1) while y = 0, and then keeps it. *)
Definition stickyB (x : bool) (_ : unit) (y : nat) : nat :=
  if Nat.eqb y 0 then (if x then 2 else 1) else y.

Lemma sticky_idem : forall x z, stickyB x tt (stickyB x tt z) = stickyB x tt z.
Proof. intros x z; unfold stickyB; destruct (Nat.eqb z 0) eqn:E; [destruct x; reflexivity | rewrite E; reflexivity]. Qed.

Lemma sticky_run : forall x w y, run (stickyB x) w y = match w with [] => y | _ => stickyB x tt y end.
Proof.
  intros x w y. destruct w as [| [] w]; [reflexivity |]. simpl.
  revert y. induction w as [| [] w IH]; intros z; [reflexivity |].
  simpl. rewrite sticky_idem. apply IH.
Qed.

Lemma sticky_conv : forall x, Conv (@eq nat) okT (stickyB x).
Proof.
  intros x y. split.
  - exists [tt]. split; [apply okT_all |]. intros [] _. apply sticky_idem.
  - intros w1 w2 _ _ Q1 Q2. pose proof (Q1 tt I) as A. pose proof (Q2 tt I) as B.
    rewrite !sticky_run in *. destruct w1, w2; try reflexivity; [exact (eq_sym A) | exact B].
Qed.

Local Notation stickyC := (stepC bool nat unit unit flipA stickyB).

(* Headline counterexample: each block converges in isolation (A from every start, B at every
   fixed input from every start), and the composite does not: B's settled value depends on whether
   it moved before or after A. *)
Theorem compose_isolated_refuted :
  Conv (@eq bool) okT flipA /\ (forall x, Conv (@eq nat) okT (stickyB x)) /\
  run stickyC [inl tt; inr tt] (false, 0) = (true, 2) /\
  run stickyC [inr tt; inl tt] (false, 0) = (true, 1) /\
  ~ Conv (eqC bool nat (@eq bool) (@eq nat)) (okC unit unit okT okT) stickyC.
Proof.
  split; [exact flip_conv |]. split; [exact sticky_conv |]. split; [reflexivity |]. split; [reflexivity |].
  intros H. pose proof (proj2 (H (false, 0)) [inl tt; inr tt] [inr tt; inl tt] (okC_all _) (okC_all _)) as U.
  assert (Q : forall y, y <> 0 -> Quiet (eqC bool nat (@eq bool) (@eq nat)) (okC unit unit okT okT) stickyC (true, y)).
  { intros y Hy [[] | []] _; split; simpl; try reflexivity. unfold stickyB.
    destruct (Nat.eqb_spec y 0); [contradiction | reflexivity]. }
  destruct (U (Q 2 ltac:(discriminate)) (Q 1 ltac:(discriminate))) as [_ E]. discriminate E.
Qed.

(* The A conjunct: A with two normal forms from one start, B trivial. *)
Definition twoA (b : bool) (x : nat) : nat := if Nat.eqb x 0 then (if b then 1 else 2) else x.
Definition idB (_ : nat) (_ : unit) (y : unit) : unit := y.

Theorem compose_needs_A :
  (forall xs, Quiet (@eq nat) okT twoA xs -> WNB nat unit unit (@eq unit) okT idB xs) /\
  (forall xs, Quiet (@eq nat) okT twoA xs -> LkUnique nat unit bool unit (@eq nat) (@eq unit) okT twoA okT idB xs) /\
  ~ Conv (@eq nat) okT twoA /\
  ~ Conv (eqC nat unit (@eq nat) (@eq unit)) (okC bool unit okT okT) (stepC nat unit bool unit twoA idB).
Proof.
  assert (NA : ~ Conv (@eq nat) okT twoA).
  { intros H. pose proof (proj2 (H 0) [true] [false] (okT_all _) (okT_all _)) as U.
    assert (Q : forall x, x <> 0 -> Quiet (@eq nat) okT twoA x).
    { intros x Hx b _. unfold twoA. destruct (Nat.eqb_spec x 0); [contradiction | reflexivity]. }
    specialize (U (Q 1 ltac:(discriminate)) (Q 2 ltac:(discriminate))). discriminate U. }
  split; [intros xs _ y; exists []; split; [constructor | intros [] _; reflexivity] |].
  split; [intros xs _ [] [] _ _ _; reflexivity |].
  split; [exact NA |].
  intros H. apply NA. apply (conv_A nat unit bool unit (@eq nat) (@eq unit) (@eq_refl nat) (@eq_sym nat) (@eq_trans nat)
    (@eq_refl unit) (@eq_sym unit) okT twoA okT idB (fun a x x' H => f_equal _ H)
    (fun b x x' y y' Hx Hy => Hy) tt H).
Qed.

(* The existence conjunct: B never settles at A's normal form. *)
Definition unitA (_ : unit) (x : unit) : unit := x.
Definition incB (_ : unit) (_ : unit) (y : nat) : nat := S y.

Theorem compose_needs_wn :
  Conv (@eq unit) okT unitA /\
  (forall xs, Quiet (@eq unit) okT unitA xs -> LkUnique unit nat unit unit (@eq unit) (@eq nat) okT unitA okT incB xs) /\
  ~ Conv (eqC unit nat (@eq unit) (@eq nat)) (okC unit unit okT okT) (stepC unit nat unit unit unitA incB).
Proof.
  split.
  { intros [] . split; [exists []; split; [constructor | intros [] _; reflexivity] |].
    intros w1 w2 _ _ _ _. destruct (run unitA w1 tt), (run unitA w2 tt). reflexivity. }
  split; [intros xs _ y1 y2 Q _ _; pose proof (Q tt I) as A; unfold incB in A; lia |].
  intros H. destruct (proj1 (H (tt, 0))) as [w [_ Q]].
  destruct (run (stepC unit nat unit unit unitA incB) w (tt, 0)) as [x y].
  destruct (Q (inr tt) I) as [_ E]. simpl in E. unfold incB in E. lia.
Qed.

(* B is constrained only at A's normal forms: at the transient input false it never settles. *)
Definition transB (x : bool) (_ : unit) (y : nat) : nat := if x then 0 else S y.

Theorem compose_transient_free :
  ~ WN (@eq nat) okT (transB false) 0 /\
  Conv (eqC bool nat (@eq bool) (@eq nat)) (okC unit unit okT okT) (stepC bool nat unit unit flipA transB).
Proof.
  split.
  { intros [w [_ Q]]. pose proof (Q tt I) as A. unfold transB in A. lia. }
  apply (compose_exact bool nat unit unit (@eq bool) (@eq nat) (@eq_refl bool) (@eq_sym bool) (@eq_trans bool)
           (@eq_refl nat) (@eq_sym nat) (@eq_trans nat) okT flipA okT transB
           (fun a x x' H => f_equal _ H) (fun b x x' y y' Hx Hy => ltac:(subst; reflexivity)) 0).
  split; [exact flip_conv |]. split.
  - intros xs Qs y. pose proof (Qs tt I) as A. unfold flipA in A. subst xs.
    exists [tt]. split; [apply okT_all |]. intros [] _. reflexivity.
  - intros xs Qs y1 y2 Q1 Q2 _. pose proof (Qs tt I) as A. unfold flipA in A. subst xs.
    pose proof (Q1 tt I) as B1. pose proof (Q2 tt I) as B2. unfold transB in B1, B2. congruence.
Qed.

