(* ----- rootless invertible networks (RootlessNetworks.v) as a block ----- *)

Section RootlessBlock.
  Context {G : Type}.
  Variable op : G -> G -> G.
  Variable es : list (@edge G).

  Definition rok (x : @edge G) : Prop := In x es.
  Definition rstep (x : @edge G) (t : nat -> G) : nat -> G := fire1 op t x.

  Lemma rrun_fire : forall w t, run rstep w t = fire op w t.
  Proof. reflexivity. Qed.

  Lemma rok_incl : forall w, Forall rok w <-> incl w es.
  Proof. intros w. unfold rok, incl. rewrite Forall_forall. tauto. Qed.

  Lemma rquiet_iff : forall t, Quiet (@peq G) rok rstep t <-> is_section op t es.
  Proof.
    intros t. split.
    - intros H [[u v] g] Hin. pose proof (H _ Hin v) as A. unfold rstep in A. simpl in A.
      destruct (Nat.eq_dec v v) as [_ | N]; [exact A | contradiction].
    - intros H [[u v] g] Hin k. pose proof (H _ Hin) as A. simpl in A. unfold rstep. simpl.
      destruct (Nat.eq_dec k v) as [-> | _]; [exact A | reflexivity].
  Qed.

  (* Conv for the rootless block is exactly the left side of net_unique_normal_form_iff. *)
  Lemma rootless_conv_lhs :
    Conv (@peq G) rok rstep <->
    (forall t0, exists p,
        incl p es /\ incl es p /\ is_section op (fire op p t0) es /\
        (forall q, incl q es -> is_section op (fire op q t0) es -> peq (fire op q t0) (fire op p t0))).
  Proof.
    split.
    - intros H t0. destruct (proj1 (H t0)) as [p [Hp Qp]].
      apply rok_incl in Hp. apply rquiet_iff in Qp. rewrite rrun_fire in Qp.
      destruct (extend_fair op es p t0 Hp Qp) as [A [B [C D]]].
      exists (p ++ es). split; [exact A | split; [exact B | split; [exact D |]]].
      intros q Hq Sq k. rewrite C.
      apply (proj2 (H t0) q p); [apply rok_incl; exact Hq | apply rok_incl; exact Hp | | ];
        apply rquiet_iff; rewrite rrun_fire; assumption.
    - intros H t0. destruct (H t0) as [p [Hp [_ [Sp U]]]]. split.
      + exists p. split; [apply rok_incl; exact Hp | apply rquiet_iff; exact Sp].
      + intros w1 w2 H1 H2 Q1 Q2 k. apply rquiet_iff in Q1. apply rquiet_iff in Q2.
        rewrite !rrun_fire in *. rewrite (U w1 (proj1 (rok_incl w1) H1) Q1 k), (U w2 (proj1 (rok_incl w2) H2) Q2 k).
        reflexivity.
  Qed.

  Variables (e : G) (inv : G -> G).
  Hypothesis assoc : forall a b c, op a (op b c) = op (op a b) c.
  Hypothesis id_l  : forall a, op e a = a.
  Hypothesis id_r  : forall a, op a e = a.
  Hypothesis inv_r : forall a, op a (inv a) = e.
  Hypothesis inv_l : forall a, op (inv a) a = e.

  (* The rootless engine's exact condition, as the A-conjunct of compose_exact. *)
  Theorem rootless_conv_iff :
    Conv (@peq G) rok rstep <-> has_section op es /\ (authority_cover es \/ @trivial_group G).
  Proof.
    rewrite rootless_conv_lhs. exact (net_unique_normal_form_iff op e inv assoc id_l id_r inv_r inv_l es).
  Qed.

  (* A rootless block feeding any block B. *)
  Variables (Y AB : Type) (eqY : Y -> Y -> Prop).
  Hypothesis eqY_refl : forall x, eqY x x.
  Hypothesis eqY_sym : forall x y, eqY x y -> eqY y x.
  Hypothesis eqY_trans : forall x y z, eqY x y -> eqY y z -> eqY x z.
  Variable okB : AB -> Prop.
  Variable stepB : (nat -> G) -> AB -> Y -> Y.
  Hypothesis stepB_ext : forall b x x' y y', peq x x' -> eqY y y' -> eqY (stepB x b y) (stepB x' b y').
  Variable y_inh : Y.

  Lemma peq_refl' : forall t : nat -> G, peq t t. Proof. intros t k. reflexivity. Qed.
  Lemma peq_sym' : forall s t : nat -> G, peq s t -> peq t s. Proof. intros s t H k. symmetry. apply H. Qed.
  Lemma peq_trans' : forall s t u : nat -> G, peq s t -> peq t u -> peq s u.
  Proof. intros s t u H1 H2 k. rewrite H1. apply H2. Qed.

  Theorem mixed_rootless_exact :
    Conv (eqC (nat -> G) Y (@peq G) eqY) (okC (@edge G) AB rok okB) (stepC (nat -> G) Y (@edge G) AB rstep stepB) <->
    (has_section op es /\ (authority_cover es \/ @trivial_group G)) /\
    (forall xs, is_section op xs es -> WNB (nat -> G) Y AB eqY okB stepB xs) /\
    (forall xs, is_section op xs es ->
       LkUnique (nat -> G) Y (@edge G) AB (@peq G) eqY rok rstep okB stepB xs).
  Proof.
    rewrite (compose_exact (nat -> G) Y (@edge G) AB (@peq G) eqY peq_refl' peq_sym' peq_trans'
               eqY_refl eqY_sym eqY_trans rok rstep okB stepB (fun x s t H => fire1_ext op x s t H)
               stepB_ext y_inh).
    rewrite rootless_conv_iff. split.
    - intros [A [B C]]. split; [exact A |].
      split; intros xs Hs; [apply B | apply C]; apply rquiet_iff; exact Hs.
    - intros [A [B C]]. split; [exact A |].
      split; intros xs Hs; [apply B | apply C]; apply rquiet_iff; exact Hs.
  Qed.
End RootlessBlock.

(* Non-vacuity: the network of rootless_source_feeds_cycle (registry 0 feeds the coherently
   oriented 2-cycle 1 <-> 2, over Z/2, with |G| = 2) feeding a block that reads registry 2. *)
Definition copy2 (x : nat -> bool) (_ : unit) (_ : bool) : bool := x 2.

Theorem mixed_instance :
  Conv (@peq bool) (rok sfc) (rstep xorb) /\
  Conv (eqC (nat -> bool) bool (@peq bool) (@eq bool)) (okC (@edge bool) unit (rok sfc) okT)
       (stepC (nat -> bool) bool (@edge bool) unit (rstep xorb) copy2).
Proof.
  assert (HA : Conv (@peq bool) (rok sfc) (rstep xorb)).
  { apply rootless_conv_lhs. destruct rootless_source_feeds_cycle as [_ [_ [_ [_ H]]]]. exact H. }
  split; [exact HA |].
  apply (compose_exact (nat -> bool) bool (@edge bool) unit (@peq bool) (@eq bool) peq_refl' peq_sym'
           peq_trans' (@eq_refl bool) (@eq_sym bool) (@eq_trans bool) (rok sfc) (rstep xorb) okT copy2
           (fun x s t H => fire1_ext xorb x s t H) (fun b x x' y y' Hx _ => Hx 2) false).
  split; [exact HA |]. split.
  - intros xs _ y. exists [tt]. split; [apply okT_all | intros [] _; reflexivity].
  - intros xs _ y1 y2 Q1 Q2 _. pose proof (Q1 tt I) as A. pose proof (Q2 tt I) as B.
    unfold copy2 in A, B. congruence.
Qed.

(* ----- monotone cycles (DistributedCycles.v) as a block ----- *)

Section MonoBlock.
  Variables Loc Sh : Type.
  Variable le : Sh -> Sh -> Prop.
  Hypothesis le_refl : forall x, le x x.
  Hypothesis le_trans : forall x y z, le x y -> le y z -> le x z.
  Hypothesis le_antisym : forall x y, le x y -> le y x -> x = y.
  Variable bot : Sh.
  Hypothesis bot_least : forall x, le bot x.
  Variable rank : Sh -> nat.
  Hypothesis rank_strict : forall x y, le x y -> x <> y -> rank x < rank y.
  Variable height : nat.
  Hypothesis rank_bound : forall x, rank x <= height.
  Variable sh_eq_dec : forall x y : Sh, {x = y} + {x <> y}.
  Variable F : Loc -> Sh -> Sh.
  Variable u : Loc -> nat -> Sh -> Sh.
  Hypothesis u_incr : forall l j x, sound Loc Sh le F l x -> le x (u l j x).
  Hypothesis u_sound : forall l j x, sound Loc Sh le F l x -> sound Loc Sh le F l (u l j x).
  Hypothesis u_mono : forall l j x y, le x y -> le (u l j x) (u l j y).
  Hypothesis u_fixed : forall l j x, F l x = x -> u l j x = x.
  Variable K : nat.
  Hypothesis K_big : height < K.
  Variable js : list nat.
  Hypothesis Hcov : Cover Loc Sh F u js.
  Variable top : Sh.
  Hypothesis top_greatest : forall x, le x top.
  Hypothesis u_decr : forall l j x, le (F l x) x -> le (u l j x) x.
  Hypothesis u_cosound : forall l j x, le (F l x) x -> le (F l (u l j x)) (u l j x).
  Variable sg : nat -> nat.
  Hypothesis Hf : Fair js sg.

  Definition mok (j : nat) : Prop := In j js.

  Local Notation LfpM := (Lfp Loc Sh bot sh_eq_dec u K js).

  Lemma prs_run : forall (up : nat -> Sh -> Sh) n h, prs Sh up sg n h = run up (map sg (seq 0 n)) h.
  Proof.
    intros up n. induction n as [| n IH]; intros h; [reflexivity |].
    rewrite seq_S, map_app, run_app. simpl. rewrite IH. reflexivity.
  Qed.

  Lemma sg_ok : forall n, Forall mok (map sg (seq 0 n)).
  Proof. intros n. apply Forall_forall. intros j Hj. apply in_map_iff in Hj. destruct Hj as [m [<- _]]. apply Hf. Qed.

  Lemma mquiet_iff : forall l h, Quiet (@eq Sh) mok (u l) h <-> F l h = h.
  Proof.
    intros l h. rewrite <- (qstable_iff Loc Sh F u u_fixed js Hcov l h). unfold QStable, Stable, Quiet, mok. tauto.
  Qed.

  (* The monotone engine meets the black-box interface with K = every state (its normal form a
     function of its locals alone) exactly when its repair has one fixed point. *)
  Theorem mono_block_interface_iff : forall l,
    ((forall h, WN (@eq Sh) mok (u l) h) /\
     (forall h1 h2, Quiet (@eq Sh) mok (u l) h1 -> Quiet (@eq Sh) mok (u l) h2 -> h1 = h2)) <->
    (forall p, F l p = p -> p = LfpM l).
  Proof.
    intros l. split.
    - intros [_ U] p Hp. apply U; apply mquiet_iff; [exact Hp |].
      exact (Lfp_fixed Loc Sh le le_refl le_trans bot bot_least rank rank_strict height rank_bound
               sh_eq_dec F u u_incr u_sound u_mono u_fixed K K_big js Hcov l).
    - intros Hu.
      pose proof (proj2 (q1_unique_iff Loc Sh le le_refl le_trans le_antisym bot bot_least rank rank_strict
                          height rank_bound sh_eq_dec F u u_incr u_sound u_mono u_fixed K K_big js Hcov top
                          top_greatest u_decr u_cosound l sg Hf) Hu) as HS.
      split.
      + intros h. destruct (HS h) as [N HN]. exists (map sg (seq 0 N)). split; [apply sg_ok |].
        rewrite <- prs_run, (HN N (le_n N)). apply mquiet_iff.
        exact (Lfp_fixed Loc Sh le le_refl le_trans bot bot_least rank rank_strict height rank_bound
                 sh_eq_dec F u u_incr u_sound u_mono u_fixed K K_big js Hcov l).
      + intros h1 h2 Q1 Q2. apply mquiet_iff in Q1. apply mquiet_iff in Q2.
        rewrite (Hu _ Q1), (Hu _ Q2). reflexivity.
  Qed.

  (* A monotone block fed by any upstream system A: its locals are read from A's state
     (loc x). With one fixed point at every quiet input of A, its two conjuncts of compose_exact
     hold, so the composite converges iff A does. *)
  Variables (X AA : Type) (eqX : X -> X -> Prop).
  Hypothesis eqX_refl : forall x, eqX x x.
  Hypothesis eqX_sym : forall x y, eqX x y -> eqX y x.
  Hypothesis eqX_trans : forall x y z, eqX x y -> eqX y z -> eqX x z.
  Variable okA : AA -> Prop.
  Variable stepA : AA -> X -> X.
  Hypothesis stepA_ext : forall a x x', eqX x x' -> eqX (stepA a x) (stepA a x').
  Variable loc : X -> Loc.
  Hypothesis loc_ext : forall x x', eqX x x' -> loc x = loc x'.

  Definition mstep (x : X) (j : nat) (h : Sh) : Sh := u (loc x) j h.

  Theorem mixed_mono_iff :
    (forall xs, Quiet eqX okA stepA xs -> forall p, F (loc xs) p = p -> p = LfpM (loc xs)) ->
    (Conv (eqC X Sh eqX (@eq Sh)) (okC AA nat okA mok) (stepC X Sh AA nat stepA mstep) <->
     Conv eqX okA stepA).
  Proof.
    intros Hu.
    rewrite (compose_exact X Sh AA nat eqX (@eq Sh) eqX_refl eqX_sym eqX_trans (@eq_refl Sh) (@eq_sym Sh)
               (@eq_trans Sh) okA stepA mok mstep stepA_ext
               (fun b x x' y y' Hx Hy => ltac:(subst y'; unfold mstep; rewrite (loc_ext x x' Hx); reflexivity)) bot).
    split; [intros [H _]; exact H |]. intros HA. split; [exact HA |].
    split; intros xs Qs; destruct (proj2 (mono_block_interface_iff (loc xs)) (Hu xs Qs)) as [W U].
    - exact W.
    - intros y1 y2 Q1 Q2 _. exact (U y1 y2 Q1 Q2).
  Qed.
End MonoBlock.

(* Instances on the two-flag lattice B2 of FederationEventsCycles.v. *)
Ltac bfc := repeat match goal with
  | x : B2 |- _ => destruct x
  | x : bool * bool |- _ => destruct x
  | b : bool |- _ => destruct b
  end.

(* A monotone 2-cycle with one fixed point at every local: sa := l && sb, sb := l || sa. *)
Definition aF (l : bool) (x : B2) : B2 := (l && snd x, l || fst x).
Definition au (l : bool) (j : nat) (x : B2) : B2 :=
  match j with 0 => (fst (aF l x), snd x) | 1 => (fst x, snd (aF l x)) | _ => x end.

Lemma au_incr : forall l j x, sound bool B2 cle aF l x -> cle x (au l j x).
Proof. intros l [| [| j]] x; bfc; unfold sound, cle, au, aF; simpl; intuition. Qed.
Lemma au_sound : forall l j x, sound bool B2 cle aF l x -> sound bool B2 cle aF l (au l j x).
Proof. intros l [| [| j]] x; bfc; unfold sound, cle, au, aF; simpl; intuition. Qed.
Lemma au_mono : forall l j x y, cle x y -> cle (au l j x) (au l j y).
Proof. intros l [| [| j]] x y; bfc; unfold cle, au, aF; simpl; intuition. Qed.
Lemma au_fixed : forall l j x, aF l x = x -> au l j x = x.
Proof. intros l [| [| j]] x; bfc; unfold au, aF; simpl; intro H; congruence. Qed.
Lemma au_cover : Cover bool B2 aF au cts.
Proof.
  intros l x H. pose proof (H 0 (or_introl eq_refl)) as H0. pose proof (H 1 (or_intror (or_introl eq_refl))) as H1.
  revert H0 H1. bfc; unfold au, aF; simpl; intros H0 H1; congruence.
Qed.
Lemma ctop : forall x, cle x (true, true). Proof. intros; bfc; split; reflexivity. Qed.
Lemma au_decr : forall l j x, cle (aF l x) x -> cle (au l j x) x.
Proof. intros l [| [| j]] x; bfc; unfold cle, au, aF; simpl; intuition. Qed.
Lemma au_cosound : forall l j x, cle (aF l x) x -> cle (aF l (au l j x)) (au l j x).
Proof. intros l [| [| j]] x; bfc; unfold cle, au, aF; simpl; intuition. Qed.
Lemma aF_unique : forall l p, aF l p = p -> p = Lfp bool B2 cbot ceq_dec au 3 cts l.
Proof. intros l p; bfc; unfold aF; simpl; intro H; try discriminate H; vm_compute; reflexivity. Qed.

(* The alternating schedule 0, 1, 0, 1, ... is fair for cts. *)
Fixpoint par (n : nat) : nat := match n with 0 => 0 | 1 => 1 | S (S k) => par k end.

Lemma par_add : forall n j, par (2 * n + j) = par j.
Proof. induction n as [| n IH]; intros j; [reflexivity |]. replace (2 * S n + j) with (S (S (2 * n + j))) by lia. apply IH. Qed.

Lemma par_fair : Fair cts par.
Proof.
  split.
  - intros n. induction n as [n IH] using (well_founded_induction lt_wf).
    destruct n as [| [| n]]; [left; reflexivity | right; left; reflexivity |]. exact (IH n ltac:(lia)).
  - intros j n Hj. exists (2 * n + j). split; [lia |]. rewrite par_add.
    destruct Hj as [<- | [<- | []]]; reflexivity.
Qed.

(* Rootless block feeding a monotone cycle: the rootless network of rootless_source_feeds_cycle,
   registry 2 read as the cycle's local; the cycle has one fixed point at every local, so the
   composite converges (mixed_mono_iff with the rootless engine's exact condition). *)
Definition loc2 (x : nat -> bool) : bool := x 2.

Theorem mixed_mono_instance :
  (forall l p, aF l p = p -> p = Lfp bool B2 cbot ceq_dec au 3 cts l) /\
  Conv (eqC (nat -> bool) B2 (@peq bool) (@eq B2)) (okC (@edge bool) nat (rok sfc) (mok cts))
       (stepC (nat -> bool) B2 (@edge bool) nat (rstep xorb) (mstep bool B2 au (nat -> bool) loc2)).
Proof.
  split; [exact aF_unique |].
  apply (mixed_mono_iff bool B2 cle cle_refl cle_trans cle_antisym cbot cbot_least crank crank_strict 2
           crank_bound ceq_dec aF au au_incr au_sound au_mono au_fixed 3 ltac:(lia) cts au_cover (true, true)
           ctop au_decr au_cosound par par_fair (nat -> bool) (@edge bool) (@peq bool) peq_refl' peq_sym'
           peq_trans' (rok sfc) (rstep xorb) (fun x s t H => fire1_ext xorb x s t H) loc2 (fun x x' H => H 2)).
  - intros xs _ p Hp. apply aF_unique. exact Hp.
  - exact (proj1 mixed_instance).
Qed.

(* The interleaving conjunct with real engines: the same rootless block feeding the flag cycle of
   FederationEventsCycles.v (sa := lb || sb, sb := la || sa), registry 2 read as the alarm la.
   With the alarm clear the cycle has two fixed points (the ghost of bottom_matters); a transient
   alarm, raised while the rootless block is still settling, lifts the cycle to the ghost, and the
   composite reaches two normal forms. *)
Definition flagloc (x : nat -> bool) : B2 := (x 2, false).
Definition gt0 (k : nat) : bool := Nat.eqb k 2.

Local Notation flagC := (stepC (nat -> bool) B2 (@edge bool) nat (rstep xorb) (mstep B2 B2 cu (nat -> bool) flagloc)).

Theorem mixed_ghost_refuted :
  Conv (@peq bool) (rok sfc) (rstep xorb) /\
  cF (false, false) (true, true) = (true, true) /\ cF (false, false) (false, false) = (false, false) /\
  ~ Conv (eqC (nat -> bool) B2 (@peq bool) (@eq B2)) (okC (@edge bool) nat (rok sfc) (mok cts)) flagC.
Proof.
  split; [exact (proj1 mixed_instance) |]. split; [reflexivity |]. split; [reflexivity |].
  intros H.
  set (w1 := [inr 1; inr 0; inl (1, 2, false)] : list (@edge bool + nat)).
  set (w2 := [inl (1, 2, false)] : list (@edge bool + nat)).
  assert (O1 : Forall (okC (@edge bool) nat (rok sfc) (mok cts)) w1).
  { repeat constructor; simpl; unfold mok, rok, cts, sfc; simpl; tauto. }
  assert (O2 : Forall (okC (@edge bool) nat (rok sfc) (mok cts)) w2).
  { repeat constructor; simpl; unfold rok, sfc; simpl; tauto. }
  assert (Qx : forall p, (forall k, fst p k = false) -> snd p = (true, true) \/ snd p = (false, false) ->
             Quiet (eqC (nat -> bool) B2 (@peq bool) (@eq B2)) (okC (@edge bool) nat (rok sfc) (mok cts)) flagC p).
  { intros [x y] Hx Hy. simpl in Hx, Hy.
    apply (proj2 (QC_iff (nat -> bool) B2 (@edge bool) nat (@peq bool) (@eq B2) peq_refl' peq_sym'
                    (@eq_refl B2) (@eq_sym B2) (rok sfc) (rstep xorb) (mok cts)
                    (mstep B2 B2 cu (nat -> bool) flagloc) x y)). split.
    - apply (proj2 (rquiet_iff xorb sfc x)). intros [[u v] g] Hin. simpl in Hin. unfold sat.
      destruct Hin as [E | [E | [E | []]]]; injection E as <- <- <-; rewrite !Hx; reflexivity.
    - intros j Hj. unfold mstep, flagloc. rewrite Hx. destruct Hj as [<- | [<- | []]];
        destruct Hy as [-> | ->]; reflexivity. }
  pose proof (proj2 (H (gt0, (false, false))) w1 w2 O1 O2) as U.
  assert (R1 : snd (run flagC w1 (gt0, (false, false))) = (true, true)) by reflexivity.
  assert (R2 : snd (run flagC w2 (gt0, (false, false))) = (false, false)) by reflexivity.
  assert (F1 : forall k, fst (run flagC w1 (gt0, (false, false))) k = false).
  { intros [| [| [| k]]]; reflexivity. }
  assert (F2 : forall k, fst (run flagC w2 (gt0, (false, false))) k = false).
  { intros [| [| [| k]]]; reflexivity. }
  destruct (U (Qx _ F1 (or_introl R1)) (Qx _ F2 (or_intror R2))) as [_ E].
  rewrite R1, R2 in E. discriminate E.
Qed.

