Section DistAtoms.
  Variable V : Type.
  Variable src : nat -> list nat.
  Variable f : nat -> (nat -> V) -> V -> V.
  Variable valid : nat -> V -> Prop.
  Variable rho : nat -> V -> V.
  Variable E : Type.
  Variable reg : E -> nat.
  Variable sig : E -> V -> V.
  Variable I : E -> E -> Prop.
  Variable o : list nat.
  Hypothesis HC : Common V src f valid rho E reg sig o.

  Local Notation feqF := (feq V).
  Local Notation InvF := (Inv V valid).
  Local Notation nF := (N V f rho o).
  Local Notation frF := (frun V f).
  Local Notation rF := (runF V f rho E reg sig o).
  Local Notation aF := (applyF V f rho E reg sig o).
  Local Notation evF := (evstep V E reg sig).
  Local Notation dF := (drun V f E reg sig).
  Local Notation DE := (DEv E).
  Local Notation DP := (DProp E).
  Local Notation evsF := (evs E).
  Local Notation IfedF := (Ifed E reg I).
  Local Notation XUatF := (XUat V f rho E reg sig o).

  Lemma dA_app : forall p q t, dF (p ++ q) t = dF q (dF p t).
  Proof. induction p as [| a p IH]; intros q t; [reflexivity |]. simpl. apply IH. Qed.

  Lemma dA_props : forall l t, dF (map DP l) t = frF l t.
  Proof. induction l as [| a l IH]; intros t; [reflexivity |]. simpl. rewrite IH. reflexivity. Qed.

  Lemma evsA_app : forall p q, evsF (p ++ q) = evsF p ++ evsF q.
  Proof. induction p as [| a p IH]; intros q; [reflexivity |]. destruct a; simpl; rewrite IH; reflexivity. Qed.

  Lemma evsA_props : forall l, evsF (map DP l) = [].
  Proof. induction l as [| a l IH]; [reflexivity | exact IH]. Qed.

  Lemma props_flush : forall l t, InvF t -> incl l o -> feqF (nF (frF l t)) (nF t).
  Proof.
    induction l as [| a l IH]; intros t Ht Hl; [intro k; reflexivity |].
    change (frF (a :: l) t) with (frF l (fstep V f t a)).
    eapply feq_trans; [apply IH; [apply (fstep_inv _ _ _ _ _ _ _ _ _ HC); exact Ht | intros x Hx; apply Hl; right; exact Hx] |].
    apply (flush_prop _ _ _ _ _ _ _ _ _ HC); [exact Ht | apply Hl; left; reflexivity].
  Qed.

  (* ----- an atom set: every event, propagation words, and a flush ----- *)
  Variable At : list (act E) -> Prop.
  Hypothesis at_ev : forall e, At [DE e].
  Hypothesis at_shape : forall a, At a -> (exists e, a = [DE e]) \/ (exists l, a = map DP l /\ incl l o).
  Variable fl : list (list (act E)).
  Hypothesis fl_ok : Forall At fl.
  Variable lf : list nat.
  Hypothesis fl_word : concat fl = map DP lf.
  Hypothesis fl_flush : forall t, InvF t -> feqF (frF lf t) (frF o t).

  (* Convergence over the atom words, compared after the final flush, and XU at the states they
     reach. *)
  Definition DistConvA (s0 : nat -> V) : Prop :=
    forall ws1 ws2, Forall At ws1 -> Forall At ws2 -> tequiv IfedF (evsF (concat ws1)) (evsF (concat ws2)) ->
      feqF (nF (dF (concat ws1) s0)) (nF (dF (concat ws2) s0)).

  Definition XURA (s0 : nat -> V) : Prop :=
    forall ws e, Forall At ws -> XUatF (dF (concat ws) s0) e.

  Lemma flushA : forall s0, InvF s0 -> XURA s0 -> forall ws q, Forall At q -> Forall At ws ->
    feqF (nF (dF (concat ws) (dF (concat q) s0))) (rF (evsF (concat ws)) (nF (dF (concat q) s0))).
  Proof.
    intros s0 Hi Hx ws. induction ws as [| a ws IH]; intros q Hq Hw; [intro k; reflexivity |].
    inversion Hw as [| ? ? Ha Hw']; subst.
    assert (Hqa : Forall At (q ++ [a])) by (apply Forall_app; split; [exact Hq | constructor; [exact Ha | constructor]]).
    set (t := dF (concat q) s0).
    assert (It : InvF t) by (apply (drun_inv _ _ _ _ _ _ _ _ _ HC); exact Hi).
    assert (Ea : dF a t = dF (concat (q ++ [a])) s0) by (rewrite concat_app, dA_app; simpl; rewrite app_nil_r; reflexivity).
    simpl. rewrite dA_app, Ea.
    eapply feq_trans; [exact (IH (q ++ [a]) Hqa Hw') |]. rewrite <- Ea.
    rewrite evsA_app. destruct (at_shape a Ha) as [[e ->] | [l [-> Hl]]].
    - simpl. apply (runF_ext _ _ _ _ _ _ _ _ _ HC). apply (flush_ev_at _ _ _ _ _ _ _ _ _ HC); [exact It |].
      apply Hx. exact Hq.
    - rewrite evsA_props. simpl. apply (runF_ext _ _ _ _ _ _ _ _ _ HC). rewrite dA_props.
      apply props_flush; assumption.
  Qed.

  Lemma flushA0 : forall s0, InvF s0 -> XURA s0 -> forall ws, Forall At ws ->
    feqF (nF (dF (concat ws) s0)) (rF (evsF (concat ws)) (nF s0)).
  Proof. intros s0 Hi Hx ws Hw. exact (flushA s0 Hi Hx ws [] (Forall_nil _) Hw). Qed.

  Definition evatoms (es : list E) : list (list (act E)) := map (fun e => [DE e]) es.

  Lemma evatoms_ok : forall es, Forall At (evatoms es).
  Proof. induction es as [| e es IH]; constructor; [apply at_ev | exact IH]. Qed.

  Lemma evatoms_concat : forall es, concat (evatoms es) = map DE es.
  Proof. induction es as [| e es IH]; [reflexivity | simpl; rewrite IH; reflexivity]. Qed.

  Lemma evs_map : forall es, evsF (map DE es) = es.
  Proof. induction es as [| e es IH]; [reflexivity | simpl; rewrite IH; reflexivity]. Qed.

  (* The flush word, from a reachable state, lands on the flushed state. *)
  Lemma fl_lands : forall t, InvF t -> feqF (dF (concat fl) t) (nF t).
  Proof.
    intros t Ht. rewrite fl_word, dA_props. eapply feq_trans; [exact (fl_flush t Ht) |].
    apply feq_sym. exact (N_frun _ _ _ _ _ _ _ _ _ HC t Ht).
  Qed.

  Lemma xura_nec : forall s0, InvF s0 -> DistConvA s0 -> XURA s0.
  Proof.
    intros s0 Hi Hd ws e Hw. unfold XUat.
    set (t := dF (concat ws) s0).
    assert (It : InvF t) by (apply (drun_inv _ _ _ _ _ _ _ _ _ HC); exact Hi).
    assert (O1 : Forall At (ws ++ [[DE e]])) by (apply Forall_app; split; [exact Hw | repeat constructor; apply at_ev]).
    assert (O2 : Forall At (ws ++ fl ++ [[DE e]]))
      by (apply Forall_app; split; [exact Hw | apply Forall_app; split; [exact fl_ok | repeat constructor; apply at_ev]]).
    assert (Ev : evsF (concat (ws ++ [[DE e]])) = evsF (concat (ws ++ fl ++ [[DE e]]))).
    { rewrite !concat_app, !evsA_app, fl_word, evsA_props. reflexivity. }
    pose proof (Hd _ _ O1 O2 (eq_rect _ (fun l => tequiv IfedF (evsF (concat (ws ++ [[DE e]]))) l)
                                (teq_refl IfedF _) _ Ev) (reg e)) as H.
    rewrite !concat_app, !dA_app in H. simpl in H. rewrite ?app_nil_r in H. fold t in H.
    change (dF [DE e] t) with (evF e t) in H.
    set (u := dF (concat fl) t) in H.
    change (dF [DE e] u) with (evF e u) in H.
    assert (Hu : feqF u (nF t)) by (apply fl_lands; exact It).
    assert (Iu : InvF u) by (apply (drun_inv _ _ _ _ _ _ _ _ _ HC); exact It).
    assert (In_ : InvF (nF t)) by (apply (N_inv _ _ _ _ _ _ _ _ _ HC); exact It).
    assert (Nn : feqF (nF u) (nF t)).
    { eapply feq_trans; [apply (N_ext _ _ _ _ _ _ _ _ _ HC); exact Hu |].
      apply (N_self _ _ _ _ _ _ _ _ _ HC); [exact In_ | apply (N_cons _ _ _ _ _ _ _ _ _ HC); exact It]. }
    rewrite (N_ev_at _ _ _ _ _ _ _ _ _ HC e t It), (N_ev_at _ _ _ _ _ _ _ _ _ HC e u Iu) in H.
    rewrite (f_ext _ _ _ _ _ _ _ _ _ HC (reg e) _ _ _ Nn), (Hu (reg e)) in H.
    rewrite (N_at _ _ _ _ _ _ _ _ _ HC t (reg e) It (c_reg _ _ _ _ _ _ _ _ _ HC e)) in H.
    symmetry. exact H.
  Qed.

  Lemma tc_nec : forall s0, InvF s0 -> DistConvA s0 -> XURA s0 -> TraceConv V f rho E reg sig I o (nF s0).
  Proof.
    intros s0 Hi Hd Hx es1 es2 H.
    pose proof (flushA0 s0 Hi Hx _ (evatoms_ok es1)) as A1.
    pose proof (flushA0 s0 Hi Hx _ (evatoms_ok es2)) as A2.
    rewrite evatoms_concat, evs_map in A1, A2.
    assert (Ht : tequiv IfedF (evsF (concat (evatoms es1))) (evsF (concat (evatoms es2))))
      by (rewrite !evatoms_concat, !evs_map; exact H).
    pose proof (Hd _ _ (evatoms_ok es1) (evatoms_ok es2) Ht) as D. rewrite !evatoms_concat in D.
    eapply feq_trans; [apply feq_sym; exact A1 |]. eapply feq_trans; [exact D | exact A2].
  Qed.

  Lemma xura_c1r1 : forall s0, InvF s0 -> XURA s0 -> C1R1 V f rho E reg sig o (nF s0).
  Proof.
    intros s0 Hi Hx q e a Ne. unfold C1at.
    set (s := rF q (nF s0)).
    set (ws := evatoms q ++ fl).
    assert (Hws : Forall At ws) by (apply Forall_app; split; [apply evatoms_ok | exact fl_ok]).
    set (u := dF (concat ws) s0).
    assert (Hu : feqF u s).
    { unfold u, ws. rewrite concat_app, dA_app, evatoms_concat.
      assert (Iq : InvF (dF (map DE q) s0)) by (apply (drun_inv _ _ _ _ _ _ _ _ _ HC); exact Hi).
      eapply feq_trans; [apply fl_lands; exact Iq |].
      pose proof (flushA0 s0 Hi Hx _ (evatoms_ok q)) as A. rewrite evatoms_concat, evs_map in A. exact A. }
    pose proof (Hx (ws ++ [[DE a]]) e ltac:(apply Forall_app; split; [exact Hws | repeat constructor; apply at_ev])) as X.
    rewrite concat_app, dA_app in X. simpl in X. rewrite ?app_nil_r in X. fold u in X.
    change (dF [DE a] u) with (evF a u) in X. unfold XUat in X.
    assert (Na : feqF (nF (evF a u)) (aF a s)).
    { unfold applyF. apply (N_ext _ _ _ _ _ _ _ _ _ HC). apply (evstep_ext V E reg sig). exact Hu. }
    rewrite !(f_ext _ _ _ _ _ _ _ _ _ HC (reg e) _ _ _ Na) in X.
    rewrite (evstep_off V E reg sig a u (reg e) (fun H => Ne (eq_sym H))) in X.
    rewrite (Hu (reg e)) in X. exact X.
  Qed.

  (* Headline (b), generic form: over any atom set with every event and a flush, convergence is
     reachable XU over its words plus the FedMachine's C2 at states reachable from the flushed
     start. *)
  Theorem dist_atoms_exact : forall s0, InvF s0 ->
    (DistConvA s0 <-> XURA s0 /\ C2R V f rho E reg sig I o (nF s0)).
  Proof.
    intros s0 Hi.
    assert (In_ : InvF (nF s0)) by (apply (N_inv _ _ _ _ _ _ _ _ _ HC); exact Hi).
    assert (Cn : Cons V f o (nF s0)) by (apply (N_cons _ _ _ _ _ _ _ _ _ HC); exact Hi).
    split.
    - intros Hd. assert (Hx : XURA s0) by (apply xura_nec; assumption).
      split; [exact Hx |].
      exact (proj2 (proj1 (fed_exact _ _ _ _ _ _ _ _ _ _ HC (nF s0) In_ Cn) (tc_nec s0 Hi Hd Hx))).
    - intros [Hx H2] ws1 ws2 H1 H2' Hq.
      assert (Ht : TraceConv V f rho E reg sig I o (nF s0)).
      { apply (proj2 (fed_exact _ _ _ _ _ _ _ _ _ _ HC (nF s0) In_ Cn)). split; [apply xura_c1r1; assumption | exact H2]. }
      eapply feq_trans; [exact (flushA0 s0 Hi Hx ws1 H1) |].
      eapply feq_trans; [exact (Ht _ _ Hq) | apply feq_sym; exact (flushA0 s0 Hi Hx ws2 H2')].
  Qed.
End DistAtoms.

(* dist_exact recovered: N's own words are the singleton atoms. *)
Section DistRecovered.
  Variable V : Type.
  Variable src : nat -> list nat.
  Variable f : nat -> (nat -> V) -> V -> V.
  Variable valid : nat -> V -> Prop.
  Variable rho : nat -> V -> V.
  Variable E : Type.
  Variable reg : E -> nat.
  Variable sig : E -> V -> V.
  Variable I : E -> E -> Prop.
  Variable o : list nat.
  Hypothesis HC : Common V src f valid rho E reg sig o.

  Definition At1 (a : list (act E)) : Prop := exists x, a = [x] /\ okact E o x.

  Lemma single_concat : forall w : list (act E), concat (map (fun x => [x]) w) = w.
  Proof. induction w as [| x w IH]; [reflexivity | simpl; rewrite IH; reflexivity]. Qed.

  Lemma single_ok : forall w, Forall (okact E o) w -> Forall At1 (map (fun x => [x]) w).
  Proof.
    induction w as [| x w IH]; intros H; [constructor |]. inversion H; subst.
    constructor; [exists x; split; [reflexivity | assumption] | apply IH; assumption].
  Qed.

  Lemma At1_ok : forall ws, Forall At1 ws -> Forall (okact E o) (concat ws).
  Proof.
    induction ws as [| a ws IH]; intros H; [constructor |]. inversion H as [| ? ? [x [-> Hx]] Hw]; subst.
    simpl. constructor; [exact Hx | apply IH; exact Hw].
  Qed.

  Theorem dist_exact_recovered : forall s0, Inv V valid s0 ->
    (DistConv V f rho E reg sig I o s0 <-> XUR V f rho E reg sig o s0 /\ C2R V f rho E reg sig I o (N V f rho o s0)).
  Proof.
    intros s0 Hi.
    assert (Hd : DistConv V f rho E reg sig I o s0 <-> DistConvA V f rho E reg sig I o At1 s0).
    { split.
      - intros H ws1 ws2 H1 H2 Ht. apply H; [apply At1_ok; exact H1 | apply At1_ok; exact H2 | exact Ht].
      - intros H w1 w2 H1 H2 Ht. rewrite <- (single_concat w1), <- (single_concat w2).
        apply H; [apply single_ok; exact H1 | apply single_ok; exact H2 | rewrite !single_concat; exact Ht]. }
    assert (Hx : XUR V f rho E reg sig o s0 <-> XURA V f rho E reg sig o At1 s0).
    { split.
      - intros H ws e Hw. apply H. apply At1_ok. exact Hw.
      - intros H p e Hp. rewrite <- (single_concat p). apply H. apply single_ok. exact Hp. }
    rewrite Hd, Hx.
    apply (dist_atoms_exact V src f valid rho E reg sig I o HC At1) with (fl := map (fun x => [x]) (map (DProp E) o)) (lf := o).
    - intros e. exists (DEv E e). split; [reflexivity | exact Logic.I].
    - intros a [[e | j] [-> Hx']]; [left; exists e; reflexivity | right; exists [j]; split; [reflexivity |]].
      intros k [<- | []]. exact Hx'.
    - apply (single_ok (map (DProp E) o)). apply Forall_forall. intros x Hx'. apply in_map_iff in Hx'.
      destruct Hx' as [j [<- Hj]]. exact Hj.
    - apply single_concat.
    - intros t _ k. reflexivity.
    - exact Hi.
  Qed.
End DistRecovered.

(* ----- the collapsed distributed network N': J propagates as one atom ----- *)

Section DistCollapse.
  Variable V : Type.
  Variable src : nat -> list nat.
  Variable f : nat -> (nat -> V) -> V -> V.
  Variable valid : nat -> V -> Prop.
  Variable rho : nat -> V -> V.
  Variable E : Type.
  Variable reg : E -> nat.
  Variable sig : E -> V -> V.
  Variable I : E -> E -> Prop.
  Variable o : list nat.
  Hypothesis HC : Common V src f valid rho E reg sig o.
  Variable inJ : nat -> bool.
  Hypothesis Hconv : Convex src inJ.

  Local Notation DE := (DEv E).
  Local Notation DP := (DProp E).
  Local Notation B := (blk inJ o).

  (* N''s atoms: an event; a propagation step of a registry outside J; J's whole internal repair,
     its block in order, as one step. *)
  Definition AtC (a : list (act E)) : Prop :=
    (exists e, a = [DE e]) \/ (exists j, a = [DP j] /\ In j o /\ inJ j = false) \/ a = map DP B.

  Definition flC : list (list (act E)) :=
    map (fun j => [DP j]) (preJ src inJ o) ++ [map DP B] ++ map (fun j => [DP j]) (postJ src inJ o).

  Lemma concat_single : forall l, concat (map (fun j => [DP j]) l) = map DP l.
  Proof. induction l as [| a l IH]; [reflexivity | simpl; rewrite IH; reflexivity]. Qed.

  Lemma flC_word : concat flC = map DP (blockOrder src inJ o).
  Proof.
    unfold flC, blockOrder. rewrite !concat_app, !concat_single, !map_app. simpl. rewrite app_nil_r. reflexivity.
  Qed.

  Lemma htopo : topoF src o. Proof. exact (c_topo _ _ _ _ _ _ _ _ _ HC). Qed.

  Lemma flC_ok : Forall AtC flC.
  Proof.
    unfold flC. apply Forall_app. split; [| apply Forall_app; split].
    - apply Forall_forall. intros a Ha. apply in_map_iff in Ha. destruct Ha as [j [<- Hj]].
      apply in_preJ in Hj. right. left. exists j. split; [reflexivity | split; apply Hj].
    - constructor; [right; right; reflexivity | constructor].
    - apply Forall_forall. intros a Ha. apply in_map_iff in Ha. destruct Ha as [j [<- Hj]].
      apply in_postJ in Hj. right. left. exists j. split; [reflexivity | split; [apply Hj |]].
      apply (desc_notJ src inJ o htopo). apply Hj.
  Qed.

  Lemma AtC_shape : forall a, AtC a -> (exists e, a = [DE e]) \/ (exists l, a = map DP l /\ incl l o).
  Proof.
    intros a [H | [[j [-> [Hj _]]] | ->]]; [left; exact H | right | right].
    - exists [j]. split; [reflexivity | intros x [<- | []]; exact Hj].
    - exists B. split; [reflexivity |]. intros x Hx. apply in_blk in Hx. apply Hx.
  Qed.

  Lemma flC_flush : forall t, Inv V valid t -> feq V (frun V f (blockOrder src inJ o) t) (frun V f o t).
  Proof.
    intros t _. destruct (Hbo V src f valid rho E reg sig o HC inJ Hconv) as [T P].
    apply (frun_topo_eq V src f valid rho E reg sig o HC); [exact T | exact htopo |].
    intros k. split; apply Permutation.Permutation_in; [apply Permutation.Permutation_sym |]; exact P.
  Qed.

  Definition DistConvC (s0 : nat -> V) : Prop := DistConvA V f rho E reg sig I o AtC s0.
  Definition XURC (s0 : nat -> V) : Prop := XURA V f rho E reg sig o AtC s0.

  (* The exact condition for N'. *)
  Theorem dist_collapse_exact : forall s0, Inv V valid s0 ->
    (DistConvC s0 <-> XURC s0 /\ C2R V f rho E reg sig I o (N V f rho o s0)).
  Proof.
    intros s0 Hi.
    exact (dist_atoms_exact V src f valid rho E reg sig I o HC AtC (fun e => or_introl (ex_intro _ e eq_refl))
             AtC_shape flC flC_ok (blockOrder src inJ o) flC_word flC_flush s0 Hi).
  Qed.

  Lemma AtC_ok : forall ws, Forall AtC ws -> Forall (okact E o) (concat ws).
  Proof.
    induction ws as [| a ws IH]; intros H; [constructor |]. inversion H as [| ? ? Ha Hw]; subst.
    simpl. apply Forall_app. split; [| apply IH; exact Hw].
    destruct Ha as [[e ->] | [[j [-> [Hj _]]] | ->]]; [repeat constructor | repeat constructor; exact Hj |].
    apply Forall_forall. intros x Hx. apply in_map_iff in Hx. destruct Hx as [j [<- Hj]].
    apply in_blk in Hj. apply Hj.
  Qed.

  (* N converges -> N' converges: every N' word is an N word. *)
  Theorem dist_collapse_sound : forall s0, DistConv V f rho E reg sig I o s0 -> DistConvC s0.
  Proof. intros s0 H ws1 ws2 H1 H2 Ht. apply H; [apply AtC_ok; exact H1 | apply AtC_ok; exact H2 | exact Ht]. Qed.

  Lemma xur_xurc : forall s0, XUR V f rho E reg sig o s0 -> XURC s0.
  Proof. intros s0 H ws e Hw. apply H. apply AtC_ok. exact Hw. Qed.

  (* Headline (b): N converges iff N' does and XU holds at every state N reaches, J
     half-propagated included. *)
  Theorem dist_collapse_iff : forall s0, Inv V valid s0 ->
    (DistConv V f rho E reg sig I o s0 <-> DistConvC s0 /\ XUR V f rho E reg sig o s0).
  Proof.
    intros s0 Hi. rewrite (dist_exact V src f valid rho E reg sig I o HC s0 Hi). split.
    - intros [Hx H2]. split; [| exact Hx]. apply (proj2 (dist_collapse_exact s0 Hi)).
      split; [apply xur_xurc; exact Hx | exact H2].
    - intros [Hc Hx]. split; [exact Hx | exact (proj2 (proj1 (dist_collapse_exact s0 Hi) Hc))].
  Qed.

  (* Under static XU (gsm's ProjectionSafe check), collapse is preserved in the distributed model. *)
  Theorem dist_collapse_xu : XU V f valid E reg sig -> forall s0, Inv V valid s0 ->
    (DistConvC s0 <-> DistConv V f rho E reg sig I o s0).
  Proof.
    intros HX s0 Hi. rewrite (dist_collapse_iff s0 Hi).
    pose proof (xu_xur V src f valid rho E reg sig o HC HX s0 Hi). tauto.
  Qed.
End DistCollapse.

(* ----- counterexamples ----- *)

(* The chain 0 -> 1 -> 2 (Collapse.v's chain_src), J = {1, 2}. Values (shared, local). Registry 1
   copies 0's shared value, 2 copies 1's. Seven (on 1) writes 7 into 1's shared part; Bump (on 2)
   counts, but only at shared value 7. No N' run puts 7 into 2: J's atom repairs 1 before it
   copies 1 into 2. An N run can: Seven, then propagate 2 alone. *)
Definition ch_f (j : nat) (z : nat -> nat * nat) (x : nat * nat) : nat * nat :=
  match j with 1 => (fst (z 0), snd x) | 2 => (fst (z 1), snd x) | _ => x end.
Definition ch_valid (_ : nat) (_ : nat * nat) : Prop := True.
Definition ch_rho (_ : nat) (x : nat * nat) : nat * nat := x.
Inductive chev : Type := Seven | Bump.
Definition ch_reg (e : chev) : nat := match e with Seven => 1 | Bump => 2 end.
Definition ch_sig (e : chev) (x : nat * nat) : nat * nat :=
  match e with Seven => (7, snd x) | Bump => if Nat.eqb (fst x) 7 then (fst x, S (snd x)) else x end.
Definition ch_I (_ _ : chev) : Prop := True.
Definition ch_o : list nat := [0; 1; 2].
Definition j12 (v : nat) : bool := match v with 1 | 2 => true | _ => false end.
Definition ch_s0 (_ : nat) : nat * nat := (0, 0).

Lemma ch_common : Common (nat * nat) chain_src ch_f ch_valid ch_rho chev ch_reg ch_sig ch_o.
Proof.
  constructor.
  - intros [| [| [| j]]] z1 z2 x H; simpl; try reflexivity; rewrite H; simpl; auto.
  - simpl. intuition lia.
  - intros; exact I.
  - intros [| [| [| j]]] z z' x _ _ _; reflexivity.
  - intros; reflexivity.
  - intros; exact I.
  - intros []; simpl; tauto.
Qed.

Lemma ch_convex : Convex chain_src j12.
Proof.
  intros u m w _ _ Hm P _. destruct (path_last chain_src u m P) as [y Hy].
  destruct m as [| [| [| m]]]; simpl in Hy; try discriminate Hm; exact Hy.
Qed.

Local Notation chD := (drun (nat * nat) ch_f chev ch_reg ch_sig).

(* The invariant of N' runs from ch_s0: registries 0 and 2 hold shared value 0. *)
Lemma ch_inv : forall ws t, Forall (AtC chev ch_o j12) ws -> fst (t 0) = 0 -> fst (t 2) = 0 ->
  fst (chD (concat ws) t 0) = 0 /\ fst (chD (concat ws) t 2) = 0.
Proof.
  induction ws as [| a ws IH]; intros t Hw H0 H2; [split; assumption |].
  inversion Hw as [| ? ? Ha Hw']; subst. simpl. rewrite dA_app.
  destruct Ha as [[[] ->] | [[j [-> [Hj HjJ]]] | ->]].
  all: apply IH; [exact Hw' | |].
  all: unfold blk, ch_o; simpl; unfold evstep, fstep, FederationEvents.upd; simpl; try assumption.
  all: try (destruct (Nat.eqb (fst (t 2)) 7); simpl; assumption).
  all: destruct Hj as [<- | [<- | [<- | []]]]; try discriminate HjJ; simpl; assumption.
Qed.

Lemma ch_xurc : XURC (nat * nat) ch_f ch_rho chev ch_reg ch_sig ch_o j12 ch_s0.
Proof.
  intros ws e Hw. destruct (ch_inv ws ch_s0 Hw eq_refl eq_refl) as [H0 H2].
  set (t := chD (concat ws) ch_s0) in *. clearbody t. unfold XUat.
  destruct e; simpl.
  - destruct (t 1) as [a b]. reflexivity.
  - unfold N, frun, fstep, FederationEvents.upd, ch_rho; simpl. rewrite H0.
    destruct (t 2) as [a b] eqn:T2. simpl in H2. subst a. reflexivity.
Qed.

Lemma ch_c2r : forall s, C2R (nat * nat) ch_f ch_rho chev ch_reg ch_sig ch_I ch_o s.
Proof. intros s p [] [] E' _; simpl in E'; try discriminate E'; reflexivity. Qed.

(* Headline counterexample (b): the collapsed distributed network converges, the network does not;
   collapse_c's "N' converges iff N does" fails in the distributed model. *)
Theorem dist_collapse_refuted :
  Common (nat * nat) chain_src ch_f ch_valid ch_rho chev ch_reg ch_sig ch_o /\
  Convex chain_src j12 /\
  XURC (nat * nat) ch_f ch_rho chev ch_reg ch_sig ch_o j12 ch_s0 /\
  DistConvC (nat * nat) ch_f ch_rho chev ch_reg ch_sig ch_I ch_o j12 ch_s0 /\
  ~ XUR (nat * nat) ch_f ch_rho chev ch_reg ch_sig ch_o ch_s0 /\
  ~ DistConv (nat * nat) ch_f ch_rho chev ch_reg ch_sig ch_I ch_o ch_s0.
Proof.
  pose proof ch_common as HC. pose proof ch_convex as Hcv.
  assert (Hi : Inv (nat * nat) ch_valid ch_s0) by (intro k; exact I).
  assert (Nd : ~ DistConv (nat * nat) ch_f ch_rho chev ch_reg ch_sig ch_I ch_o ch_s0).
  { intro Hd.
    assert (Ok1 : Forall (okact chev ch_o) [DEv chev Seven; DProp chev 2; DEv chev Bump])
      by (repeat constructor; simpl; tauto).
    assert (Ok2 : Forall (okact chev ch_o) [DEv chev Seven; DEv chev Bump]) by (repeat constructor).
    pose proof (Hd _ _ Ok1 Ok2 (teq_refl _ [Seven; Bump]) 2) as H. vm_compute in H. discriminate H. }
  split; [exact HC |]. split; [exact Hcv |]. split; [exact ch_xurc |]. split.
  - apply (proj2 (dist_collapse_exact (nat * nat) chain_src ch_f ch_valid ch_rho chev ch_reg ch_sig ch_I ch_o
                    HC j12 Hcv ch_s0 Hi)).
    split; [exact ch_xurc | apply ch_c2r].
  - split; [| exact Nd].
    intro Hx. apply Nd. apply (proj2 (dist_exact _ _ _ _ _ _ _ _ _ _ HC ch_s0 Hi)). split; [exact Hx | apply ch_c2r].
Qed.

(* The other conjunct: XU everywhere does not give N' convergence (two events on registry 0, a
   root, declared independent and not commuting: C2 fails). *)
Inductive c2ev : Type := Inc | Dbl.
Definition c2_reg (_ : c2ev) : nat := 0.
Definition c2_sig (e : c2ev) (x : nat * nat) : nat * nat :=
  match e with Inc => (fst x, S (snd x)) | Dbl => (fst x, 2 * snd x) end.
Definition c2_I (_ _ : c2ev) : Prop := True.

Lemma c2_common : Common (nat * nat) chain_src ch_f ch_valid ch_rho c2ev c2_reg c2_sig ch_o.
Proof.
  constructor.
  - intros [| [| [| j]]] z1 z2 x H; simpl; try reflexivity; rewrite H; simpl; auto.
  - simpl. intuition lia.
  - intros; exact I.
  - intros [| [| [| j]]] z z' x _ _ _; reflexivity.
  - intros; reflexivity.
  - intros; exact I.
  - intros []; simpl; tauto.
Qed.

Theorem dist_collapse_needs_c2 :
  Common (nat * nat) chain_src ch_f ch_valid ch_rho c2ev c2_reg c2_sig ch_o /\
  XUR (nat * nat) ch_f ch_rho c2ev c2_reg c2_sig ch_o ch_s0 /\
  ~ DistConvC (nat * nat) ch_f ch_rho c2ev c2_reg c2_sig c2_I ch_o j12 ch_s0.
Proof.
  split; [exact c2_common |]. split; [intros p e _; destruct e; reflexivity |].
  intros H.
  assert (O : forall a b, Forall (AtC c2ev ch_o j12) [[DEv c2ev a]; [DEv c2ev b]])
    by (intros a b; constructor; [left; exists a; reflexivity | constructor; [left; exists b; reflexivity | constructor]]).
  assert (Ht : tequiv (Ifed c2ev c2_reg c2_I) (evs c2ev (concat [[DEv c2ev Inc]; [DEv c2ev Dbl]]))
                 (evs c2ev (concat [[DEv c2ev Dbl]; [DEv c2ev Inc]])))
    by (apply (teq_swap _ [] Inc Dbl []); right; exact I).
  pose proof (H _ _ (O Inc Dbl) (O Dbl Inc) Ht 0) as E. vm_compute in E. discriminate E.
Qed.
