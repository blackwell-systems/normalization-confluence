(* CompositionBlocks.v: composition beyond acyclic collapse (REGIME-AUDIT section 14, gaps 19 and 5),
   mechanized axiom-free.

   Collapse.v proves compositional collapse for an ACYCLIC convex sub-federation J in the FedMachine
   model (collapse_c_exact: the contracted network N' converges iff N does, with the same exact
   condition). Two questions were open. (a) Networks whose strongly connected blocks use different
   engines (a monotone cycle, a rootless invertible cycle, an acyclic block, a non-monotone block):
   when does the composed network converge, and is its normal form the one computed block by block?
   (b) The distributed model, where J's internal propagation steps interleave with outer events.
   This file answers both, and closes gap 5 (a cyclic MONOTONE J) in the FedMachine model.

   PART A. The interface theorem (any engines). The condensation of a network into strongly
   connected blocks is acyclic, so a network is an acyclic composition of black boxes, and every
   finite DAG of blocks is built by repeatedly composing an upstream system A with one downstream
   block B (the composite is again a system of the same kind). A system is a state type with an
   equivalence (states are compared pointwise in the development), a type of actions with a
   predicate selecting the network's own actions, and a deterministic step per action; a schedule
   is a finite list of allowed actions. A is any system on X; B is a system on Y whose steps read A's
   CURRENT state x (its inputs; stepB x b y). The composite runs on X * Y and interleaves A's and B's
   actions freely. Quiet: every allowed action leaves the state unchanged (a normal form).
     Conv (convergence of a system): from every start some schedule reaches a quiet state, and every
     schedule that reaches a quiet state reaches the same one (up to the equivalence). This is the
     form of net_unique_normal_form_iff (RootlessNetworks.v).
     Lk xs: the equivalence on Y generated by B's steps taken at inputs x from which A reaches xs
     (the inputs A presents on its way to xs).
   compose_exact (exact, each conjunct necessary):
     Conv composite <-> Conv A
                        /\ (for every quiet xs of A, B at input xs reaches a quiet state from every y)
                        /\ (for every quiet xs of A, two quiet states of B at xs related by Lk xs are
                            equal).
   The third conjunct is the interleaving conjunct: B's settled output must not depend on the steps
   B took while A was still moving. It is not implied by each block converging in isolation:
   compose_isolated_refuted (the sticky block, y := input while y = 0: A converges, B converges at
   every fixed input, the composite reaches two normal forms). Each conjunct is necessary:
   compose_needs_A, compose_needs_wn, compose_isolated_refuted; and B is constrained only at A's
   quiet inputs: compose_transient_free (B has no normal form at a transient input, the composite
   converges).
   compose_collapse (the collapse): under the conjuncts, every normal form of the composite from
   (x, y) is (xs, ys) with xs A's normal form from x and ys B's normal form at input xs FROM THE
   ORIGINAL y. The composite's normal form is the collapsed, block-by-block one.
   The black-box interface. Give each block an equivalence K on its states that its steps preserve
   at every input (its own inputs: the locals, the values at its de facto roots; K = everything for
   a block whose normal form is unique), with eq included in K. Settles K: every start reaches a
   quiet state, and quiet states related by K are equal.
     settles_conv: Settles K -> Conv (a block meeting the interface converges).
     interface_closed: Settles (KA x KB) of the composite <-> Settles KA of A /\ Settles KB of B at
       every quiet input of A. The interface is closed under composition, exactly; by induction it
       holds for every finite DAG of blocks meeting it, whatever their engines.
     interface_lk: Settles KB of B at a quiet input gives compose_exact's interleaving conjunct.

   PART B. Engine instances.
     rootless_conv_iff: a rootless invertible network (RootlessNetworks.v), as a system whose
       actions are its edges, converges iff has_section and (authority_cover or the group is
       trivial): net_unique_normal_form_iff read as Conv (rootless_conv_lhs), so it is the exact
       A-conjunct for a rootless block feeding other blocks. mixed_rootless_exact: a rootless block
       feeding any block B converges iff that condition holds and B's two conjuncts hold at the
       rootless block's sections.
     mono_block_interface_iff: a monotone cycle (DistributedCycles.v, at fixed locals) meets the
       interface with K = every state exactly when its repair has one fixed point (through
       q1_unique_iff). mixed_mono_iff: a monotone block reading its locals from any upstream
       system A, with one fixed point at every quiet input of A, converges iff A does.
     Non-vacuity and the interleaving conjunct with real engines: mixed_instance (the rootless
       network of rootless_source_feeds_cycle, a source feeding a coherently oriented 2-cycle over
       Z/2, feeding a block that reads it), mixed_mono_instance (the same rootless block feeding a
       monotone 2-cycle with one fixed point at every local: the composite converges), and
       mixed_ghost_refuted (the same rootless block feeding the flag cycle of
       FederationEventsCycles.v: the rootless block converges, but a transient alarm, raised while
       it is still settling, lifts the cycle to its ghost fixed point, so the composite reaches two
       normal forms; compose_exact's third conjunct fails).

   PART C. Gap 5 in the FedMachine model: a cyclic MONOTONE J. The FedMachine of a monotone network
   computes the least fixed point of the repair (FederationEventsCycles.cyc_N_lfp). Split the
   shared values into an upstream block X and a downstream block Y (J is either; nesting the split
   gives any block decomposition along the condensation): the repair is triangular,
   F l (x, y) = (FA l x, FB l x y). bekic_lfp: if a is the least fixed point of FA l and b that of
   FB l a, then (a, b) is the least fixed point of F l (Bekic's principle for a triangular system;
   finite height on Y). mono_collapse_nf: a flattened normalizer computing lfp F (the form
   cyc_N_lfp gives for gsm's normalizeCyclic) equals the collapsed one, which normalizes J as one
   effective registry with its own least fixed point; mono_collapse_runs_agree,
   mono_collapse_converges_iff: N' converges iff N does, and mono_collapse_exact: both iff the
   global condition GC (gc_iff), the exact condition on cycles. Non-vacuity: mono_collapse_instance.

   PART D. The distributed model (FederationEvents.v, DistributedExact.v): a word of local events
   and propagation steps, compared after a final flush. In the collapsed distributed network N', J
   propagates as one effective registry: one action runs J's internal repair to completion (its
   block, in order), so no outer event sees J half-propagated. Words are lists of atoms.
     dist_atoms_exact: for any atom set containing every event, whose other atoms are propagation
       words and which contains a flush, convergence over its words is reachable XU over its words
       plus the FedMachine's C2 at states reachable from the flushed start (dist_exact's form).
       dist_exact is recovered as the singleton-atom case (dist_exact_recovered).
     dist_collapse_exact: N' converges iff XU at N'-reachable states and C2R.
     dist_collapse_sound: N converges -> N' converges.
     dist_collapse_iff: N converges <-> N' converges /\ XUR (XU at every state N reaches, J
       half-propagated included). The second conjunct is the settlement conjunct.
     dist_collapse_refuted: the plain collapse_c statement fails in the distributed model: a chain
       0 -> 1 -> 2, J = {1, 2}, Common, J convex, N' converges from the start, N does not (an event
       on 1 propagated to 2 before 1 is repaired is a combination no N' run produces).
     dist_collapse_needs_c2: XUR does not give N' convergence (C2 fails), so both conjuncts are
       needed.
     dist_collapse_xu: under static XU (gsm's ProjectionSafe check) N converges iff N' does.

   Literature. The composition of fixed points along an acyclic block decomposition is classical:
   Bekic's principle for least fixed points (H. Bekic, "Definable operations in general algebras,
   and the theory of automata and flowcharts", 1969, in LNCS 177, 1984); Robert's decomposition of
   discrete iterations along the strongly connected components of the interaction graph
   (F. Robert, "Discrete Iterations", Springer 1986); modular and SCC-based attractor computation for
   Boolean networks (for example Mizera, Pang, Qu, Yuan, "Taming asynchrony for attractor detection
   in large Boolean networks", IEEE/ACM TCBB 16(1), 2019, which detects attractors block by block
   along the SCC decomposition; Kadelka, Wheeler, Veliz-Cuba, Murrugarra,
   Laubenbacher, "Modularity of biological systems: a link between structure and function",
   J. R. Soc. Interface 20(207), 2023, where the attractors of a network are assembled from those of its
   modules driven by their upstream modules). Part A is in that line: a block driven by an upstream
   block. What is stated here is the exact condition for a unique reachable normal form in the
   asynchronous step model with arbitrary interleaving, its interleaving conjunct, and the
   interface closure; no claim beyond that is made.

   States are compared by a given equivalence; no functional extensionality is used. *)

