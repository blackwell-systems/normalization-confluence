Section Bekic.
  Variables Loc X Y : Type.
  Variable leX : X -> X -> Prop.
  Variable leY : Y -> Y -> Prop.
  Hypothesis leX_refl : forall x, leX x x.
  Hypothesis leX_antisym : forall x y, leX x y -> leX y x -> x = y.
  Hypothesis leY_refl : forall y, leY y y.
  Hypothesis leY_trans : forall x y z, leY x y -> leY y z -> leY x z.
  Hypothesis leY_antisym : forall x y, leY x y -> leY y x -> x = y.
  Variable rankY : Y -> nat.
  Hypothesis rankY_strict : forall x y, leY x y -> x <> y -> rankY x < rankY y.
  Variable Ydec : forall x y : Y, {x = y} + {x <> y}.

  (* The triangular repair: the upstream block X does not read Y. *)
  Variable FA : Loc -> X -> X.
  Variable FB : Loc -> X -> Y -> Y.
  Hypothesis FB_mono : forall l x x' y y', leX x x' -> leY y y' -> leY (FB l x y) (FB l x' y').

  Definition leP (p q : X * Y) : Prop := leX (fst p) (fst q) /\ leY (snd p) (snd q).
  Definition FP (l : Loc) (p : X * Y) : X * Y := (FA l (fst p), FB l (fst p) (snd p)).

  Lemma leP_antisym : forall p q, leP p q -> leP q p -> p = q.
  Proof.
    intros [a b] [c d] [H1 H2] [H3 H4]. simpl in *. f_equal; [apply leX_antisym | apply leY_antisym]; assumption.
  Qed.

  (* Finite height: the least fixed point is below every pre-fixed point. *)
  Lemma lfp_below_prefixed : forall (g : Y -> Y) b, (forall y y', leY y y' -> leY (g y) (g y')) ->
    is_lfp leY g b -> forall y, leY (g y) y -> leY b y.
  Proof.
    intros g b Hg [Hb Hl] y. induction y as [y IH] using (well_founded_induction (well_founded_ltof Y rankY)).
    intros Hy. destruct (Ydec (g y) y) as [E | N].
    - apply Hl. exact E.
    - assert (Hr : rankY (g y) < rankY y) by (apply rankY_strict; assumption).
      eapply leY_trans; [apply (IH (g y) Hr); apply Hg; exact Hy | exact Hy].
  Qed.

  (* Bekic's principle for a triangular monotone system: the blockwise least fixed points form
     the least fixed point. *)
  Theorem bekic_lfp : forall l a b,
    is_lfp leX (FA l) a -> is_lfp leY (FB l a) b -> is_lfp leP (FP l) (a, b).
  Proof.
    intros l a b [Ha Hal] [Hb Hbl]. split.
    - unfold fixed_point, FP. simpl. unfold fixed_point in Ha, Hb. rewrite Ha, Hb. reflexivity.
    - intros [x y] Hxy. unfold fixed_point, FP in Hxy. simpl in Hxy. injection Hxy as Ex Ey.
      assert (Hax : leX a x) by (apply Hal; exact Ex).
      split; [exact Hax |]. simpl.
      apply (lfp_below_prefixed (FB l a) b (fun y y' H => FB_mono l a a y y' (leX_refl a) H) (conj Hb Hbl) y).
      rewrite <- Ey at 2. apply FB_mono; [exact Hax | apply leY_refl].
  Qed.

  (* ----- the collapsed and the flattened FedMachine ----- *)

  Variable rho1 : Loc * (X * Y) -> Loc * (X * Y).   (* phase 1 *)
  (* The flattened normalizer: the least fixed point of the whole repair (the form of
     FederationEventsCycles.cyc_N_lfp, which gsm's normalizeCyclic satisfies). *)
  Variable Nflat : Loc * (X * Y) -> Loc * (X * Y).
  Hypothesis HNf : forall t, fst (Nflat t) = fst (rho1 t) /\ is_lfp leP (FP (fst (rho1 t))) (snd (Nflat t)).
  (* The collapsed normalizer: each block normalized as one effective registry, J by its own least
     fixed point at its inputs. *)
  Variable NA : Loc -> X.
  Hypothesis HNA : forall l, is_lfp leX (FA l) (NA l).
  Variable NB : Loc -> X -> Y.
  Hypothesis HNB : forall l x, is_lfp leY (FB l x) (NB l x).

  Definition Ncol (t : Loc * (X * Y)) : Loc * (X * Y) :=
    (fst (rho1 t), (NA (fst (rho1 t)), NB (fst (rho1 t)) (NA (fst (rho1 t))))).

  Theorem mono_collapse_nf : forall t, Ncol t = Nflat t.
  Proof.
    intros t. destruct (HNf t) as [E L]. unfold Ncol. destruct (Nflat t) as [l' p]. simpl in E, L. subst l'.
    f_equal. apply (lfp_unique leP leP_antisym (FP (fst (rho1 t)))); [| exact L].
    apply bekic_lfp; [apply HNA | apply HNB].
  Qed.

  Theorem mono_collapse_runs_agree : forall (E : Type) (ev : E -> Loc * (X * Y) -> Loc * (X * Y)) es s,
    grun _ E Ncol ev es s = grun _ E Nflat ev es s.
  Proof.
    intros E ev es. unfold grun, runT. induction es as [| e es IH]; intros s; [reflexivity |].
    simpl. replace (gstep _ E Ncol ev e s) with (gstep _ E Nflat ev e s); [apply IH |].
    unfold gstep. symmetry. apply mono_collapse_nf.
  Qed.

  (* N' converges iff N does, and both exactly when the global condition holds. *)
  Theorem mono_collapse_converges_iff : forall (E : Type) ev reg (I : E -> E -> Prop) s0,
    Converges _ E Ncol ev reg I s0 <-> Converges _ E Nflat ev reg I s0.
  Proof.
    intros E ev reg I s0. unfold Converges. split; intros H es1 es2 Ht;
      [rewrite <- !mono_collapse_runs_agree | rewrite !mono_collapse_runs_agree]; apply H; exact Ht.
  Qed.

  Theorem mono_collapse_exact : forall (E : Type) ev reg (I : E -> E -> Prop) s0,
    (Converges _ E Ncol ev reg I s0 <-> GC _ E Nflat ev reg I s0) /\
    (GC _ E Ncol ev reg I s0 <-> GC _ E Nflat ev reg I s0).
  Proof.
    intros E ev reg I s0. rewrite mono_collapse_converges_iff, <- gc_iff. split; [tauto |].
    rewrite !gc_iff. apply mono_collapse_converges_iff.
  Qed.
End Bekic.

(* Non-vacuity: a root (registry 0, shared flag copying its local) feeding the flag cycle
   (registries 1 and 2, each one's flag fed by the other and by the root). The flattened
   normalizer is gsm's normalizeCyclic (Ncyc_with) on the three targets. *)
Definition ble (a b : bool) : Prop := implb a b = true.
Definition L3 : Type := (bool * B2)%type.
Definition gFA (l : L3) (_ : bool) : bool := fst l.
Definition gFB (l : L3) (x : bool) (y : B2) : B2 := (snd (snd l) || snd y || x, fst (snd l) || fst y).
Definition gle (p q : bool * B2) : Prop := leP bool B2 ble cle p q.
Definition gF (l : L3) (p : bool * B2) : bool * B2 := FP L3 bool B2 gFA gFB l p.
Definition gu (l : L3) (j : nat) (p : bool * B2) : bool * B2 :=
  match j with
  | 0 => (fst (gF l p), snd p)
  | 1 => (fst p, (fst (snd (gF l p)), snd (snd p)))
  | 2 => (fst p, (fst (snd p), snd (snd (gF l p))))
  | _ => p
  end.
Definition grank (p : bool * B2) : nat := (if fst p then 1 else 0) + crank (snd p).
Definition gbot : bool * B2 := (false, (false, false)).
Definition g_dec : forall x y : bool * B2, {x = y} + {x <> y}.
Proof. decide equality; [apply ceq_dec | apply bool_dec]. Defined.
Definition gts : list nat := [0; 1; 2].
Definition gN : L3 * (bool * B2) -> L3 * (bool * B2) := Ncyc_with L3 (bool * B2) gbot g_dec gu (fun s => s) 4 gts.
Definition gNA (l : L3) : bool := fst l.
Definition gNB (l : L3) (x : bool) : B2 := let c := fst (snd l) || snd (snd l) || x in (c, c).

Ltac bfg := repeat match goal with
  | x : L3 |- _ => destruct x
  | x : bool * B2 |- _ => destruct x
  | x : B2 |- _ => destruct x
  | b : bool |- _ => destruct b
  end.

Lemma gle_refl : forall x, gle x x. Proof. intros; bfg; unfold gle, leP, ble, cle; simpl; tauto. Qed.
Lemma gle_trans : forall x y z, gle x y -> gle y z -> gle x z.
Proof. intros x y z; bfg; unfold gle, leP, ble, cle; simpl; intuition congruence. Qed.
Lemma gbot_least : forall x, gle gbot x. Proof. intros; bfg; unfold gle, leP, ble, cle; simpl; tauto. Qed.
Lemma grank_strict : forall x y, gle x y -> x <> y -> grank x < grank y.
Proof. intros x y; bfg; unfold gle, leP, ble, cle, grank, crank; simpl; intuition (try congruence; try lia). Qed.
Lemma grank_bound : forall x, grank x <= 3. Proof. intros; bfg; unfold grank, crank; simpl; lia. Qed.
Lemma gu_incr : forall l j x, sound L3 (bool * B2) gle gF l x -> gle x (gu l j x).
Proof. intros l [| [| [| j]]] x; bfg; unfold sound, gle, leP, ble, cle, gu, gF, FP, gFA, gFB; simpl; intuition. Qed.
Lemma gu_sound : forall l j x, sound L3 (bool * B2) gle gF l x -> sound L3 (bool * B2) gle gF l (gu l j x).
Proof. intros l [| [| [| j]]] x; bfg; unfold sound, gle, leP, ble, cle, gu, gF, FP, gFA, gFB; simpl; intuition. Qed.
Lemma gu_mono : forall l j x y, gle x y -> gle (gu l j x) (gu l j y).
Proof. intros l [| [| [| j]]] x y; bfg; unfold gle, leP, ble, cle, gu, gF, FP, gFA, gFB; simpl; intuition. Qed.
Lemma gu_fixed : forall l j x, gF l x = x -> gu l j x = x.
Proof. intros l [| [| [| j]]] x; bfg; unfold gu, gF, FP, gFA, gFB; simpl; intro H; first [reflexivity | congruence]. Qed.
Lemma gts_cover : Cover L3 (bool * B2) gF gu gts.
Proof.
  intros l x H. pose proof (H 0 (or_introl eq_refl)) as H0. pose proof (H 1 (or_intror (or_introl eq_refl))) as H1.
  pose proof (H 2 (or_intror (or_intror (or_introl eq_refl)))) as H2.
  revert H0 H1 H2. bfg; unfold gu, gF, FP, gFA, gFB; simpl; intros H0 H1 H2; first [reflexivity | congruence].
Qed.

Theorem mono_collapse_instance :
  (forall t, Ncol L3 bool B2 (fun s => s) gNA gNB t = gN t) /\
  gN ((true, (false, false)), (false, (false, false))) = ((true, (false, false)), (true, (true, true))) /\
  gN ((false, (false, false)), (true, (true, true))) = ((false, (false, false)), (false, (false, false))).
Proof.
  split; [| split; reflexivity].
  apply (mono_collapse_nf L3 bool B2 ble cle (fun x => ltac:(destruct x; reflexivity))
           (fun x y => ltac:(destruct x, y; unfold ble; simpl; congruence)) cle_refl cle_trans cle_antisym
           crank crank_strict ceq_dec gFA gFB).
  - intros l x x' y y' Hx Hy. revert Hx Hy. bfg; unfold ble, cle, gFB; simpl; intuition.
  - intros t. exact (cyc_N_lfp L3 (bool * B2) gle gle_refl gle_trans gbot gbot_least grank grank_strict 3
                       grank_bound g_dec gF gu gu_incr gu_sound gu_mono gu_fixed (fun s => s) 4 ltac:(lia) gts
                       gts_cover t).
  - intros l. split; [reflexivity |]. intros x Hx. unfold fixed_point, gFA in Hx. subst x. unfold ble, gNA. destruct (fst l); reflexivity.
  - intros l x. split.
    + unfold fixed_point, gNB, gFB. bfg; reflexivity.
    + intros [a b] H. revert H. bfg; unfold fixed_point, gFB, gNB, cle; simpl; intro H;
        try discriminate H; split; reflexivity.
Qed.

