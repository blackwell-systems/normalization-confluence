Section NoSwitch.
  Context {S E : Type}.
  Variable step : E -> S -> S.
  Variable eqv : S -> S -> Prop.
  Variable AdmE : list E -> Prop.
  Variable RelE : list E -> list E -> Prop.

  Local Notation run := (runT step).

  (* B = A, M and tau identities, and only A-events submitted: the class lifted to E + E. *)
  Definition AdmN (w : list (E + E)) : Prop := projB w = [] /\ AdmE (projA w).
  Definition RelN (w1 w2 : list (E + E)) : Prop := RelE (projA w1) (projA w2).
  Definition ConvE (s0 : S) : Prop :=
    forall o1 o2, AdmE o1 -> AdmE o2 -> RelE o1 o2 -> eqv (run o1 s0) (run o2 s0).

  Lemma projB_nil_inl : forall (q : list (E + E)), projB q = [] -> q = map inl (projA q).
  Proof.
    induction q as [| [a | b] q IH]; intros H; [reflexivity | simpl; f_equal; exact (IH H) | discriminate H].
  Qed.

  Lemma runX_id : forall (l : list E) y, runT (stepX step (fun e => e)) (map inl l) y = run l y.
  Proof. induction l as [| a l IH]; intros y; [reflexivity |]. simpl map. rewrite !runT_cons. apply IH. Qed.

  Theorem no_switch_exact : forall s0,
    LiveD step step eqv (fun s => s) (fun e => e) AdmN RelN s0 <-> ConvE s0.
  Proof.
    intros s0. split.
    - intros H o1 o2 H1 H2 R. pose proof (H [] (map inl o1) [] (map inl o2)) as K. unfold outD in K.
      simpl in K. rewrite !runX_id in K. apply K.
      + split; [apply projB_inl | rewrite projA_inl; exact H1].
      + split; [apply projB_inl | rewrite projA_inl; exact H2].
      + unfold RelN. rewrite !projA_inl. exact R.
    - intros H p1 q1 p2 q2 [B1 H1] [B2 H2] R. unfold outD, RelN in *.
      rewrite projB_app, projB_inl in B1, B2. simpl in B1, B2.
      rewrite (projB_nil_inl q1 B1), (projB_nil_inl q2 B2), !runX_id, <- !runT_app.
      rewrite !projA_app, !projA_inl in R. rewrite !projA_app, !projA_inl in H1. rewrite !projA_app, !projA_inl in H2.
      exact (H _ _ H1 H2 R).
  Qed.
End NoSwitch.

(* The gap 15 theorems, with no switch. *)
Theorem causal_no_switch : forall {S E : Type} (step : E -> S -> S) (hb : E -> E -> Prop) s0,
  LiveD step step eq (fun s => s) (fun e => e) (AdmN (causal hb)) (RelN (@Permutation E)) s0 <->
  NC.GovernanceConverse.CCR step hb s0.
Proof.
  intros S E step hb s0. rewrite no_switch_exact. rewrite <- NC.GovernanceConverse.causal_exact.
  unfold ConvE, NC.GovernanceConverse.CausalConv. tauto.
Qed.

Theorem alo_no_switch : forall {S E : Type} (dec : forall x y : E, {x = y} + {x <> y}) (step : E -> S -> S)
  (Ev : E -> Prop) s0,
  LiveD step step eq (fun s => s) (fun e => e) (AdmN (Forall Ev)) (RelN SameSet) s0 <->
  CommReach step Ev s0 /\ forall a, IdemReach step Ev s0 a.
Proof.
  intros S E dec step Ev s0. rewrite no_switch_exact. rewrite <- alo_exact by exact dec.
  unfold ConvE, ALOConv, SameSet. split.
  - intros H d o Hd Ho Hs. apply H; [exact Hd | | intros x; symmetry; apply Hs].
    apply Forall_forall. intros x Hx. apply (proj1 (Forall_forall Ev d) Hd). apply Hs. exact Hx.
  - intros H d1 d2 H1 H2 Hs.
    rewrite (H d1 (dedup dec d1) H1 (dedup_NoDup dec d1) (fun x => dedup_In dec d1 x)).
    symmetry. apply H; [exact H2 | apply dedup_NoDup |].
    intros x. rewrite dedup_In. split; intros Hx; apply Hs; exact Hx.
Qed.

Theorem declared_no_switch : forall {S E : Type} (step : E -> S -> S) (Ev : E -> Prop) (hb I : E -> E -> Prop),
  (forall a b, I a b -> I b a) -> (forall a, ~ I a a) -> (forall a b, I a b -> ~ hb a b) -> forall s0,
  LiveD step step eq (fun s => s) (fun e => e) (AdmN (fun o => Forall Ev o /\ causal hb o)) (RelN (tequiv I)) s0 <->
  NC.AtLeastOnceDeclared.CommI step Ev hb I s0.
Proof.
  intros S E step Ev hb I Isym Iirr Ihb s0. rewrite no_switch_exact.
  rewrite <- (NC.AtLeastOnceDeclared.tconv_exact step Ev hb I Isym Iirr Ihb s0).
  unfold ConvE, NC.AtLeastOnceDeclared.TConvI. split.
  - intros H o1 o2 H1 H2 T. apply H; [split; assumption | | exact T]. split.
    + apply (Permutation_Forall (tequiv_perm _ _ _ T)). exact H1.
    + exact (NC.AtLeastOnceDeclared.tequiv_I_causal hb I Isym Iirr Ihb o1 o2 T H2).
  - intros H o1 o2 [H1 H2] _ T. exact (H o1 o2 H1 H2 T).
Qed.

Theorem dalo_no_switch : forall {S E : Type} (dec : forall x y : E, {x = y} + {x <> y}) (step : E -> S -> S)
  (Ev : E -> Prop) (hb I : E -> E -> Prop),
  (forall x, ~ hb x x) -> (forall a b, I a b -> I b a) -> (forall a, ~ I a a) -> (forall a b, I a b -> ~ hb a b) ->
  forall s0,
  let RelD := fun d1 d2 : list E => exists o, Forall Ev o /\ causal hb o /\ SameSet d1 o /\
                NC.AtLeastOnceDeclared.ALOI I o d1 /\ SameSet d2 o /\ NC.AtLeastOnceDeclared.ALOI I o d2 in
  LiveD step step eq (fun s => s) (fun e => e) (AdmN (fun d => RelD d d)) (RelN RelD) s0 <->
  NC.AtLeastOnceDeclared.CommI step Ev hb I s0 /\ forall a, IdemAt step Ev hb s0 a.
Proof.
  intros S E dec step Ev hb I Hirr Isym Iirr Ihb s0 RelD. rewrite no_switch_exact.
  rewrite <- (NC.AtLeastOnceDeclared.dalo_exact dec step Ev hb I Hirr Isym Iirr Ihb s0).
  unfold ConvE, NC.AtLeastOnceDeclared.DALOConv, RelD. split.
  - intros H o d Ho Hc Hs Ha.
    assert (Haa : NC.AtLeastOnceDeclared.ALOI I o o).
    { intros a b Hab l r E1 Hb Ha'. exfalso. destruct Hc as [Hnd _].
      apply (NC.AtLeastOnceDeclared.decl_prec_asym a b o Hnd Hab). rewrite E1. exact (rd_prec_cross b a l r Hb Ha'). }
    assert (Hso : SameSet o o) by (intros x; reflexivity).
    apply H.
    + exists o. split; [exact Ho | split; [exact Hc | split; [exact Hs | split; [exact Ha | split; [exact Hs | exact Ha]]]]].
    + exists o. split; [exact Ho | split; [exact Hc | split; [exact Hso | split; [exact Haa | split; [exact Hso | exact Haa]]]]].
    + exists o. split; [exact Ho | split; [exact Hc | split; [exact Hs | split; [exact Ha | split; [exact Hso | exact Haa]]]]].
  - intros H d1 d2 _ _ [o [Ho [Hc [S1 [A1 [S2 A2]]]]]].
    rewrite (H o d1 Ho Hc S1 A1). symmetry. exact (H o d2 Ho Hc S2 A2).
Qed.

