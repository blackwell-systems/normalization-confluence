      classify_declared_complete (every sequence admissible), classify_causal_complete,
      classify_alo_complete. Causal and at-least-once admissibility depend on the delivered set:
      the decision computes the closure over (state, delivered set) pairs (sections Monitor,
      FiniteClass: mreach_iff, mforall_dec, causal_forall_dec, alo_forall_dec, ccr_s_dec,
      idem_s_dec, causal_pairs_dec, alo_pairs_dec).

   7. Instances (each a counterexample to one conjunct with the others holding, or non-vacuity).
      - cross_declared_online / cross_declared_barrier: A sets a flag, B has set and toggle, M the
        identity, DS1 holds. Declaring nothing, Online; declaring only the pair (in-flight set,
