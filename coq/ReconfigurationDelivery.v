(* ReconfigurationDelivery.v: reconfiguration inside a run under a delivery class (gap 20 of
   REGIME-AUDIT.md, residue (b)): declared independence, causal and at-least-once delivery across
   the switch. Axiom-free.

   Setting: section Det of Reconfiguration.v, gsm's runtime. Deterministic steps stepA, stepB, an
   equivalence eqvB on B-states respected by stepB, a migration M, a translation tau. A run is a
   delivery sequence w of the combined alphabet X = EA + EB (inl a: an A-event, submitted before
   the switch; inr b: a B-event, submitted after it), split as w = map inl p ++ q: p delivered
   under A, the switch, then q under B, where inl a is applied as stepB (tau a):
     outD s0 p q = runX q (M (runA p s0)),   runX the run of stepX x = stepB (trX x).
   A delivery class is a set Adm of admissible sequences of X, closed under prefixes, compared by a
   relation Rel reflexive on it (as in DistributedDelivery.v). Free delivery: every sequence,
   Permutation. Declared independence IX on X: tequiv IX (only declared pairs reorder; a pair of
   A-events, of B-events, or an in-flight A-event with a B-event). Causal: causal hbX, Permutation.
   At-least-once: causal_alo hbX (hbX empty for free), the same set of events.

   1. Generic (section Generic).
      LiveD s0: every two splits of Rel-related admissible sequences agree (the switch anywhere
      before the first B-event). BarD s0: the same for the splits a barrier allows (Q p q: B-events
      only, or for at-least-once also redeliveries of A-events delivered before the switch).
      - live_delivery_exact: LiveD s0 <-> ConvXD (M s0) /\ S1D s0, where ConvXD y is B's class
        condition from y over the combined alphabet (translated A-events included) and S1D s0 is
          M (stepA a (runA u s0)) ~ stepB (tau a) (M (runA u s0))
        at every A-prefix u ++ [a] the class admits (duplicates included under at-least-once).
      - barrier_delivery_exact: given Glue (the A parts and the B parts of two related barrier runs
        can be compared separately), BarD s0 <-> BarBD s0 /\ AmodMD s0: B's class condition after
        a quiescent switch at every migrated reachable state, and A's class convergence modulo M.
      - live_implies_barrier_d; ClassD (Online, BarrierOnly, Unsafe), classD_unique, classD_decide.

   2. Free delivery recovered: free_live_exact (LiveD <-> det_live_exact's DLive),
      free_barrier_exact (BarD <-> DBar), free_barrier_closure_exact (det_barrier_closure_exact).

   3. Trace classes (Rel = tequiv IX, Adm closed under prefixes and declared swaps).
      - trace_conv_s_exact (generic, up to an equivalence): TConvS y <-> CommS y, declared pairs
        commuting after every admissible prefix.
      - live_trace_exact: LiveD s0 <-> CommS stepX (M s0) /\ S1D s0: every declared pair of the
        combined alphabet (translated A-pairs, in-flight A-event with B-event, B-pairs) commutes
        after every admissible prefix from M s0. The cross pairs enter only as the class declares
        them.
      - barrier_trace_exact (when admissibility of map inl p ++ map inr v splits):
        BarD s0 <-> (forall p, AdmA p -> CommS stepB AdmB IB (M (runA p s0))) /\ AmodT s0, with
        amodt_swap_exact (the A part generated by adjacent declared swaps).
      - Causal: live_causal_exact (CCRonS of the combined alphabet at M s0, and S1 at the causal
        A-prefixes, S1C) and barrier_causal_exact (CCRonS of B at every migrated causal state, and
        A's causal convergence modulo M, AmodC), with hbX never ordering a B-event before an
        A-event for the barrier.
      - Declared with every sequence admissible (gsm's Independent pairs): live_declared_exact
        (declared pairs of the combined alphabet commute at every state reached from M s0, and
        DS1) and barrier_declared_exact (B's declared pairs at every state reached from every
        migrated reachable state, and ClosureI: the pair closure seeded with A's declared pairs
        only, closureI_swap_exact, closureI_witness_exact).

   4. At-least-once (causal, hbX irreflexive; free = hbX empty).
      - live_alo_exact: LiveD s0 <-> (CCRonS stepX hbX (M s0) /\ forall x, IdemAtS stepX hbX (M s0) x)
        /\ S1CA s0: B's at-least-once condition over the combined alphabet at M s0 (commutation of
        concurrent pairs and idempotence, translated A-events included) and S1 at every causally
        consistent at-least-once A-prefix, so with duplicates delivered before the switch. A
        duplicate straddling a live switch needs no conjunct of its own: S1 at the duplicate
        prefix and the idempotence of tau a cover it.
      - barrier_alo_exact: BarD s0 <-> (forall p, causal_alo hbA p -> CCRonS and IdemAtS of B at
        M (runA p s0)) /\ AbsorbS s0 /\ AmodA s0. AbsorbS, the straddling duplicate: an A-event a
        delivered before the switch and redelivered after the B-events v (where causally
        consistent) is absorbed,
          stepB (tau a) (runB v (M (runA p s0))) ~ runB v (M (runA p s0))   for a in p.
        AmodA: A-runs with the same set of events migrate to equivalent states.
      - live_free_alo_exact, barrier_free_alo_exact: the free forms (CommND, IdemND, DS1,
        AbsorbFree, AmodFree).

   5. No switch (B = A, M and tau identities, only A-events): no_switch_exact (LiveD is the class's
      own convergence), and the gap 15 theorems as corollaries: causal_no_switch (causal_exact),
      alo_no_switch (alo_exact), declared_no_switch (tconv_exact), dalo_no_switch (dalo_exact).

   6. Finite instances (finite states and events on both sides, decidable state equality, decidable
