  assert (H0 : causal (hbA (@nohb (unit + bool))) []) by (split; [constructor | intros a b _ []]).
  specialize (H [] H0).
  assert (Hc : causal (hbB (@nohb (unit + bool))) ([] ++ [true; false])).
  { split; [repeat constructor; simpl; intuition discriminate | intros a b [] _ _]. }
