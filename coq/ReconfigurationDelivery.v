  specialize (H [true; false] [false; true]
                (Hc [true; false] ltac:(repeat constructor; simpl; intuition discriminate))
                (Hc [false; true] ltac:(repeat constructor; simpl; intuition discriminate)) (perm_swap false true [])).
  discriminate H.
Qed.

(* ---- Non-vacuity: a rescaled max-register, every condition of every class holding. ----
   A and B are max-registers, M doubles the state and tau doubles the event. *)
Definition rmA (a : nat) (s : nat) : nat := Nat.max s a.
Definition rmB (b : nat) (y : nat) : nat := Nat.max y b.
Definition rmM (s : nat) : nat := 2 * s.
Definition rmTau (a : nat) : nat := 2 * a.

Lemma max_swap : forall t a b, Nat.max (Nat.max t a) b = Nat.max (Nat.max t b) a.
Proof. intros t a b. rewrite <- !Nat.max_assoc, (Nat.max_comm a b). reflexivity. Qed.
Lemma max_idem : forall t a, Nat.max (Nat.max t a) a = Nat.max t a.
Proof. intros t a. rewrite <- Nat.max_assoc, Nat.max_id. reflexivity. Qed.

Lemma rm_run_ge : forall l s, runT rmA l s >= s.
Proof.
  induction l as [| a l IH]; intros s; [simpl; lia |]. rewrite runT_cons.
  pose proof (IH (rmA a s)). unfold rmA in *. pose proof (Nat.le_max_l s a). lia.
Qed.
Lemma rm_run_in : forall l s a, In a l -> runT rmA l s >= a.
Proof.
  induction l as [| x l IH]; intros s a H; [destruct H |]. rewrite runT_cons. destruct H as [-> | H].
  - pose proof (rm_run_ge l (rmA a s)). unfold rmA in *. pose proof (Nat.le_max_r s a). lia.
  - exact (IH _ a H).
Qed.
Lemma rm_run_mem : forall l s, runT rmA l s = s \/ In (runT rmA l s) l.
Proof.
  induction l as [| x l IH] using rev_ind; intros s; [left; reflexivity |].
  rewrite runT_app. change (runT rmA [x] (runT rmA l s)) with (Nat.max (runT rmA l s) x).
  destruct (Nat.max_dec (runT rmA l s) x) as [E1 | E1]; rewrite E1.
  - destruct (IH s) as [H | H]; [left; exact H | right; apply in_or_app; left; exact H].
  - right. apply in_or_app. right. left. reflexivity.
Qed.
Lemma rm_run_set : forall p1 p2 s, SameSet p1 p2 -> runT rmA p1 s = runT rmA p2 s.
Proof.
  intros p1 p2 s HS.
  assert (K : forall q1 q2, SameSet q1 q2 -> runT rmA q1 s <= runT rmA q2 s).
  { intros q1 q2 H. destruct (rm_run_mem q1 s) as [E1 | E1].
    - rewrite E1. apply rm_run_ge.
    - apply rm_run_in. apply H. exact E1. }
  apply Nat.le_antisymm; apply K; [exact HS | intros x; symmetry; apply HS].
Qed.

Lemma rm_ds1 : forall s0, DS1 rmA rmB eq rmM rmTau s0.
Proof. intros s0 u e. unfold rmA, rmB, rmM, rmTau. rewrite Nat.mul_max_distr_l. reflexivity. Qed.

Theorem rescaled_max : forall s0,
  ClassD rmA rmB eq rmM rmTau AdmF SameSet QA s0 Online /\
  (forall p, CommND rmB eq (rmM (runT rmA p s0)) /\ forall b, IdemND rmB eq (rmM (runT rmA p s0)) b) /\
  AbsorbFree rmA rmB eq rmM rmTau s0 /\ AmodFree rmA eq rmM s0 /\
  ClassD rmA rmB eq rmM rmTau (causal nohb) (@Permutation _) QT s0 Online /\
  ClassD rmA rmB eq rmM rmTau AdmF (tequiv (fun x y => x <> y)) QT s0 Online.
Proof.
  intros s0. split; [| split; [| split; [| split; [| split]]]].
  - simpl. apply (live_free_alo_exact Nat.eq_dec Nat.eq_dec rmA rmB eq eq_refl' eq_sym' eq_trans' (eq_ext' rmB)
                    rmM rmTau s0). split; [split | apply rm_ds1].
    + intros p a b _ _. apply max_swap.
    + intros x u _. apply max_idem.
  - intros p. split; [intros q a b _ _; apply max_swap | intros b u _; apply max_idem].
  - intros p v a Ha. unfold rmB at 1. apply Nat.max_l.
    change (runT rmB v (rmM (runT rmA p s0))) with (runT rmA v (rmM (runT rmA p s0))).
    pose proof (rm_run_ge v (rmM (runT rmA p s0))). pose proof (rm_run_in p s0 a Ha). unfold rmM, rmTau in *. lia.
  - intros p1 p2 HS. unfold rmM. rewrite (rm_run_set p1 p2 s0 HS). reflexivity.
  - simpl. apply (live_causal_exact rmA rmB eq eq_refl' eq_sym' eq_trans' (eq_ext' rmB) rmM rmTau nohb s0).
    split; [intros p a b _ _; apply max_swap | intros u a _; apply rm_ds1].
  - simpl. apply (live_declared_exact rmA rmB eq eq_refl' eq_sym' eq_trans' (eq_ext' rmB) rmM rmTau
                    (fun x y => x <> y) (fun x y H E1 => H (eq_sym E1)) s0).
    split; [intros w x y _; apply max_swap | apply rm_ds1].
Qed.

