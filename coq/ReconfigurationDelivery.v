(* Generic: trace convergence up to an equivalence, for an admissibility closed under prefixes and
   under swapping a declared pair. *)
Section TraceConv.
  Context {S E : Type}.
  Variable step : E -> S -> S.
  Variable eqv : S -> S -> Prop.
  Hypothesis eqv_refl : forall x, eqv x x.
  Hypothesis eqv_sym : forall x y, eqv x y -> eqv y x.
  Hypothesis eqv_trans : forall x y z, eqv x y -> eqv y z -> eqv x z.
  Hypothesis step_ext : forall e x y, eqv x y -> eqv (step e x) (step e y).
  Variable Adm : list E -> Prop.
  Variable I : E -> E -> Prop.
  Hypothesis I_sym : forall a b, I a b -> I b a.
  Hypothesis adm_prefix : forall l r, Adm (l ++ r) -> Adm l.
  Hypothesis adm_swap : forall l a b r, I a b -> Adm (l ++ a :: b :: r) -> Adm (l ++ b :: a :: r).

  Local Notation run := (runT step).

  Definition TConvS (y : S) : Prop :=
    forall w1 w2, Adm w1 -> Adm w2 -> tequiv I w1 w2 -> eqv (run w1 y) (run w2 y).

  (* Declared pairs commute after every admissible prefix. *)
  Definition CommS (y : S) : Prop :=
    forall p a b, Adm (p ++ [a; b]) -> I a b -> eqv (step b (step a (run p y))) (step a (step b (run p y))).

  Lemma run_ext_s : forall l x y, eqv x y -> eqv (run l x) (run l y).
  Proof.
    induction l as [| e l IH]; intros x y H; [exact H |].
    rewrite !runT_cons. apply IH. apply step_ext. exact H.
  Qed.

  Theorem trace_conv_s_exact : forall y, TConvS y <-> CommS y.
  Proof.
    intros y. split.
    - intros H p a b Ha Hab.
      pose proof (H (p ++ [a; b]) (p ++ [b; a]) Ha (adm_swap p a b [] Hab Ha) (teq_swap I p a b [] Hab)) as K.
      rewrite !runT_app in K. exact K.
    - intros H.
      assert (K : forall w1 w2, tequiv I w1 w2 -> Adm w1 -> eqv (run w1 y) (run w2 y)).
      { intros w1 w2 T. induction T as [l | l a b r Hab | l1 l2 T IH | l1 l2 l3 T1 IH1 T2 IH2]; intros Hw.
        - apply eqv_refl.
        - rewrite !runT_app, !runT_cons. apply run_ext_s. apply H; [| exact Hab].
          apply (adm_prefix _ r). rewrite <- app_assoc. exact Hw.
        - apply eqv_sym. apply IH. exact (proj2 (rd_tequiv_adm I Adm I_sym adm_swap _ _ T) Hw).
        - apply (eqv_trans _ _ _ (IH1 Hw)). apply IH2.
          exact (proj1 (rd_tequiv_adm I Adm I_sym adm_swap _ _ T1) Hw). }
      intros w1 w2 H1 _ T. exact (K w1 w2 T H1).
  Qed.
End TraceConv.

Section TraceSwitch.
  Context {SA EA SB EB : Type}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.

  (* The class: admissible sequences Adm of the combined alphabet, and the declared independence
     IX on it (a pair of A-events, of B-events, or an in-flight A-event and a B-event). *)
  Variable Adm : list (EA + EB) -> Prop.
  Variable IX : EA + EB -> EA + EB -> Prop.
  Hypothesis IX_sym : forall x y, IX x y -> IX y x.
  Hypothesis adm_prefix : forall l r, Adm (l ++ r) -> Adm l.
  Hypothesis adm_swap : forall l a b r, IX a b -> Adm (l ++ a :: b :: r) -> Adm (l ++ b :: a :: r).

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).
  Local Notation runX := (runT (stepX stepB tau)).

  Definition AdmA (p : list EA) : Prop := Adm (map inl p).
  Definition AdmB (v : list EB) : Prop := Adm (map inr v).
  Definition IA (a a' : EA) : Prop := IX (inl a) (inl a').
  Definition IB (b b' : EB) : Prop := IX (inr b) (inr b').

  Lemma stepX_ext : forall x y z, eqvB y z -> eqvB (stepX stepB tau x y) (stepX stepB tau x z).
  Proof. intros x y z H. apply stepB_ext. exact H. Qed.

  (* Live: the combined declared pairs commute after every admissible prefix from M s0, and S1. *)
  Theorem live_trace_exact : forall s0,
    LiveD stepA stepB eqvB M tau Adm (tequiv IX) s0 <->
    CommS (stepX stepB tau) eqvB Adm IX (M s0) /\ S1D stepA stepB eqvB M tau Adm s0.
  Proof.
    intros s0.
    rewrite (live_delivery_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau Adm
               (tequiv IX) adm_prefix (fun l _ => teq_refl IX l) s0).
    rewrite <- (trace_conv_s_exact (stepX stepB tau) eqvB eqvB_refl eqvB_sym eqvB_trans stepX_ext Adm IX
                  IX_sym adm_prefix adm_swap (M s0)).
    unfold ConvXD, TConvS. tauto.
  Qed.

  (* Barrier: B-events only after the switch. *)
  Definition QT (_ : list EA) (q : list (EA + EB)) : Prop := AllB q.

  (* The class does not tie B-events to A-events delivered before them. *)
  Hypothesis adm_split : forall p v, Adm (map inl p ++ map inr v) <-> AdmA p /\ AdmB v.

  Lemma admB_prefix : forall l r, AdmB (l ++ r) -> AdmB l.
  Proof. intros l r H. unfold AdmB in *. rewrite map_app in H. exact (adm_prefix _ _ H). Qed.

  Lemma admB_swap : forall l a b r, IB a b -> AdmB (l ++ a :: b :: r) -> AdmB (l ++ b :: a :: r).
  Proof. intros l a b r Hab H. unfold AdmB in *. rewrite map_app in *. simpl in *. apply adm_swap; assumption. Qed.

  Lemma admA_swap : forall l a b r, IA a b -> AdmA (l ++ a :: b :: r) -> AdmA (l ++ b :: a :: r).
  Proof. intros l a b r Hab H. unfold AdmA in *. rewrite map_app in *. simpl in *. apply adm_swap; assumption. Qed.

  Lemma IB_sym : forall a b, IB a b -> IB b a.
  Proof. intros a b H. apply IX_sym. exact H. Qed.
  Lemma IA_sym : forall a b, IA a b -> IA b a.
  Proof. intros a b H. apply IX_sym. exact H. Qed.

  Lemma glue_trace : Glue Adm (tequiv IX) QT.
  Proof.
    intros p1 q1 p2 q2 Q1 Q2 H1 H2 T.
    destruct (allB_ex q1 Q1) as [v1 ->]. destruct (allB_ex q2 Q2) as [v2 ->].
    pose proof (tequiv_projA IX _ _ T) as TA. rewrite !projA_app, !projA_inl, !projA_inr, !app_nil_r in TA.
    pose proof (tequiv_projB IX _ _ T) as TB. rewrite !projB_app, !projB_inl, !projB_inr in TB. simpl in TB.
    split; [exact (rd_tequiv_map inl IX p1 p2 TA) |]. split; [exact Q1 |]. split.
    - apply adm_split. split; [exact (proj1 (proj1 (adm_split p2 v2) H2)) | exact (proj2 (proj1 (adm_split p1 v1) H1))].
    - apply tequiv_app_l. exact (rd_tequiv_map inr IX v1 v2 TB).
  Qed.

  Lemma barB_trace_iff : forall s0,
    BarBD stepA stepB eqvB M tau Adm (tequiv IX) QT s0 <->
    forall p, AdmA p -> CommS stepB eqvB AdmB IB (M (runA p s0)).
  Proof.
    intros s0. split.
    - intros H p Hp. apply (trace_conv_s_exact stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext AdmB IB
                              IB_sym admB_prefix admB_swap).
      intros v1 v2 H1 H2 T. rewrite <- !(runX_inr stepB tau).
      apply (H p); [apply allB_map | apply allB_map | apply adm_split; split; assumption
                   | apply adm_split; split; assumption |].
      apply tequiv_app_l. exact (rd_tequiv_map inr IX v1 v2 T).
    - intros H p q1 q2 Q1 Q2 H1 H2 T.
      destruct (allB_ex q1 Q1) as [v1 ->]. destruct (allB_ex q2 Q2) as [v2 ->].
      apply adm_split in H1. apply adm_split in H2.
      pose proof (tequiv_projB IX _ _ T) as TB. rewrite !projB_app, !projB_inl, !projB_inr in TB. simpl in TB.
      rewrite !runX_inr.
      apply (proj2 (trace_conv_s_exact stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext AdmB IB
                      IB_sym admB_prefix admB_swap _) (H p (proj1 H1))); [exact (proj2 H1) | exact (proj2 H2) | exact TB].
  Qed.

  (* A converges under the class modulo M. *)
  Definition AmodT (s0 : SA) : Prop :=
    forall p1 p2, AdmA p1 -> AdmA p2 -> tequiv IA p1 p2 -> eqvB (M (runA p1 s0)) (M (runA p2 s0)).

  Lemma amodm_trace_iff : forall s0, AmodMD stepA eqvB M Adm (tequiv IX) s0 <-> AmodT s0.
  Proof.
    intros s0. split.
    - intros H p1 p2 H1 H2 T. apply H; [exact H1 | exact H2 | exact (rd_tequiv_map inl IX p1 p2 T)].
    - intros H p1 p2 H1 H2 T. apply H; [exact H1 | exact H2 |].
      pose proof (tequiv_projA IX _ _ T) as TA. rewrite !projA_inl in TA. exact TA.
  Qed.

  Theorem barrier_trace_exact : forall s0,
    BarD stepA stepB eqvB M tau Adm (tequiv IX) QT s0 <->
    (forall p, AdmA p -> CommS stepB eqvB AdmB IB (M (runA p s0))) /\ AmodT s0.
  Proof.
    intros s0.
    rewrite (barrier_delivery_exact stepA stepB eqvB eqvB_trans stepB_ext M tau Adm (tequiv IX) QT
               adm_prefix (fun p x H => match H with end) glue_trace s0).
    rewrite barB_trace_iff, amodm_trace_iff. tauto.
  Qed.

  (* The A part is generated by adjacent declared swaps (with any continuation). *)
  Theorem amodt_swap_exact : forall s0, AmodT s0 <->
    forall l a b r, AdmA (l ++ a :: b :: r) -> IA a b ->
      eqvB (M (runA (l ++ a :: b :: r) s0)) (M (runA (l ++ b :: a :: r) s0)).
  Proof.
    intros s0. split.
    - intros H l a b r Ha Hab. apply H; [exact Ha | exact (admA_swap l a b r Hab Ha) | apply teq_swap; exact Hab].
    - intros H.
      assert (K : forall p1 p2, tequiv IA p1 p2 -> AdmA p1 -> eqvB (M (runA p1 s0)) (M (runA p2 s0))).
      { intros p1 p2 T. induction T as [l | l a b r Hab | l1 l2 T IH | l1 l2 l3 T1 IH1 T2 IH2]; intros Hp.
        - apply eqvB_refl.
        - apply H; assumption.
        - apply eqvB_sym. apply IH. exact (proj2 (rd_tequiv_adm IA AdmA IA_sym admA_swap _ _ T) Hp).
        - apply (eqvB_trans _ _ _ (IH1 Hp)). apply IH2.
          exact (proj1 (rd_tequiv_adm IA AdmA IA_sym admA_swap _ _ T1) Hp). }
      intros p1 p2 H1 _ T. exact (K p1 p2 T H1).
  Qed.
End TraceSwitch.

(* ---- List facts for causal and causal at-least-once delivery. ---- *)

Lemma rd_nodup_app : forall {E : Type} (l r : list E),
  NoDup (l ++ r) <-> NoDup l /\ NoDup r /\ (forall x, In x l -> ~ In x r).
Proof.
  intros E l r. induction l as [| a l IH]; simpl.
  - split; [intros H; split; [constructor | split; [exact H | intros x []]] | intros [_ [H _]]; exact H].
  - rewrite !NoDup_cons_iff, IH, in_app_iff. split.
    + intros [Ha [Hl [Hr Hd]]]. split; [split; [tauto | exact Hl] |]. split; [exact Hr |].
      intros x [<- | Hx]; [tauto | apply Hd; exact Hx].
    + intros [[Ha Hl] [Hr Hd]]. split; [intros [H | H]; [exact (Ha H) | exact (Hd a (or_introl eq_refl) H)] |].
      split; [exact Hl |]. split; [exact Hr |]. intros x Hx. apply Hd. right. exact Hx.
Qed.

Lemma rd_prec_app_l : forall {E : Type} (a b : E) l r, prec a b r -> prec a b (l ++ r).
Proof. intros E a b l r H. induction l as [| x l IH]; [exact H |]. simpl. right. exact IH. Qed.

Lemma rd_prec_app_r : forall {E : Type} (a b : E) l r, prec a b l -> prec a b (l ++ r).
Proof.
  intros E a b l r. induction l as [| x l IH]; simpl; [intros [] |].
  intros [[Ex Hb] | H]; [left; split; [exact Ex | apply in_or_app; left; exact Hb] | right; exact (IH H)].
Qed.

Lemma rd_prec_cross : forall {E : Type} (a b : E) l r, In a l -> In b r -> prec a b (l ++ r).
Proof.
  intros E a b l r Ha Hb. induction l as [| x l IH]; [destruct Ha |]. simpl. destruct Ha as [-> | Ha].
  - left. split; [reflexivity | apply in_or_app; right; exact Hb].
  - right. exact (IH Ha).
Qed.

Lemma rd_prec_inv_l : forall {E : Type} (a b : E) l r,
  NoDup (l ++ r) -> prec a b (l ++ r) -> In b l -> a <> b -> prec a b l.
Proof.
  intros E a b l r. induction l as [| x l IH]; simpl; intros Hnd H Hb Hne; [destruct Hb |].
  apply NoDup_cons_iff in Hnd. destruct Hnd as [Hx Hnd].
  destruct H as [[Ex Hin] | H].
  - subst x. left. split; [reflexivity |]. destruct Hb as [Eb | Hb]; [congruence | exact Hb].
  - destruct Hb as [Eb | Hb].
    + subst x. exfalso. apply Hx. exact (prec_in_r _ _ _ H).
    + right. exact (IH Hnd H Hb Hne).
Qed.

Lemma rd_prec_inv_r : forall {E : Type} (a b : E) l r, NoDup (l ++ r) -> prec a b (l ++ r) -> In a r -> prec a b r.
Proof.
  intros E a b l r. induction l as [| x l IH]; simpl; intros Hnd H Ha; [exact H |].
  apply NoDup_cons_iff in Hnd. destruct Hnd as [Hx Hnd].
  destruct H as [[Ex _] | H].
  - subst x. exfalso. apply Hx. apply in_or_app. right. exact Ha.
  - exact (IH Hnd H Ha).
Qed.

(* A causally consistent concatenation: both parts, disjoint, nothing in r before something in l. *)
Lemma rd_causal_app : forall {E : Type} (hb : E -> E -> Prop) l r,
  causal hb (l ++ r) <-> causal hb l /\ causal hb r /\ (forall x, In x l -> ~ In x r) /\
    (forall x y, In x l -> In y r -> ~ hb y x).
Proof.
  intros E hb l r. unfold causal. rewrite rd_nodup_app. split.
  - intros [[Hl [Hr Hd]] Hc]. assert (Hnd : NoDup (l ++ r)) by (apply rd_nodup_app; tauto).
    split; [split; [exact Hl |] |]. 
    + intros a b Hab Ha Hb.
      assert (P : prec a b (l ++ r)) by (apply Hc; [exact Hab | apply in_or_app; left; exact Ha | apply in_or_app; left; exact Hb]).
      exact (rd_prec_inv_l a b l r Hnd P Hb (NC.AtLeastOnceDeclared.decl_prec_neq a b _ Hnd P)).
    + split; [split; [exact Hr |] |]; [| split; [exact Hd |]].
      * intros a b Hab Ha Hb. apply (rd_prec_inv_r a b l r Hnd); [| exact Ha].
        apply Hc; [exact Hab | apply in_or_app; right; exact Ha | apply in_or_app; right; exact Hb].
      * intros x y Hx Hy Hyx. apply (Hd x Hx).
        assert (P : prec y x (l ++ r)) by (apply Hc; [exact Hyx | apply in_or_app; right; exact Hy | apply in_or_app; left; exact Hx]).
        exact (prec_in_r _ _ _ (rd_prec_inv_r y x l r Hnd P Hy)).
  - intros [[Hl Cl] [[Hr Cr] [Hd Hx]]]. split; [tauto |].
    intros a b Hab Ha Hb. apply in_app_or in Ha. apply in_app_or in Hb.
    destruct Ha as [Ha | Ha]; destruct Hb as [Hb | Hb].
    + apply rd_prec_app_r. exact (Cl a b Hab Ha Hb).
    + exact (rd_prec_cross a b l r Ha Hb).
    + exfalso. exact (Hx b a Hb Ha Hab).
    + apply rd_prec_app_l. exact (Cr a b Hab Ha Hb).
Qed.

Lemma rd_causal_alo_app : forall {E : Type} (hb : E -> E -> Prop) l r,
  causal_alo hb (l ++ r) <-> causal_alo hb l /\ causal_alo hb r /\ (forall x y, In x l -> In y r -> ~ hb y x).
Proof.
  intros E hb l r. split.
  - intros H. split; [| split].
    + intros a b Hab l1 r1 E1 Hb Ha. apply (H a b Hab l1 (r1 ++ r)); [rewrite E1, <- app_assoc; reflexivity | exact Hb |].
      apply in_or_app. left. exact Ha.
    + intros a b Hab l1 r1 E1 Hb Ha. apply (H a b Hab (l ++ l1) r1); [rewrite E1, app_assoc; reflexivity | | exact Ha].
      apply in_or_app. right. exact Hb.
    + intros x y Hx Hy Hyx. exact (H y x Hyx l r eq_refl Hx Hy).
  - intros [Hl [Hr Hx]] a b Hab l1 r1 E1 Hb Ha.
    apply app_eq_app in E1. destruct E1 as [m [[-> ->] | [-> ->]]].
    + apply in_app_or in Ha. destruct Ha as [Ha | Ha].
      * exact (Hl a b Hab l1 m eq_refl Hb Ha).
      * exact (Hx b a (in_or_app _ _ _ (or_introl Hb)) Ha Hab).
    + apply in_app_or in Hb. destruct Hb as [Hb | Hb].
      * exact (Hx b a Hb (in_or_app _ _ _ (or_intror Ha)) Hab).
      * exact (Hr a b Hab m r1 eq_refl Hb Ha).
Qed.

Section MapInj.
  Context {E F : Type}.
  Variable f : E -> F.
  Hypothesis f_inj : forall x y, f x = f y -> x = y.

  Lemma rd_in_map_inj : forall a l, In (f a) (map f l) <-> In a l.
  Proof.
    intros a l. rewrite in_map_iff. split; [intros [a' [E1 H]]; rewrite <- (f_inj _ _ E1); exact H |].
    intros H. exists a. split; [reflexivity | exact H].
  Qed.

  Lemma rd_nodup_map_inj : forall l, NoDup (map f l) <-> NoDup l.
  Proof.
    induction l as [| x l IH]; simpl; [split; intros; constructor |].
    rewrite !NoDup_cons_iff, IH, rd_in_map_inj. tauto.
  Qed.

  Lemma rd_prec_map_inj : forall a b l, prec (f a) (f b) (map f l) <-> prec a b l.
  Proof.
    intros a b. induction l as [| x l IH]; simpl; [tauto |]. rewrite IH, rd_in_map_inj. split.
    - intros [[E1 H] | H]; [left; split; [exact (f_inj _ _ E1) | exact H] | right; exact H].
    - intros [[E1 H] | H]; [left; split; [rewrite E1; reflexivity | exact H] | right; exact H].
  Qed.

  Lemma rd_causal_map_inj : forall (hb : F -> F -> Prop) l,
    causal hb (map f l) <-> causal (fun a b => hb (f a) (f b)) l.
  Proof.
    intros hb l. unfold causal. rewrite rd_nodup_map_inj. split.
    - intros [Hnd Hc]. split; [exact Hnd |]. intros a b Hab Ha Hb. apply rd_prec_map_inj.
      apply Hc; [exact Hab | apply rd_in_map_inj; exact Ha | apply rd_in_map_inj; exact Hb].
    - intros [Hnd Hc]. split; [exact Hnd |]. intros x y Hxy Hx Hy.
      apply in_map_iff in Hx. destruct Hx as [a [<- Ha]]. apply in_map_iff in Hy. destruct Hy as [b [<- Hb]].
      apply rd_prec_map_inj. exact (Hc a b Hxy Ha Hb).
  Qed.

  Lemma rd_map_eq_app : forall l l1 r1, map f l = l1 ++ r1 ->
    exists l' r', l = l' ++ r' /\ l1 = map f l' /\ r1 = map f r'.
  Proof.
    induction l as [| x l IH]; intros l1 r1 H.
    - symmetry in H. apply app_eq_nil in H. destruct H as [-> ->]. exists [], []. split; [reflexivity | split; reflexivity].
    - destruct l1 as [| y l1].
      + exists [], (x :: l). split; [reflexivity | split; [reflexivity | symmetry; exact H]].
      + simpl in H. injection H as Hy H. destruct (IH l1 r1 H) as [l' [r' [-> [-> ->]]]].
        exists (x :: l'), r'. split; [reflexivity | split; [simpl; rewrite Hy; reflexivity | reflexivity]].
  Qed.

  Lemma rd_causal_alo_map_inj : forall (hb : F -> F -> Prop) l,
    causal_alo hb (map f l) <-> causal_alo (fun a b => hb (f a) (f b)) l.
  Proof.
    intros hb l. split.
    - intros H a b Hab l1 r1 E1 Hb Ha. apply (H (f a) (f b) Hab (map f l1) (map f r1)).
      + rewrite E1, map_app. reflexivity.
      + apply rd_in_map_inj. exact Hb.
      + apply rd_in_map_inj. exact Ha.
    - intros H x y Hxy l1 r1 E1 Hy Hx. destruct (rd_map_eq_app l l1 r1 E1) as [l' [r' [-> [-> ->]]]].
      apply in_map_iff in Hx. destruct Hx as [a [<- Ha]]. apply in_map_iff in Hy. destruct Hy as [b [<- Hb]].
      exact (H a b Hxy l' r' eq_refl Hb Ha).
  Qed.
End MapInj.

Lemma inl_inj : forall {EA EB : Type} (a a' : EA), @inl EA EB a = inl a' -> a = a'.
Proof. intros EA EB a a' H. injection H as H. exact H. Qed.
Lemma inr_inj : forall {EA EB : Type} (b b' : EB), @inr EA EB b = inr b' -> b = b'.
Proof. intros EA EB b b' H. injection H as H. exact H. Qed.

(* Causal delivery across the switch: Rel = Permutation over causally consistent sequences of the
   combined alphabet, hbX a happens-before on it in which no B-event precedes an A-event. *)
Section CausalSwitch.
  Context {SA EA SB EB : Type}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.
  Variable hbX : EA + EB -> EA + EB -> Prop.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).
  Local Notation runX := (runT (stepX stepB tau)).

  Definition hbA (a a' : EA) : Prop := hbX (inl a) (inl a').
  Definition hbB (b b' : EB) : Prop := hbX (inr b) (inr b').

  Lemma causal_inl : forall p, causal hbX (map inl p) <-> causal hbA p.
  Proof. intros p. exact (rd_causal_map_inj inl inl_inj hbX p). Qed.
  Lemma causal_inr : forall v, causal hbX (map inr v) <-> causal hbB v.
  Proof. intros v. exact (rd_causal_map_inj inr inr_inj hbX v). Qed.

  Lemma concurrent_inr : forall a b, concurrent hbX (inr a) (inr b) <-> concurrent hbB a b.
  Proof.
    intros a b. unfold concurrent, hbB. split; intros [H1 H2]; split; try exact H2.
    - intros ->. apply H1. reflexivity.
    - intros E1. apply H1. exact (inr_inj _ _ E1).
  Qed.
  Lemma concurrent_inl : forall a b, concurrent hbX (inl a) (inl b) <-> concurrent hbA a b.
  Proof.
    intros a b. unfold concurrent, hbA. split; intros [H1 H2]; split; try exact H2.
    - intros ->. apply H1. reflexivity.
    - intros E1. apply H1. exact (inl_inj _ _ E1).
  Qed.

  Lemma causal_swap_conc : forall l a b r, concurrent hbX a b ->
    causal hbX (l ++ a :: b :: r) -> causal hbX (l ++ b :: a :: r).
  Proof.
    intros l a b r [_ [Hab _]] H. exact (NC.GovernanceConverse.causal_swap hbX l a b r Hab H).
  Qed.

  Lemma rel_causal : forall w1 w2, causal hbX w1 -> causal hbX w2 ->
    (Permutation w1 w2 <-> tequiv (concurrent hbX) w1 w2).
  Proof.
    intros w1 w2 H1 H2. split; [apply causal_tequiv; assumption | apply tequiv_perm].
  Qed.

  (* S1 at the causally consistent A-prefixes. *)
  Definition S1C (s0 : SA) : Prop :=
    forall u a, causal hbA (u ++ [a]) -> eqvB (M (stepA a (runA u s0))) (stepB (tau a) (M (runA u s0))).

  Theorem live_causal_exact : forall s0,
    LiveD stepA stepB eqvB M tau (causal hbX) (@Permutation _) s0 <->
    NC.DistributedDelivery.CCRonS (stepX stepB tau) hbX eqvB (M s0) /\ S1C s0.
  Proof.
    intros s0. rewrite (liveD_rel_ext stepA stepB eqvB M tau (causal hbX) _ (tequiv (concurrent hbX)) rel_causal s0).
    rewrite (live_trace_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau (causal hbX)
               (concurrent hbX) (concurrent_sym hbX) (NC.GovernanceConverse.causal_prefix hbX) causal_swap_conc s0).
    unfold CommS, NC.DistributedDelivery.CCRonS, S1D, S1C. split; intros [H1 H2]; split.
    - intros p a b Hab Hc. exact (H1 p a b Hc Hab).
    - intros u a Hc. apply H2. apply causal_inl. exact Hc.
    - intros p a b Hc Hab. exact (H1 p a b Hab Hc).
    - intros u a Hc. apply H2. apply causal_inl. exact Hc.
  Qed.

  Hypothesis hb_BA : forall a b, ~ hbX (inr b) (inl a).

  Lemma causal_split : forall p v,
    causal hbX (map inl p ++ map inr v) <-> AdmA (causal hbX) p /\ AdmB (causal hbX) v.
  Proof.
    intros p v. unfold AdmA, AdmB. rewrite rd_causal_app. split; [tauto |].
    intros [H1 H2]. split; [exact H1 | split; [exact H2 | split]].
    - intros x Hx Hx'. apply in_map_iff in Hx. destruct Hx as [a [<- _]]. exact (not_in_inl_inr v a Hx').
    - intros x y Hx Hy. apply in_map_iff in Hx. destruct Hx as [a [<- _]].
      apply in_map_iff in Hy. destruct Hy as [b [<- _]]. apply hb_BA.
  Qed.

  (* A converges causally modulo M. *)
  Definition AmodC (s0 : SA) : Prop :=
    forall p1 p2, causal hbA p1 -> causal hbA p2 -> Permutation p1 p2 -> eqvB (M (runA p1 s0)) (M (runA p2 s0)).

  Theorem barrier_causal_exact : forall s0,
    BarD stepA stepB eqvB M tau (causal hbX) (@Permutation _) QT s0 <->
    (forall p, causal hbA p -> NC.DistributedDelivery.CCRonS stepB hbB eqvB (M (runA p s0))) /\ AmodC s0.
  Proof.
    intros s0. rewrite (barD_rel_ext stepA stepB eqvB M tau (causal hbX) _ (tequiv (concurrent hbX)) QT rel_causal s0).
    rewrite (barrier_trace_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau (causal hbX)
               (concurrent hbX) (concurrent_sym hbX) (NC.GovernanceConverse.causal_prefix hbX) causal_swap_conc
               causal_split s0).
    assert (KB : forall y, CommS stepB eqvB (AdmB (causal hbX)) (IB (concurrent hbX)) y <->
                        NC.DistributedDelivery.CCRonS stepB hbB eqvB y).
    { intros y. unfold CommS, NC.DistributedDelivery.CCRonS, AdmB, IB. split.
      - intros H p a b Hab Hc. apply H; [apply causal_inr; exact Hc | apply concurrent_inr; exact Hab].
      - intros H p a b Hc Hab. apply H; [apply concurrent_inr; exact Hab | apply causal_inr; exact Hc]. }
    assert (KA : AmodT stepA eqvB M (causal hbX) (concurrent hbX) s0 <-> AmodC s0).
    { unfold AmodT, AmodC, AdmA. split.
      - intros H p1 p2 H1 H2 P. apply causal_inl in H1. apply causal_inl in H2. apply H; [exact H1 | exact H2 |].
        apply (NC.AtLeastOnceDeclared.decl_tequiv_mono (concurrent hbA)).
        + intros a b Hab. apply concurrent_inl. exact Hab.
        + apply causal_tequiv; [apply causal_inl; exact H1 | apply causal_inl; exact H2 | exact P].
      - intros H p1 p2 H1 H2 T. apply H; [apply causal_inl; exact H1 | apply causal_inl; exact H2 |].
        exact (tequiv_perm _ _ _ T). }
    split.
    - intros [H1 H2]. split; [| apply KA; exact H2].
      intros p Hp. apply KB. apply H1. apply causal_inl. exact Hp.
    - intros [H1 H2]. split; [| apply KA; exact H2].
      intros p Hp. apply KB. apply H1. apply causal_inl. exact Hp.
  Qed.
End CausalSwitch.

