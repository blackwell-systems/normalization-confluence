(* Reachability in a finite successor graph closed on a finite universe. *)
Section ClosureIn.
  Context {X : Type}.
  Variable eqX : forall a b : X, {a = b} + {a <> b}.
  Variable all : list X.
  Variable succ : X -> list X.
  Hypothesis succ_closed : forall a b, In a all -> In b (succ a) -> In b all.

  Lemma layer_in : forall x0 k z, In x0 all -> In z (layer succ x0 k) -> In z all.
  Proof.
    intros x0 k. induction k as [| k IH]; intros z Hx0 Hz; simpl in Hz.
    - destruct Hz as [<- | []]. exact Hx0.
    - apply in_app_or in Hz. destruct Hz as [Hz | Hz]; [exact (IH z Hx0 Hz) |].
      apply in_flat_map in Hz. destruct Hz as [a [Ha Hz]]. exact (succ_closed a z (IH a Hx0 Ha) Hz).
  Qed.

  Lemma closed_or_grow_in : forall x0, In x0 all -> forall k,
    (exists j, j <= k /\ closedL succ (layer succ x0 j)) \/ S k <= cnt eqX all (layer succ x0 k).
  Proof.
    intros x0 Hx0 k. induction k as [| k IH].
    - right. pose proof (cnt_lt eqX all [] (layer succ x0 0) x0 (fun z H => match H with end)
                           Hx0 (or_introl eq_refl) (fun H => H)) as H. lia.
    - destruct IH as [[j [Hj Hc]] | IH]; [left; exists j; split; [lia | exact Hc] |].
      assert (Dsucc : forall a, ((forall b, In b (succ a) -> In b (layer succ x0 k)) +
                                {b : X | In b (succ a) /\ ~ In b (layer succ x0 k)})%type).
      { intros a. exact (list_forall_or_witness (fun b => In b (layer succ x0 k)) (succ a)
                           (fun b => in_dec eqX b _)). }
      destruct (list_forall_or_witness (fun a => forall b, In b (succ a) -> In b (layer succ x0 k))
                  (layer succ x0 k)) as [Hc | [a [Ha Hn]]].
      + intros a. destruct (Dsucc a) as [H | [b [Hb Hnb]]]; [left; exact H |].
        right. intro H. exact (Hnb (H b Hb)).
      + left. exists k. split; [lia | intros a b Ha Hb; exact (Hc a Ha b Hb)].
      + destruct (Dsucc a) as [H | [b [Hb Hnb]]]; [exfalso; exact (Hn H) |].
        right. pose proof (cnt_lt eqX all (layer succ x0 k) (layer succ x0 (S k)) b (layer_sub succ x0 k)
                             (layer_in x0 (S k) b Hx0 (layer_succ succ x0 k a b Ha Hb))
                             (layer_succ succ x0 k a b Ha Hb) Hnb). lia.
  Qed.

  Lemma closed_layer_in : forall x0, In x0 all -> exists j, j <= length all /\ closedL succ (layer succ x0 j).
  Proof.
    intros x0 Hx0. destruct (closed_or_grow_in x0 Hx0 (length all)) as [H | H]; [exact H |].
    exfalso. pose proof (cnt_bound eqX all (layer succ x0 (length all))). lia.
  Qed.

  Theorem star_in_iff : forall x0 y, In x0 all -> (star (Rsucc succ) x0 y <-> In y (layer succ x0 (length all))).
  Proof.
    intros x0 y Hx0. split.
    - intros S. destruct (closed_layer_in x0 Hx0) as [j [Hj Hc]].
      apply (layer_sub_le succ x0 j (length all) Hj).
      apply (NC.GovernanceConverse.star_closed (Rsucc succ) (fun z => In z (layer succ x0 j))
               (fun a b Ha Hb => Hc a b Ha Hb) x0 y (layer_x0 succ x0 j) S).
    - apply layer_sound.
  Qed.

  Theorem star_in_dec : forall x0 y, In x0 all -> {star (Rsucc succ) x0 y} + {~ star (Rsucc succ) x0 y}.
  Proof.
    intros x0 y Hx0. destruct (in_dec eqX y (layer succ x0 (length all))) as [H | H].
    - left. apply (star_in_iff x0 y Hx0). exact H.
    - right. rewrite (star_in_iff x0 y Hx0). exact H.
  Qed.
End ClosureIn.

(* Canonical delivered sets: the elements of allX in D, in allX's order. *)
Section Canon.
  Context {X : Type}.
  Variable eqX : forall a b : X, {a = b} + {a <> b}.
  Variable allX : list X.
  Hypothesis allX_full : forall x, In x allX.

  Definition canon (D : list X) : list X := filter (fun z => inb eqX z D) allX.

  Lemma canon_in : forall D z, In z (canon D) <-> In z D.
  Proof.
    intros D z. unfold canon. rewrite filter_In, inb_iff. split; [tauto |].
    intros H. split; [apply allX_full | exact H].
  Qed.

  Lemma canon_ext : forall D D', (forall z, In z D <-> In z D') -> canon D = canon D'.
  Proof.
    intros D D' H. unfold canon. generalize allX as l. intros l. induction l as [| x l IH]; [reflexivity |]. simpl. rewrite IH.
    destruct (inb eqX x D) eqn:E1; destruct (inb eqX x D') eqn:E2; try reflexivity.
    - apply inb_iff in E1. apply H in E1. rewrite (proj2 (inb_iff eqX x D') E1) in E2. discriminate E2.
    - apply inb_iff in E2. apply H in E2. rewrite (proj2 (inb_iff eqX x D) E2) in E1. discriminate E1.
  Qed.

  Fixpoint subs (l : list X) : list (list X) :=
    match l with
    | [] => [[]]
    | x :: l' => map (cons x) (subs l') ++ subs l'
    end.

  Lemma filter_subs : forall (f : X -> bool) l, In (filter f l) (subs l).
  Proof.
    intros f. induction l as [| x l IH]; simpl; [left; reflexivity |].
    destruct (f x); apply in_or_app; [left; apply in_map; exact IH | right; exact IH].
  Qed.

End Canon.

(* A class monitored by the set of delivered events: the next event x is admissible after the
   delivered list D iff ok D x, and ok depends only on the elements of D. *)
Section Monitor.
  Context {S X : Type}.
  Variable eqX : forall a b : X, {a = b} + {a <> b}.
  Variable allX : list X.
  Hypothesis allX_full : forall x, In x allX.
  Variable eqS : forall a b : S, {a = b} + {a <> b}.
  Variable allS : list S.
  Hypothesis allS_full : forall s, In s allS.
  Variable step : X -> S -> S.
  Variable ok : list X -> X -> Prop.
  Hypothesis ok_dec : forall D x, {ok D x} + {~ ok D x}.
  Hypothesis ok_ext : forall D D' x, (forall z, In z D <-> In z D') -> ok D x -> ok D' x.

  Local Notation run := (runT step).

  Definition admFrom (D0 w : list X) : Prop := forall l x r, w = l ++ x :: r -> ok (D0 ++ l) x.

  Lemma admFrom_nil : forall D0, admFrom D0 [].
  Proof. intros D0 l x r E1. destruct l; discriminate E1. Qed.

  Lemma admFrom_snoc : forall D0 w x, admFrom D0 (w ++ [x]) <-> admFrom D0 w /\ ok (D0 ++ w) x.
  Proof.
    intros D0 w x. split.
    - intros H. split.
      + intros l y r E1. apply (H l y (r ++ [x])). rewrite E1, <- app_assoc. reflexivity.
      + apply (H w x []). reflexivity.
    - intros [H Hx] l y r E1. destruct (rev_case r) as [-> | [z [r' ->]]].
      + apply app_inj_tail in E1. destruct E1 as [-> ->]. exact Hx.
      + replace (l ++ y :: r' ++ [z]) with ((l ++ y :: r') ++ [z]) in E1 by (rewrite <- app_assoc; reflexivity).
        apply app_inj_tail in E1. destruct E1 as [E1 _]. exact (H l y r' E1).
  Qed.

  Local Notation canon := (canon eqX allX).
  Lemma canon_subs : forall D, In (canon D) (subs allX).
  Proof. intros D. apply filter_subs. Qed.
  Local Notation canon_in := (canon_in eqX allX allX_full).
  Local Notation canon_ext := (canon_ext eqX allX).

  Definition msucc (c : S * list X) : list (S * list X) :=
    flat_map (fun x => if ok_dec (snd c) x then [(step x (fst c), canon (x :: snd c))] else []) allX.

  Definition univ : list (S * list X) := list_prod allS (subs allX).

  Lemma msucc_iff : forall s D t D', In (t, D') (msucc (s, D)) <->
    exists x, ok D x /\ t = step x s /\ D' = canon (x :: D).
  Proof.
    intros s D t D'. unfold msucc. rewrite in_flat_map. simpl. split.
    - intros [x [_ Hx]]. destruct (ok_dec D x) as [Ho | Ho]; [| destruct Hx].
      destruct Hx as [E1 | []]. injection E1 as <- <-. exists x. split; [exact Ho | split; reflexivity].
    - intros [x [Ho [-> ->]]]. exists x. split; [apply allX_full |].
      destruct (ok_dec D x) as [_ | N]; [left; reflexivity | contradiction].
  Qed.

  Lemma msucc_closed : forall c c', In c univ -> In c' (msucc c) -> In c' univ.
  Proof.
    intros [s D] [t D'] _ H. apply msucc_iff in H. destruct H as [x [_ [-> ->]]].
    apply in_prod; [apply allS_full | apply canon_subs].
  Qed.

  Theorem mreach_iff : forall D0 y t D,
    (exists w, admFrom D0 w /\ t = run w y /\ D = canon (D0 ++ w)) <-> star (Rsucc msucc) (y, canon D0) (t, D).
  Proof.
    intros D0 y t D. split.
    - intros [w [Hw [-> ->]]]. revert Hw. induction w as [| x w IH] using rev_ind; intros Hw.
      + rewrite app_nil_r. apply star_refl.
      + apply admFrom_snoc in Hw. destruct Hw as [Hw Hx]. eapply star_trans; [exact (IH Hw) |]. apply star_one.
        unfold Rsucc. apply msucc_iff. exists x. split; [apply (ok_ext (D0 ++ w)); [| exact Hx] |].
        * intros z. symmetry. apply canon_in.
        * split; [rewrite runT_app; reflexivity |]. apply canon_ext. intros z. simpl.
          rewrite canon_in, !in_app_iff. simpl. tauto.
    - intros H.
      refine (NC.GovernanceConverse.star_closed (Rsucc msucc)
                (fun c => exists w, admFrom D0 w /\ fst c = run w y /\ snd c = canon (D0 ++ w)) _
                (y, canon D0) (t, D) _ H).
      + intros [s1 D1] [s2 D2] [w [Hw [E1 E2]]] Hs. simpl in *. apply msucc_iff in Hs.
        destruct Hs as [x [Hx [-> ->]]]. exists (w ++ [x]). split; [| split].
        * apply admFrom_snoc. split; [exact Hw |]. apply (ok_ext D1); [| exact Hx].
          intros z. rewrite E2, canon_in. reflexivity.
        * rewrite runT_app, E1. reflexivity.
        * apply canon_ext. intros z. simpl. rewrite E2, canon_in, !in_app_iff. simpl. tauto.
      + exists []. split; [apply admFrom_nil | split; [reflexivity | rewrite app_nil_r; reflexivity]].
  Qed.

  Theorem mforall_dec : forall D0 y (P : S -> list X -> Prop), (forall t D, {P t D} + {~ P t D}) ->
    {forall w, admFrom D0 w -> P (run w y) (canon (D0 ++ w))} +
    {~ forall w, admFrom D0 w -> P (run w y) (canon (D0 ++ w))}.
  Proof.
    intros D0 y P Hd.
    assert (Hu : In (y, canon D0) univ) by (apply in_prod; [apply allS_full | apply canon_subs]).
    assert (Iff : (forall c, In c univ -> star (Rsucc msucc) (y, canon D0) c -> P (fst c) (snd c)) <->
                  (forall w, admFrom D0 w -> P (run w y) (canon (D0 ++ w)))).
    { split.
      - intros H w Hw. apply (H (run w y, canon (D0 ++ w))); [apply in_prod; [apply allS_full | apply canon_subs] |].
        apply mreach_iff. exists w. split; [exact Hw | split; reflexivity].
      - intros H [t D] _ Hs. apply mreach_iff in Hs. destruct Hs as [w [Hw [-> ->]]]. apply H. exact Hw. }
    apply (dec_iff _ _ Iff).
    destruct (list_forall_or_witness (fun c => star (Rsucc msucc) (y, canon D0) c -> P (fst c) (snd c)) univ)
      as [H | [c [Hc Hn]]].
    - intros c. apply dec_imp; [| apply Hd].
      exact (star_in_dec (prod_eq_dec eqS (list_eq_dec eqX)) univ msucc msucc_closed (y, canon D0) c Hu).
    - left. exact H.
    - right. intro H. exact (Hn (H c Hc)).
  Qed.
End Monitor.

Definition okC {E : Type} (hb : E -> E -> Prop) (D : list E) (x : E) : Prop :=
  ~ In x D /\ forall z, In z D -> ~ hb x z.
Definition okCA {E : Type} (hb : E -> E -> Prop) (D : list E) (x : E) : Prop :=
  forall z, In z D -> ~ hb x z.

Lemma causal_one : forall {E : Type} (hb : E -> E -> Prop), (forall x, ~ hb x x) -> forall x, causal hb [x].
Proof.
  intros E hb Hirr x. split; [constructor; [intros [] | constructor] |].
  intros a b Hab [<- | []] [<- | []]. exfalso. eapply Hirr. exact Hab.
Qed.

Lemma causal_snoc_iff : forall {E : Type} (hb : E -> E -> Prop), (forall x, ~ hb x x) ->
  forall w x, causal hb (w ++ [x]) <-> causal hb w /\ okC hb w x.
Proof.
  intros E hb Hirr w x. rewrite rd_causal_app. unfold okC. split.
  - intros [H1 [_ [H3 H4]]]. split; [exact H1 | split].
    + intros Hx. exact (H3 x Hx (or_introl eq_refl)).
    + intros z Hz Hh. exact (H4 z x Hz (or_introl eq_refl) Hh).
  - intros [H1 [H2 H3]]. split; [exact H1 | split; [apply causal_one; exact Hirr | split]].
    + intros y Hy [<- | []]. exact (H2 Hy).
    + intros y z Hy [<- | []]. exact (H3 y Hy).
Qed.

Lemma alo_snoc_iff : forall {E : Type} (hb : E -> E -> Prop) w x,
  causal_alo hb (w ++ [x]) <-> causal_alo hb w /\ okCA hb w x.
Proof.
  intros E hb w x. rewrite rd_causal_alo_app. unfold okCA. split.
  - intros [H1 [_ H3]]. split; [exact H1 |]. intros z Hz Hh. exact (H3 z x Hz (or_introl eq_refl) Hh).
  - intros [H1 H2]. split; [exact H1 | split; [apply rd_causal_alo_one |]].
    intros y z Hy [<- | []]. exact (H2 y Hy).
Qed.

Lemma okC_ext : forall {E : Type} (hb : E -> E -> Prop) D D' x, (forall z, In z D <-> In z D') -> okC hb D x -> okC hb D' x.
Proof.
  intros E hb D D' x H [H1 H2]. split; [intros Hx; apply H1; apply H; exact Hx |].
  intros z Hz. apply H2. apply H. exact Hz.
Qed.
Lemma okCA_ext : forall {E : Type} (hb : E -> E -> Prop) D D' x, (forall z, In z D <-> In z D') -> okCA hb D x -> okCA hb D' x.
Proof. intros E hb D D' x H H2 z Hz. apply H2. apply H. exact Hz. Qed.

Lemma forall_in_dec : forall {E : Type} (P : E -> Prop) (l : list E), (forall x, {P x} + {~ P x}) ->
  {forall x, In x l -> P x} + {~ forall x, In x l -> P x}.
Proof.
  intros E P l Hd. destruct (list_forall_or_witness P l Hd) as [H | [x [Hx Hn]]]; [left; exact H |].
  right. intro H. exact (Hn (H x Hx)).
Qed.

Section FiniteClass.
  Context {S E : Type}.
  Variable decE : forall x y : E, {x = y} + {x <> y}.
  Variable evs : list E.
  Hypothesis evs_full : forall e, In e evs.
  Variable eqS : forall a b : S, {a = b} + {a <> b}.
  Variable allS : list S.
  Hypothesis allS_full : forall s, In s allS.
  Variable step : E -> S -> S.
  Variable hb : E -> E -> Prop.
  Hypothesis hb_irrefl : forall x, ~ hb x x.
  Hypothesis hb_dec : forall x y, {hb x y} + {~ hb x y}.

  Local Notation run := (runT step).

  Lemma okC_dec : forall D x, {okC hb D x} + {~ okC hb D x}.
  Proof.
    intros D x. unfold okC. apply dec_and; [apply dec_not; apply in_dec; exact decE |].
    apply forall_in_dec. intros z. apply dec_not. apply hb_dec.
  Qed.
  Lemma okCA_dec : forall D x, {okCA hb D x} + {~ okCA hb D x}.
  Proof. intros D x. apply forall_in_dec. intros z. apply dec_not. apply hb_dec. Qed.

  Lemma causal_mon : forall w, causal hb w <-> admFrom (okC hb) [] w.
  Proof.
    induction w as [| x w IH] using rev_ind.
    - split; intros _; [apply admFrom_nil | split; [constructor | intros a b _ []]].
    - rewrite causal_snoc_iff by exact hb_irrefl. rewrite admFrom_snoc, IH. simpl. reflexivity.
  Qed.

  Lemma alo_mon : forall w, causal_alo hb w <-> admFrom (okCA hb) [] w.
  Proof.
    induction w as [| x w IH] using rev_ind.
    - split; intros _; [apply admFrom_nil | intros a b _ l r E1 Hb _; destruct l; [destruct Hb | discriminate E1]].
    - rewrite alo_snoc_iff, admFrom_snoc, IH. simpl. reflexivity.
  Qed.

  Theorem causal_forall_dec : forall y (P : S -> list E -> Prop), (forall t D, {P t D} + {~ P t D}) ->
    (forall t D D', (forall z, In z D <-> In z D') -> P t D -> P t D') ->
    {forall p, causal hb p -> P (run p y) p} + {~ forall p, causal hb p -> P (run p y) p}.
  Proof.
    intros y P Hd Hext.
    assert (Iff : (forall w, admFrom (okC hb) [] w -> P (run w y) (canon decE evs ([] ++ w))) <->
                  (forall p, causal hb p -> P (run p y) p)).
    { split.
      - intros H p Hp. apply (Hext _ (canon decE evs ([] ++ p))); [intros z; rewrite (canon_in decE evs evs_full); reflexivity |].
        apply H. apply causal_mon. exact Hp.
      - intros H w Hw. apply (Hext _ w); [intros z; rewrite (canon_in decE evs evs_full); reflexivity |].
        apply H. apply causal_mon. exact Hw. }
    apply (dec_iff _ _ Iff).
    exact (mforall_dec decE evs evs_full eqS allS allS_full step (okC hb) okC_dec (okC_ext hb) [] y P Hd).
  Qed.

  Theorem alo_forall_dec : forall y (P : S -> list E -> Prop), (forall t D, {P t D} + {~ P t D}) ->
    (forall t D D', (forall z, In z D <-> In z D') -> P t D -> P t D') ->
    {forall p, causal_alo hb p -> P (run p y) p} + {~ forall p, causal_alo hb p -> P (run p y) p}.
  Proof.
    intros y P Hd Hext.
    assert (Iff : (forall w, admFrom (okCA hb) [] w -> P (run w y) (canon decE evs ([] ++ w))) <->
                  (forall p, causal_alo hb p -> P (run p y) p)).
    { split.
      - intros H p Hp. apply (Hext _ (canon decE evs ([] ++ p))); [intros z; rewrite (canon_in decE evs evs_full); reflexivity |].
        apply H. apply alo_mon. exact Hp.
      - intros H w Hw. apply (Hext _ w); [intros z; rewrite (canon_in decE evs evs_full); reflexivity |].
        apply H. apply alo_mon. exact Hw. }
    apply (dec_iff _ _ Iff).
    exact (mforall_dec decE evs evs_full eqS allS allS_full step (okCA hb) okCA_dec (okCA_ext hb) [] y P Hd).
  Qed.

  Lemma sameset_dec : forall D D' : list E, {SameSet D D'} + {~ SameSet D D'}.
  Proof.
    intros D D'.
    assert (Iff : ((forall z, In z D -> In z D') /\ (forall z, In z D' -> In z D)) <-> SameSet D D').
    { unfold SameSet. split; [intros [H1 H2] z; split; [apply H1 | apply H2] | intros H; split; intros z; apply H]. }
    apply (dec_iff _ _ Iff). apply dec_and; apply forall_in_dec; intros z; apply in_dec; exact decE.
  Qed.

  Variable eqv : S -> S -> Prop.
  Hypothesis eqv_dec : forall x y, {eqv x y} + {~ eqv x y}.

  Definition concurrent_dec : forall a b, {concurrent hb a b} + {~ concurrent hb a b}.
  Proof.
    intros a b. unfold concurrent. apply dec_and; [apply dec_not; apply decE |].
    apply dec_and; apply dec_not; apply hb_dec.
  Defined.

  Theorem ccr_s_dec : forall y,
    {NC.DistributedDelivery.CCRonS step hb eqv y} + {~ NC.DistributedDelivery.CCRonS step hb eqv y}.
  Proof.
    intros y.
    pose (Pc := fun t D => forall a b, In a evs -> In b evs -> concurrent hb a b -> okC hb D a -> okC hb (D ++ [a]) b ->
                  eqv (step b (step a t)) (step a (step b t))).
    assert (Iff : (forall p, causal hb p -> Pc (run p y) p) <-> NC.DistributedDelivery.CCRonS step hb eqv y).
    { unfold Pc, NC.DistributedDelivery.CCRonS. split.
      - intros H p a b Hab Hc. replace (p ++ [a; b]) with ((p ++ [a]) ++ [b]) in Hc by (rewrite <- app_assoc; reflexivity).
        apply (causal_snoc_iff hb hb_irrefl) in Hc. destruct Hc as [Hc Hb].
        apply (causal_snoc_iff hb hb_irrefl) in Hc. destruct Hc as [Hc Ha].
        exact (H p Hc a b (evs_full a) (evs_full b) Hab Ha Hb).
      - intros H p Hp a b _ _ Hab Ha Hb. apply H; [exact Hab |].
        replace (p ++ [a; b]) with ((p ++ [a]) ++ [b]) by (rewrite <- app_assoc; reflexivity).
        apply causal_snoc_iff; [exact hb_irrefl |]. split; [| exact Hb].
        apply causal_snoc_iff; [exact hb_irrefl |]. split; assumption. }
    apply (dec_iff _ _ Iff). apply causal_forall_dec.
    - intros t D. unfold Pc. apply (dec_forall_fin evs evs_full). intros a. apply (dec_forall_fin evs evs_full). intros b.
      apply dec_imp; [apply in_dec; exact decE |]. apply dec_imp; [apply in_dec; exact decE |].
      apply dec_imp; [apply concurrent_dec |]. apply dec_imp; [apply okC_dec |]. apply dec_imp; [apply okC_dec | apply eqv_dec].
    - intros t D D' HD H a b Ha Hb Hab H1 H2. apply H; try assumption.
      + apply (okC_ext hb D'); [intros z; symmetry; apply HD | exact H1].
      + apply (okC_ext hb (D' ++ [a])); [| exact H2]. intros z. rewrite !in_app_iff. rewrite HD. reflexivity.
  Qed.

  Theorem idem_s_dec : forall y,
    {forall a, NC.DistributedDelivery.IdemAtS step hb eqv y a} + {~ forall a, NC.DistributedDelivery.IdemAtS step hb eqv y a}.
  Proof.
    intros y.
    pose (Pi := fun t D => forall a, In a evs -> okC hb D a -> eqv (step a (step a t)) (step a t)).
    assert (Iff : (forall p, causal hb p -> Pi (run p y) p) <-> forall a, NC.DistributedDelivery.IdemAtS step hb eqv y a).
    { unfold Pi, NC.DistributedDelivery.IdemAtS. split.
      - intros H a u Hc. apply (causal_snoc_iff hb hb_irrefl) in Hc. destruct Hc as [Hc Ha].
        exact (H u Hc a (evs_full a) Ha).
      - intros H p Hp a _ Ha. apply H. apply causal_snoc_iff; [exact hb_irrefl | split; assumption]. }
    apply (dec_iff _ _ Iff). apply causal_forall_dec.
    - intros t D. unfold Pi. apply (dec_forall_fin evs evs_full). intros a.
      apply dec_imp; [apply in_dec; exact decE |]. apply dec_imp; [apply okC_dec | apply eqv_dec].
    - intros t D D' HD H a Ha H1. apply H; [exact Ha |]. apply (okC_ext hb D'); [intros z; symmetry; apply HD | exact H1].
  Qed.

  (* Pairs of runs over the same events: for causal orders, Permutation is the same set. *)
  Theorem causal_pairs_dec : forall y (R : S -> S -> Prop), (forall s t, {R s t} + {~ R s t}) ->
    {forall p1 p2, causal hb p1 -> causal hb p2 -> Permutation p1 p2 -> R (run p1 y) (run p2 y)} +
    {~ forall p1 p2, causal hb p1 -> causal hb p2 -> Permutation p1 p2 -> R (run p1 y) (run p2 y)}.
  Proof.
    intros y R Hd.
    assert (Iff : (forall p1, causal hb p1 -> (fun t1 D1 => forall p2, causal hb p2 -> SameSet p2 D1 -> R t1 (run p2 y)) (run p1 y) p1) <->
                  (forall p1 p2, causal hb p1 -> causal hb p2 -> Permutation p1 p2 -> R (run p1 y) (run p2 y))).
    { simpl. split.
      - intros H p1 p2 H1 H2 P. apply (H p1 H1 p2 H2). intros z. split; [apply Permutation_in; apply Permutation_sym; exact P |].
        apply Permutation_in. exact P.
      - intros H p1 H1 p2 H2 HS. apply H; [exact H1 | exact H2 |].
        apply NoDup_Permutation; [exact (proj1 H1) | exact (proj1 H2) |]. intros z. symmetry. apply HS. }
    apply (dec_iff _ _ Iff).
    refine (causal_forall_dec y (fun t1 D1 => forall p2, causal hb p2 -> SameSet p2 D1 -> R t1 (run p2 y)) _ _).
    - intros t1 D1. refine (causal_forall_dec y (fun t2 D2 => SameSet D2 D1 -> R t1 t2) _ _).
      + intros t2 D2. apply dec_imp; [apply sameset_dec | apply Hd].
      + intros t2 D2 D2' HD H HS. apply H. intros z. rewrite (HD z). apply HS.
    - intros t1 D1 D1' HD H p2 Hp2 HS. apply H; [exact Hp2 |]. intros z. rewrite (HS z). symmetry. apply HD.
  Qed.

  Theorem alo_pairs_dec : forall y (R : S -> S -> Prop), (forall s t, {R s t} + {~ R s t}) ->
    {forall p1 p2, causal_alo hb p1 -> causal_alo hb p2 -> SameSet p1 p2 -> R (run p1 y) (run p2 y)} +
    {~ forall p1 p2, causal_alo hb p1 -> causal_alo hb p2 -> SameSet p1 p2 -> R (run p1 y) (run p2 y)}.
  Proof.
    intros y R Hd.
    assert (Iff : (forall p1, causal_alo hb p1 -> (fun t1 D1 => forall p2, causal_alo hb p2 -> SameSet p2 D1 -> R t1 (run p2 y)) (run p1 y) p1) <->
                  (forall p1 p2, causal_alo hb p1 -> causal_alo hb p2 -> SameSet p1 p2 -> R (run p1 y) (run p2 y))).
    { simpl. split.
      - intros H p1 p2 H1 H2 HS. apply (H p1 H1 p2 H2). intros z. symmetry. apply HS.
      - intros H p1 H1 p2 H2 HS. apply H; [exact H1 | exact H2 |]. intros z. symmetry. apply HS. }
    apply (dec_iff _ _ Iff).
    refine (alo_forall_dec y (fun t1 D1 => forall p2, causal_alo hb p2 -> SameSet p2 D1 -> R t1 (run p2 y)) _ _).
    - intros t1 D1. refine (alo_forall_dec y (fun t2 D2 => SameSet D2 D1 -> R t1 t2) _ _).
      + intros t2 D2. apply dec_imp; [apply sameset_dec | apply Hd].
      + intros t2 D2 D2' HD H HS. apply H. intros z. rewrite (HD z). apply HS.
    - intros t1 D1 D1' HD H p2 Hp2 HS. apply H; [exact Hp2 |]. intros z. rewrite (HS z). symmetry. apply HD.
  Qed.
End FiniteClass.

(* Causal and at-least-once switches decided on finite instances. *)
Section ClassFinite.
  Context {SA EA SB EB : Type}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.
  Variable hbX : EA + EB -> EA + EB -> Prop.
  Hypothesis hbX_irrefl : forall x, ~ hbX x x.
  Hypothesis hb_BA : forall a b, ~ hbX (inr b) (inl a).
  Variable decA : forall x y : EA, {x = y} + {x <> y}.
  Variable decB : forall x y : EB, {x = y} + {x <> y}.
  Variable eqSA : forall a b : SA, {a = b} + {a <> b}.
  Variable eqSB : forall a b : SB, {a = b} + {a <> b}.
  Variable allA : list SA.
  Hypothesis allA_full : forall s, In s allA.
  Variable allB : list SB.
  Hypothesis allB_full : forall x, In x allB.
  Variable evsA : list EA.
  Hypothesis evsA_full : forall e, In e evsA.
  Variable evsB : list EB.
  Hypothesis evsB_full : forall e, In e evsB.
  Hypothesis eqvB_dec : forall x y, {eqvB x y} + {~ eqvB x y}.
  Hypothesis hbX_dec : forall x y, {hbX x y} + {~ hbX x y}.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).

  Let evsXf : forall x, In x (evsX evsA evsB) := evsX_full evsA evsA_full evsB evsB_full.
  Let hbA_irrefl : forall a, ~ hbA hbX a a := fun a => hbX_irrefl (inl a).
  Let hbB_irrefl : forall b, ~ hbB hbX b b := fun b => hbX_irrefl (inr b).
  Let hbA_dec : forall a a', {hbA hbX a a'} + {~ hbA hbX a a'} := fun a a' => hbX_dec (inl a) (inl a').
  Let hbB_dec : forall b b', {hbB hbX b b'} + {~ hbB hbX b b'} := fun b b' => hbX_dec (inr b) (inr b').

  Lemma s1c_dec : forall s0, {S1C stepA stepB eqvB M tau hbX s0} + {~ S1C stepA stepB eqvB M tau hbX s0}.
  Proof.
    intros s0.
    assert (Iff : (forall u, causal (hbA hbX) u -> (fun t D => forall a, In a evsA -> okC (hbA hbX) D a ->
                     eqvB (M (stepA a t)) (stepB (tau a) (M t))) (runA u s0) u) <-> S1C stepA stepB eqvB M tau hbX s0).
    { unfold S1C. simpl. split.
      - intros H u a Hc. apply (causal_snoc_iff _ hbA_irrefl) in Hc. destruct Hc as [Hc Ha].
        exact (H u Hc a (evsA_full a) Ha).
      - intros H u Hu a _ Ha. apply H. apply causal_snoc_iff; [exact hbA_irrefl | split; assumption]. }
    apply (dec_iff _ _ Iff).
    refine (causal_forall_dec decA evsA evsA_full eqSA allA allA_full stepA (hbA hbX) hbA_irrefl hbA_dec s0
              (fun t D => forall a, In a evsA -> okC (hbA hbX) D a -> eqvB (M (stepA a t)) (stepB (tau a) (M t))) _ _).
    - intros t D. apply (dec_forall_fin evsA evsA_full). intros a. apply dec_imp; [apply in_dec; exact decA |].
      apply dec_imp; [apply (okC_dec decA (hbA hbX) hbA_dec) | apply eqvB_dec].
    - intros t D D' HD H a Ha H1. apply H; [exact Ha |]. apply (okC_ext _ D'); [intros z; symmetry; apply HD | exact H1].
  Qed.

  Theorem live_causal_dec : forall s0,
    {LiveD stepA stepB eqvB M tau (causal hbX) (@Permutation _) s0} +
    {~ LiveD stepA stepB eqvB M tau (causal hbX) (@Permutation _) s0}.
  Proof.
    intros s0. apply (dec_iff _ _ (iff_sym (live_causal_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans
                                              stepB_ext M tau hbX s0))).
    apply dec_and; [| apply s1c_dec].
    exact (ccr_s_dec (decX decA decB) (evsX evsA evsB) evsXf eqSB allB allB_full (stepX stepB tau) hbX hbX_irrefl
             hbX_dec eqvB eqvB_dec (M s0)).
  Qed.

  Theorem barrier_causal_dec : forall s0,
    {BarD stepA stepB eqvB M tau (causal hbX) (@Permutation _) QT s0} +
    {~ BarD stepA stepB eqvB M tau (causal hbX) (@Permutation _) QT s0}.
  Proof.
    intros s0. apply (dec_iff _ _ (iff_sym (barrier_causal_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans
                                              stepB_ext M tau hbX hb_BA s0))).
    apply dec_and.
    - refine (causal_forall_dec decA evsA evsA_full eqSA allA allA_full stepA (hbA hbX) hbA_irrefl hbA_dec s0
                (fun t _ => NC.DistributedDelivery.CCRonS stepB (hbB hbX) eqvB (M t)) _ _); [| intros t D D' _ H; exact H].
      intros t _. exact (ccr_s_dec decB evsB evsB_full eqSB allB allB_full stepB (hbB hbX) hbB_irrefl hbB_dec eqvB
                           eqvB_dec (M t)).
    - exact (causal_pairs_dec decA evsA evsA_full eqSA allA allA_full stepA (hbA hbX) hbA_irrefl hbA_dec s0
               (fun x y => eqvB (M x) (M y)) (fun x y => eqvB_dec (M x) (M y))).
  Qed.

  Theorem classify_causal_complete : forall s0,
    {o : outcome | ClassD stepA stepB eqvB M tau (causal hbX) (@Permutation _) QT s0 o}.
  Proof. intros s0. apply classD_decide; [apply live_causal_dec | apply barrier_causal_dec]. Qed.

  Lemma s1ca_dec : forall s0, {S1CA stepA stepB eqvB M tau hbX s0} + {~ S1CA stepA stepB eqvB M tau hbX s0}.
  Proof.
    intros s0.
    assert (Iff : (forall u, causal_alo (hbA hbX) u -> (fun t D => forall a, In a evsA -> okCA (hbA hbX) D a ->
                     eqvB (M (stepA a t)) (stepB (tau a) (M t))) (runA u s0) u) <-> S1CA stepA stepB eqvB M tau hbX s0).
    { unfold S1CA. simpl. split.
      - intros H u a Hc. apply alo_snoc_iff in Hc. destruct Hc as [Hc Ha]. exact (H u Hc a (evsA_full a) Ha).
      - intros H u Hu a _ Ha. apply H. apply alo_snoc_iff. split; assumption. }
    apply (dec_iff _ _ Iff).
    refine (alo_forall_dec decA evsA evsA_full eqSA allA allA_full stepA (hbA hbX) hbA_dec s0
              (fun t D => forall a, In a evsA -> okCA (hbA hbX) D a -> eqvB (M (stepA a t)) (stepB (tau a) (M t))) _ _).
    - intros t D. apply (dec_forall_fin evsA evsA_full). intros a. apply dec_imp; [apply in_dec; exact decA |].
      apply dec_imp; [apply (okCA_dec (hbA hbX) hbA_dec) | apply eqvB_dec].
    - intros t D D' HD H a Ha H1. apply H; [exact Ha |]. apply (okCA_ext _ D'); [intros z; symmetry; apply HD | exact H1].
  Qed.

  Theorem live_alo_dec : forall s0,
    {LiveD stepA stepB eqvB M tau (causal_alo hbX) SameSet s0} +
    {~ LiveD stepA stepB eqvB M tau (causal_alo hbX) SameSet s0}.
  Proof.
    intros s0. apply (dec_iff _ _ (iff_sym (live_alo_exact decA decB stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans
                                              stepB_ext M tau hbX hbX_irrefl s0))).
    apply dec_and; [apply dec_and | apply s1ca_dec].
    - exact (ccr_s_dec (decX decA decB) (evsX evsA evsB) evsXf eqSB allB allB_full (stepX stepB tau) hbX hbX_irrefl
               hbX_dec eqvB eqvB_dec (M s0)).
    - exact (idem_s_dec (decX decA decB) (evsX evsA evsB) evsXf eqSB allB allB_full (stepX stepB tau) hbX hbX_irrefl
               hbX_dec eqvB eqvB_dec (M s0)).
  Qed.

  Lemma absorbS_dec : forall s0, {AbsorbS stepA stepB eqvB M tau hbX s0} + {~ AbsorbS stepA stepB eqvB M tau hbX s0}.
  Proof.
    intros s0.
    pose (Q := fun (Dp : list EA) (z : SB) (Dv : list EB) => forall a, In a evsA -> In a Dp ->
                 (forall a', In a' Dp -> ~ hbX (inl a) (inl a')) -> (forall b, In b Dv -> ~ hbX (inl a) (inr b)) ->
                 eqvB (stepB (tau a) z) z).
    assert (Iff : (forall p, causal_alo (hbA hbX) p ->
                     (fun t Dp => forall v, causal_alo (hbB hbX) v -> Q Dp (runB v (M t)) v) (runA p s0) p) <->
                  AbsorbS stepA stepB eqvB M tau hbX s0).
    { unfold AbsorbS, Q. simpl. split.
      - intros H p v a Hp Hv Ha H3 H4. exact (H p Hp v Hv a (evsA_full a) Ha H3 H4).
      - intros H p Hp v Hv a _ Ha H3 H4. exact (H p v a Hp Hv Ha H3 H4). }
    apply (dec_iff _ _ Iff).
    refine (alo_forall_dec decA evsA evsA_full eqSA allA allA_full stepA (hbA hbX) hbA_dec s0
              (fun t Dp => forall v, causal_alo (hbB hbX) v -> Q Dp (runB v (M t)) v) _ _).
    - intros t Dp.
      refine (alo_forall_dec decB evsB evsB_full eqSB allB allB_full stepB (hbB hbX) hbB_dec (M t) (Q Dp) _ _).
      + intros z Dv. unfold Q. apply (dec_forall_fin evsA evsA_full). intros a.
        apply dec_imp; [apply in_dec; exact decA |]. apply dec_imp; [apply in_dec; exact decA |].
        apply dec_imp; [apply forall_in_dec; intros a'; apply dec_not; apply hbX_dec |].
        apply dec_imp; [apply forall_in_dec; intros b; apply dec_not; apply hbX_dec | apply eqvB_dec].
      + intros z Dv Dv' HD H a Ha1 Ha2 H3 H4. apply H; try assumption. intros b Hb. apply H4. apply HD. exact Hb.
    - intros t Dp Dp' HD H v Hv a Ha1 Ha2 H3 H4. apply (H v Hv a Ha1); [apply HD; exact Ha2 | | exact H4].
      intros a' Ha'. apply H3. apply HD. exact Ha'.
  Qed.

  Theorem barrier_alo_dec : forall s0,
    {BarD stepA stepB eqvB M tau (causal_alo hbX) SameSet QA s0} +
    {~ BarD stepA stepB eqvB M tau (causal_alo hbX) SameSet QA s0}.
  Proof.
    intros s0. apply (dec_iff _ _ (iff_sym (barrier_alo_exact decB stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans
                                              stepB_ext M tau hbX hbX_irrefl hb_BA s0))).
    apply dec_and; [| apply dec_and; [apply absorbS_dec |]].
    - refine (alo_forall_dec decA evsA evsA_full eqSA allA allA_full stepA (hbA hbX) hbA_dec s0
                (fun t _ => NC.DistributedDelivery.CCRonS stepB (hbB hbX) eqvB (M t) /\
                            forall b, NC.DistributedDelivery.IdemAtS stepB (hbB hbX) eqvB (M t) b) _ _);
        [| intros t D D' _ H; exact H].
      intros t _. apply dec_and.
      + exact (ccr_s_dec decB evsB evsB_full eqSB allB allB_full stepB (hbB hbX) hbB_irrefl hbB_dec eqvB eqvB_dec (M t)).
      + exact (idem_s_dec decB evsB evsB_full eqSB allB allB_full stepB (hbB hbX) hbB_irrefl hbB_dec eqvB eqvB_dec (M t)).
    - exact (alo_pairs_dec decA evsA evsA_full eqSA allA allA_full stepA (hbA hbX) hbA_dec s0
               (fun x y => eqvB (M x) (M y)) (fun x y => eqvB_dec (M x) (M y))).
  Qed.

  Theorem classify_alo_complete : forall s0,
    {o : outcome | ClassD stepA stepB eqvB M tau (causal_alo hbX) SameSet QA s0 o}.
  Proof. intros s0. apply classD_decide; [apply live_alo_dec | apply barrier_alo_dec]. Qed.
End ClassFinite.

