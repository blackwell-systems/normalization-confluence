Definition SameSet {E : Type} (l1 l2 : list E) : Prop := forall x, In x l1 <-> In x l2.

Lemma liveD_adm_ext : forall {SA EA SB EB : Type} stepA stepB eqvB (M : SA -> SB) (tau : EA -> EB)
  (Adm Adm' : list (EA + EB) -> Prop) Rel, (forall w, Adm w <-> Adm' w) ->
  forall s0, LiveD stepA stepB eqvB M tau Adm Rel s0 <-> LiveD stepA stepB eqvB M tau Adm' Rel s0.
Proof.
  intros SA EA SB EB stepA stepB eqvB M tau Adm Adm' Rel H s0.
  split; intros L p1 q1 p2 q2 H1 H2 R; apply L; try apply H; assumption.
Qed.

Lemma barD_adm_ext : forall {SA EA SB EB : Type} stepA stepB eqvB (M : SA -> SB) (tau : EA -> EB)
  (Adm Adm' : list (EA + EB) -> Prop) Rel Q, (forall w, Adm w <-> Adm' w) ->
  forall s0, BarD stepA stepB eqvB M tau Adm Rel Q s0 <-> BarD stepA stepB eqvB M tau Adm' Rel Q s0.
Proof.
  intros SA EA SB EB stepA stepB eqvB M tau Adm Adm' Rel Q H s0.
  split; intros L p1 q1 p2 q2 Q1 Q2 H1 H2 R; apply L; try apply H; assumption.
Qed.

Lemma rd_filter_eq_app : forall {E : Type} (f : E -> bool) d l r, filter f d = l ++ r ->
  exists d1 d2, d = d1 ++ d2 /\ filter f d1 = l /\ filter f d2 = r.
Proof.
  intros E f. induction d as [| x d IH]; intros l r H.
  - simpl in H. symmetry in H. apply app_eq_nil in H. destruct H as [-> ->].
    exists [], []. split; [reflexivity | split; reflexivity].
  - simpl in H. destruct (f x) eqn:Fx.
    + destruct l as [| y l].
      * exists [], (x :: d). simpl. rewrite Fx. split; [reflexivity | split; [reflexivity | exact H]].
      * simpl in H. injection H as Hy H. destruct (IH l r H) as [d1 [d2 [-> [E1 E2]]]].
        exists (x :: d1), d2. simpl. rewrite Fx. subst. split; [reflexivity | split; reflexivity].
    + destruct (IH l r H) as [d1 [d2 [-> [E1 E2]]]].
      exists (x :: d1), d2. simpl. rewrite Fx. split; [reflexivity | split; assumption].
Qed.

Lemma rd_causal_alo_filter : forall {E : Type} (hb : E -> E -> Prop) (f : E -> bool) d,
  causal_alo hb d -> causal_alo hb (filter f d).
Proof.
  intros E hb f d H a b Hab l r E1 Hb Ha. destruct (rd_filter_eq_app f d l r E1) as [d1 [d2 [-> [<- <-]]]].
  apply filter_In in Hb. apply filter_In in Ha. exact (H a b Hab d1 d2 eq_refl (proj1 Hb) (proj1 Ha)).
Qed.

Lemma rd_causal_alo_one : forall {E : Type} (hb : E -> E -> Prop) x, causal_alo hb [x].
Proof.
  intros E hb x a b _ l r E1 Hb Ha. destruct l as [| y l]; [destruct Hb |].
  injection E1 as _ E1. symmetry in E1. apply app_eq_nil in E1. destruct E1 as [_ ->]. destruct Ha.
Qed.

Lemma rd_runT_one : forall {S E : Type} (f : E -> S -> S) x s, runT f [x] s = f x s.
Proof. reflexivity. Qed.

Definition isRb {EA EB : Type} (x : EA + EB) : bool := match x with inl _ => false | inr _ => true end.

Lemma projB_filter : forall {EA EB : Type} (q : list (EA + EB)), map inr (projB q) = filter isRb q.
Proof. intros EA EB q. induction q as [| [a | b] q IH]; [reflexivity | exact IH | simpl; f_equal; exact IH]. Qed.

Section ALOSwitch.
  Context {SA EA SB EB : Type}.
  Variable decA : forall x y : EA, {x = y} + {x <> y}.
  Variable decB : forall x y : EB, {x = y} + {x <> y}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.
  Variable hbX : EA + EB -> EA + EB -> Prop.
  Hypothesis hbX_irrefl : forall x, ~ hbX x x.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).
  Local Notation runX := (runT (stepX stepB tau)).

  Definition decX : forall x y : EA + EB, {x = y} + {x <> y}.
  Proof. decide equality. Defined.

  Lemma alo_inl : forall p, causal_alo hbX (map inl p) <-> causal_alo (hbA hbX) p.
  Proof. intros p. exact (rd_causal_alo_map_inj inl inl_inj hbX p). Qed.
  Lemma alo_inr : forall v, causal_alo hbX (map inr v) <-> causal_alo (hbB hbX) v.
  Proof. intros v. exact (rd_causal_alo_map_inj inr inr_inj hbX v). Qed.

  (* S1 at the causally consistent at-least-once A-prefixes: duplicates before the switch too. *)
  Definition S1CA (s0 : SA) : Prop :=
    forall u a, causal_alo (hbA hbX) (u ++ [a]) ->
      eqvB (M (stepA a (runA u s0))) (stepB (tau a) (M (runA u s0))).

  Theorem live_alo_exact : forall s0,
    LiveD stepA stepB eqvB M tau (causal_alo hbX) SameSet s0 <->
    (NC.DistributedDelivery.CCRonS (stepX stepB tau) hbX eqvB (M s0) /\
     forall x, NC.DistributedDelivery.IdemAtS (stepX stepB tau) hbX eqvB (M s0) x) /\ S1CA s0.
  Proof.
    intros s0.
    rewrite (live_delivery_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau (causal_alo hbX)
               SameSet (NC.DistributedDelivery.causal_alo_app_prefix hbX) (fun l _ x => iff_refl _) s0).
    rewrite <- (NC.DistributedDelivery.causal_alo_s_exact decX (stepX stepB tau) hbX hbX_irrefl eqvB eqvB_refl
                  eqvB_sym eqvB_trans (stepX_ext stepB eqvB stepB_ext tau) (M s0)).
    unfold ConvXD, NC.DistributedDelivery.CALOConvS, S1D, S1CA, SameSet. split; intros [H1 H2]; split;
      try exact H1; intros u a Hc; apply H2; apply alo_inl; exact Hc.
  Qed.

  Hypothesis hb_BA : forall a b, ~ hbX (inr b) (inl a).

  Lemma alo_split : forall p v,
    causal_alo hbX (map inl p ++ map inr v) <-> causal_alo (hbA hbX) p /\ causal_alo (hbB hbX) v.
  Proof.
    intros p v. rewrite rd_causal_alo_app, alo_inl, alo_inr. split; [tauto |].
    intros [H1 H2]. split; [exact H1 | split; [exact H2 |]].
    intros x y Hx Hy. apply in_map_iff in Hx. destruct Hx as [a [<- _]].
    apply in_map_iff in Hy. destruct Hy as [b [<- _]]. apply hb_BA.
  Qed.

  (* Barrier: after the switch, B-events and redeliveries of A-events delivered before it. *)
  Definition QA (p : list EA) (q : list (EA + EB)) : Prop :=
    forall x, In x q -> (exists b, x = inr b) \/ (exists a, x = inl a /\ In a p).

  Lemma glue_alo : Glue (causal_alo hbX) SameSet QA.
  Proof.
    intros p1 q1 p2 q2 Q1 Q2 H1 H2 S.
    assert (SP : forall a, In a p1 <-> In a p2).
    { assert (K : forall p q p' q', QA p' q' -> SameSet (map inl p ++ q) (map inl p' ++ q') ->
                    forall a, In a p -> In a p').
      { intros p q p' q' Q' S' a Ha.
        assert (Hw : In (inl a) (map inl p' ++ q')) by (apply S'; apply in_or_app; left; apply in_map_inl; exact Ha).
        apply in_app_or in Hw. destruct Hw as [Hw | Hw]; [exact (proj1 (@in_map_inl EA EB p' a) Hw) |].
        destruct (Q' _ Hw) as [[b Eb] | [a' [Ea Ha']]]; [discriminate Eb | injection Ea as ->; exact Ha']. }
      intros a. split; [apply (K p1 q1 p2 q2 Q2 S) |].
      apply (K p2 q2 p1 q1 Q1). intros x. symmetry. apply S. }
    apply rd_causal_alo_app in H1. destruct H1 as [_ [Hq1 Hx1]].
    apply rd_causal_alo_app in H2. destruct H2 as [Hp2 _].
    split; [| split; [| split]].
    - intros x. split; intros Hx; apply in_map_iff in Hx; destruct Hx as [a [<- Ha]]; apply in_map_inl; apply SP; exact Ha.
    - intros x Hx. destruct (Q1 x Hx) as [Hb | [a [-> Ha]]]; [left; exact Hb |].
      right. exists a. split; [reflexivity | apply SP; exact Ha].
    - apply rd_causal_alo_app. split; [exact Hp2 | split; [exact Hq1 |]].
      intros x y Hx Hy. apply in_map_iff in Hx. destruct Hx as [a [<- Ha]].
      apply Hx1; [apply in_map_inl; apply SP; exact Ha | exact Hy].
    - intros x. split; intros Hx; apply in_app_or in Hx; destruct Hx as [Hx | Hx];
        try (apply in_or_app; left; exact Hx).
      + assert (Hw : In x (map inl p2 ++ q2)) by (apply S; apply in_or_app; right; exact Hx). exact Hw.
      + assert (Hw : In x (map inl p1 ++ q1)) by (apply S; apply in_or_app; right; exact Hx).
        apply in_app_or in Hw. destruct Hw as [Hw | Hw]; [| apply in_or_app; right; exact Hw].
        apply in_map_iff in Hw. destruct Hw as [a [<- Ha]]. apply in_or_app. left. apply in_map_inl. apply SP. exact Ha.
  Qed.

  (* B's own causal at-least-once condition at every migrated reachable state. *)
  Definition BOwnA (s0 : SA) : Prop :=
    forall p, causal_alo (hbA hbX) p -> NC.DistributedDelivery.CALOConvS stepB (hbB hbX) eqvB (M (runA p s0)).

  (* A duplicate straddling the switch: an A-event a delivered before the switch and redelivered
     after the B-events v (where that redelivery is causally consistent) is absorbed. *)
  Definition AbsorbS (s0 : SA) : Prop :=
    forall p v a, causal_alo (hbA hbX) p -> causal_alo (hbB hbX) v -> In a p ->
      (forall a', In a' p -> ~ hbX (inl a) (inl a')) -> (forall b, In b v -> ~ hbX (inl a) (inr b)) ->
      eqvB (stepB (tau a) (runB v (M (runA p s0)))) (runB v (M (runA p s0))).

  (* A converges under causal at-least-once delivery modulo M. *)
  Definition AmodA (s0 : SA) : Prop :=
    forall p1 p2, causal_alo (hbA hbX) p1 -> causal_alo (hbA hbX) p2 -> SameSet p1 p2 ->
      eqvB (M (runA p1 s0)) (M (runA p2 s0)).

  Lemma adm_straddle : forall p v a,
    causal_alo hbX (map inl p ++ map inr v ++ [inl a]) <->
    causal_alo (hbA hbX) p /\ causal_alo (hbB hbX) v /\
    (forall a', In a' p -> ~ hbX (inl a) (inl a')) /\ (forall b, In b v -> ~ hbX (inl a) (inr b)).
  Proof.
    intros p v a. rewrite app_assoc, rd_causal_alo_app, alo_split. split.
    - intros [[H1 H2] [_ H3]]. split; [exact H1 | split; [exact H2 | split]].
      + intros a' Ha' Hh. exact (H3 (inl a') (inl a) (in_or_app _ _ _ (or_introl (proj2 (@in_map_inl EA EB p a') Ha')))
                                   (or_introl eq_refl) Hh).
      + intros b Hb Hh. exact (H3 (inr b) (inl a) (in_or_app _ _ _ (or_intror (proj2 (@in_map_inr EA EB v b) Hb)))
                                 (or_introl eq_refl) Hh).
    - intros [H1 [H2 [H3 H4]]]. split; [split; assumption | split; [apply rd_causal_alo_one |]].
      intros x y Hx Hy. destruct Hy as [<- | []]. apply in_app_or in Hx. destruct Hx as [Hx | Hx].
      + apply in_map_iff in Hx. destruct Hx as [a' [<- Ha']]. exact (H3 a' Ha').
      + apply in_map_iff in Hx. destruct Hx as [b [<- Hb]]. exact (H4 b Hb).
  Qed.

  Lemma straddle_reduce : forall s0, AbsorbS s0 -> forall p q, QA p q -> causal_alo hbX (map inl p ++ q) ->
    eqvB (runX q (M (runA p s0))) (runB (projB q) (M (runA p s0))).
  Proof.
    intros s0 HS p q Q. induction q as [| x q IH] using rev_ind; intros H; [apply eqvB_refl |].
    assert (Qq : QA p q) by (intros y Hy; apply Q; apply in_or_app; left; exact Hy).
    assert (Hq : causal_alo hbX (map inl p ++ q)) by (rewrite app_assoc in H; exact (causal_alo_prefix hbX _ x H)).
    rewrite runT_app, projB_app, (runT_app stepB).
    destruct (Q x (in_or_app q [x] x (or_intror (or_introl eq_refl)))) as [[b ->] | [a [-> Ha]]].
    - change (projB [@inr EA EB b]) with [b]. rewrite !rd_runT_one.
      change (stepX stepB tau (inr b) ?z) with (stepB b z). apply stepB_ext. exact (IH Qq Hq).
    - change (projB [@inl EA EB a]) with (@nil EB). rewrite rd_runT_one.
      change (runT stepB [] ?z) with z.
      change (stepX stepB tau (inl a) ?z) with (stepB (tau a) z).
      apply (eqvB_trans _ (stepB (tau a) (runB (projB q) (M (runA p s0))))); [apply stepB_ext; exact (IH Qq Hq) |].
      rewrite app_assoc in H. apply rd_causal_alo_app in H. destruct H as [Hpq [_ Hx]].
      apply rd_causal_alo_app in Hpq. destruct Hpq as [Hp [Hqq _]].
      apply HS.
      + apply alo_inl. exact Hp.
      + apply alo_inr. rewrite projB_filter. apply rd_causal_alo_filter. exact Hqq.
      + exact Ha.
      + intros a' Ha' Hh. exact (Hx (inl a') (inl a) (in_or_app _ _ _ (or_introl (proj2 (@in_map_inl EA EB p a') Ha')))
                                   (or_introl eq_refl) Hh).
      + intros b Hb Hh. apply in_projB in Hb.
        exact (Hx (inr b) (inl a) (in_or_app _ _ _ (or_intror Hb)) (or_introl eq_refl) Hh).
  Qed.

  Lemma barB_alo_iff : forall s0,
    BarBD stepA stepB eqvB M tau (causal_alo hbX) SameSet QA s0 <-> BOwnA s0 /\ AbsorbS s0.
  Proof.
    intros s0. split.
    - intros H. split.
      + intros p Hp d1 d2 H1 H2 S. rewrite <- !(runX_inr stepB tau).
        apply (H p (map inr d1) (map inr d2)).
        * intros x Hx. left. apply in_map_iff in Hx. destruct Hx as [b [<- _]]. exists b. reflexivity.
        * intros x Hx. left. apply in_map_iff in Hx. destruct Hx as [b [<- _]]. exists b. reflexivity.
        * apply alo_split. split; assumption.
        * apply alo_split. split; assumption.
        * intros x. rewrite !in_app_iff, !in_map_iff. split; intros [Hx | [b [<- Hb]]];
            try (left; exact Hx); right; exists b; split; [reflexivity | apply S; exact Hb |
                                                          reflexivity | apply S; exact Hb].
      + intros p v a Hp Hv Ha H3 H4.
        pose proof (H p (map inr v ++ [inl a]) (map inr v)) as K.
        rewrite runT_app, (runX_inr stepB tau) in K. apply K.
        * intros x Hx. apply in_app_or in Hx. destruct Hx as [Hx | [<- | []]].
          -- left. apply in_map_iff in Hx. destruct Hx as [b [<- _]]. exists b. reflexivity.
          -- right. exists a. split; [reflexivity | exact Ha].
        * intros x Hx. left. apply in_map_iff in Hx. destruct Hx as [b [<- _]]. exists b. reflexivity.
        * apply adm_straddle. tauto.
        * apply alo_split. split; assumption.
        * intros x. rewrite !in_app_iff. split; [| tauto]. intros [Hx | [Hx | [<- | []]]]; [tauto | tauto |].
          left. apply in_map_inl. exact Ha.
    - intros [HO HS] p q1 q2 Q1 Q2 H1 H2 S.
      apply (eqvB_trans _ _ _ (straddle_reduce s0 HS p q1 Q1 H1)).
      apply (eqvB_trans _ (runB (projB q2) (M (runA p s0)))); [| apply eqvB_sym; exact (straddle_reduce s0 HS p q2 Q2 H2)].
      apply rd_causal_alo_app in H1. destruct H1 as [Hp [Hq1 _]].
      apply rd_causal_alo_app in H2. destruct H2 as [_ [Hq2 _]].
      apply HO; [apply alo_inl; exact Hp | | |].
      + apply alo_inr. rewrite projB_filter. apply rd_causal_alo_filter. exact Hq1.
      + apply alo_inr. rewrite projB_filter. apply rd_causal_alo_filter. exact Hq2.
      + intros b. rewrite !in_projB. split; intros Hb.
        * assert (Hw : In (inr b) (map inl p ++ q2)) by (apply S; apply in_or_app; right; exact Hb).
          apply in_app_or in Hw. destruct Hw as [Hw | Hw]; [exfalso; exact (not_in_inr_inl p b Hw) | exact Hw].
        * assert (Hw : In (inr b) (map inl p ++ q1)) by (apply S; apply in_or_app; right; exact Hb).
          apply in_app_or in Hw. destruct Hw as [Hw | Hw]; [exfalso; exact (not_in_inr_inl p b Hw) | exact Hw].
  Qed.

  Lemma amodm_alo_iff : forall s0, AmodMD stepA eqvB M (causal_alo hbX) SameSet s0 <-> AmodA s0.
  Proof.
    intros s0. split.
    - intros H p1 p2 H1 H2 S. apply H; [apply alo_inl; exact H1 | apply alo_inl; exact H2 |].
      intros x. split; intros Hx; apply in_map_iff in Hx; destruct Hx as [a [<- Ha]]; apply in_map_inl; apply S; exact Ha.
    - intros H p1 p2 H1 H2 S. apply H; [apply alo_inl; exact H1 | apply alo_inl; exact H2 |].
      intros a. rewrite <- !(@in_map_inl EA EB _ a). apply S.
  Qed.

  Theorem barrier_alo_exact : forall s0,
    BarD stepA stepB eqvB M tau (causal_alo hbX) SameSet QA s0 <->
    (forall p, causal_alo (hbA hbX) p ->
       NC.DistributedDelivery.CCRonS stepB (hbB hbX) eqvB (M (runA p s0)) /\
       forall b, NC.DistributedDelivery.IdemAtS stepB (hbB hbX) eqvB (M (runA p s0)) b) /\
    AbsorbS s0 /\ AmodA s0.
  Proof.
    intros s0.
    rewrite (barrier_delivery_exact stepA stepB eqvB eqvB_trans stepB_ext M tau (causal_alo hbX) SameSet QA
               (NC.DistributedDelivery.causal_alo_app_prefix hbX) (fun p x H => match H with end) glue_alo s0).
    rewrite barB_alo_iff, amodm_alo_iff. unfold BOwnA.
    assert (hbB_irrefl : forall b, ~ hbB hbX b b) by (intros b; apply hbX_irrefl).
    split.
    - intros [[H1 H2] H3]. split; [| split; assumption]. intros p Hp.
      apply (NC.DistributedDelivery.causal_alo_s_exact decB stepB (hbB hbX) hbB_irrefl eqvB eqvB_refl eqvB_sym
               eqvB_trans stepB_ext). apply H1. exact Hp.
    - intros [H1 [H2 H3]]. split; [split; [| exact H2] | exact H3]. intros p Hp.
      apply (NC.DistributedDelivery.causal_alo_s_exact decB stepB (hbB hbX) hbB_irrefl eqvB eqvB_refl eqvB_sym
               eqvB_trans stepB_ext). apply H1. exact Hp.
  Qed.
End ALOSwitch.

(* Free at-least-once delivery: the instance with no causal constraint. *)
Section FreeALO.
  Context {SA EA SB EB : Type}.
  Variable decA : forall x y : EA, {x = y} + {x <> y}.
  Variable decB : forall x y : EB, {x = y} + {x <> y}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).

  (* Distinct events commute after every duplicate-free prefix; an event is idempotent where it is
     first delivered (AtLeastOnceExact.CommReach and IdemReach, up to an equivalence). *)
  Definition CommND {S E : Type} (step : E -> S -> S) (eqv : S -> S -> Prop) (y : S) : Prop :=
    forall p a b, a <> b -> NoDup (p ++ [a; b]) ->
      eqv (step b (step a (runT step p y))) (step a (step b (runT step p y))).
  Definition IdemND {S E : Type} (step : E -> S -> S) (eqv : S -> S -> Prop) (y : S) (a : E) : Prop :=
    forall u, NoDup (u ++ [a]) -> eqv (step a (step a (runT step u y))) (step a (runT step u y)).

  Lemma ccr_nohb_iff : forall {S E : Type} (step : E -> S -> S) eqv y,
    NC.DistributedDelivery.CCRonS step nohb eqv y <-> CommND step eqv y.
  Proof.
    intros S E step eqv y. unfold NC.DistributedDelivery.CCRonS, CommND. split.
    - intros H p a b Hab Hnd. apply H; [exact (proj2 (concurrent_nohb a b) Hab) | exact (proj2 (causal_nohb _) Hnd)].
    - intros H p a b Hab Hc. apply H; [exact (proj1 (concurrent_nohb a b) Hab) | exact (proj1 (causal_nohb _) Hc)].
  Qed.

  Lemma idem_nohb_iff : forall {S E : Type} (step : E -> S -> S) eqv y a,
    NC.DistributedDelivery.IdemAtS step nohb eqv y a <-> IdemND step eqv y a.
  Proof.
    intros S E step eqv y a. unfold NC.DistributedDelivery.IdemAtS, IdemND. split.
    - intros H u Hnd. apply H. exact (proj2 (causal_nohb _) Hnd).
    - intros H u Hc. apply H. exact (proj1 (causal_nohb _) Hc).
  Qed.

  Lemma admF_alo : forall w, AdmF w <-> causal_alo (@nohb (EA + EB)) w.
  Proof. intros w. split; intros _; [apply causal_alo_nohb | exact I]. Qed.

  Theorem live_free_alo_exact : forall s0,
    LiveD stepA stepB eqvB M tau AdmF SameSet s0 <->
    (CommND (stepX stepB tau) eqvB (M s0) /\ forall x, IdemND (stepX stepB tau) eqvB (M s0) x) /\
    DS1 stepA stepB eqvB M tau s0.
  Proof.
    intros s0. rewrite (liveD_adm_ext stepA stepB eqvB M tau _ _ SameSet admF_alo s0).
    rewrite (live_alo_exact decA decB stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau nohb
               (fun x H => H) s0).
    rewrite ccr_nohb_iff. unfold S1CA, DS1. split; intros [[H1 H2] H3]; split; try split; try exact H1.
    - intros x. apply idem_nohb_iff. apply H2.
    - intros u a. apply H3. apply causal_alo_nohb.
    - intros x. apply idem_nohb_iff. apply H2.
    - intros u a _. apply H3.
  Qed.

  (* A duplicate of an A-event delivered before the switch, arriving after any B-events, is
     absorbed. *)
  Definition AbsorbFree (s0 : SA) : Prop :=
    forall p v a, In a p -> eqvB (stepB (tau a) (runB v (M (runA p s0)))) (runB v (M (runA p s0))).
  (* A converges under free at-least-once delivery modulo M. *)
  Definition AmodFree (s0 : SA) : Prop :=
    forall p1 p2, SameSet p1 p2 -> eqvB (M (runA p1 s0)) (M (runA p2 s0)).

  Theorem barrier_free_alo_exact : forall s0,
    BarD stepA stepB eqvB M tau AdmF SameSet QA s0 <->
    (forall p, CommND stepB eqvB (M (runA p s0)) /\ forall b, IdemND stepB eqvB (M (runA p s0)) b) /\
    AbsorbFree s0 /\ AmodFree s0.
  Proof.
    intros s0. rewrite (barD_adm_ext stepA stepB eqvB M tau _ _ SameSet QA admF_alo s0).
    rewrite (barrier_alo_exact decB stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau nohb
               (fun x H => H) (fun a b H => H) s0).
    unfold AbsorbS, AbsorbFree, AmodA, AmodFree. split.
    - intros [H1 [H2 H3]]. split; [| split].
      + intros p. destruct (H1 p (causal_alo_nohb p)) as [K1 K2]. split; [apply ccr_nohb_iff; exact K1 |].
        intros b. apply idem_nohb_iff. apply K2.
      + intros p v a Ha. apply H2; [apply causal_alo_nohb | apply causal_alo_nohb | exact Ha | |];
          intros _ _ [].
      + intros p1 p2 S. apply H3; [apply causal_alo_nohb | apply causal_alo_nohb | exact S].
    - intros [H1 [H2 H3]]. split; [| split].
      + intros p _. destruct (H1 p) as [K1 K2]. split; [apply ccr_nohb_iff; exact K1 |].
        intros b. apply idem_nohb_iff. apply K2.
      + intros p v a _ _ Ha _ _. apply H2. exact Ha.
      + intros p1 p2 _ _ S. apply H3. exact S.
  Qed.
End FreeALO.

