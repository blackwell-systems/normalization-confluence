Lemma rd_flat_map_app : forall {X Y : Type} (f : X -> list Y) l r,
  flat_map f (l ++ r) = flat_map f l ++ flat_map f r.
Proof.
  intros X Y f l r. induction l as [| x l IH]; [reflexivity |]. simpl. rewrite IH, app_assoc. reflexivity.
Qed.

Lemma rd_perm_flat_map : forall {X Y : Type} (f : X -> list Y) l l',
  Permutation l l' -> Permutation (flat_map f l) (flat_map f l').
Proof.
  intros X Y f l l' H. induction H as [| x l l' _ IH | x y l | l l' l'' _ IH1 _ IH2]; simpl.
  - apply Permutation_refl.
  - apply Permutation_app_head. exact IH.
  - rewrite !app_assoc. apply Permutation_app_tail. apply Permutation_app_comm.
  - exact (Permutation_trans IH1 IH2).
Qed.

Lemma rd_tequiv_app_r : forall {E : Type} (I : E -> E -> Prop) l l' m,
  tequiv I l l' -> tequiv I (l ++ m) (l' ++ m).
Proof.
  intros E I l l' m H. induction H as [l | l a b r Hab | l1 l2 _ IH | l1 l2 l3 _ IH1 _ IH2].
  - apply teq_refl.
  - rewrite <- !app_assoc. simpl. apply teq_swap. exact Hab.
  - apply teq_sym. exact IH.
  - exact (teq_trans _ _ _ _ IH1 IH2).
Qed.

Lemma rd_tequiv_map : forall {E F : Type} (f : E -> F) (I : F -> F -> Prop) l l',
  tequiv (fun a b => I (f a) (f b)) l l' -> tequiv I (map f l) (map f l').
Proof.
  intros E F f I l l' H. induction H as [l | l a b r Hab | l1 l2 _ IH | l1 l2 l3 _ IH1 _ IH2].
  - apply teq_refl.
  - rewrite !map_app. simpl. apply teq_swap. exact Hab.
  - apply teq_sym. exact IH.
  - exact (teq_trans _ _ _ _ IH1 IH2).
Qed.

(* A swap-closed admissibility is invariant under trace equivalence. *)
Lemma rd_tequiv_adm : forall {E : Type} (I : E -> E -> Prop) (Adm : list E -> Prop),
  (forall a b, I a b -> I b a) ->
  (forall l a b r, I a b -> Adm (l ++ a :: b :: r) -> Adm (l ++ b :: a :: r)) ->
  forall w1 w2, tequiv I w1 w2 -> (Adm w1 <-> Adm w2).
Proof.
  intros E I Adm Isym Hsw w1 w2 H. induction H as [l | l a b r Hab | l1 l2 _ IH | l1 l2 l3 _ IH1 _ IH2].
  - tauto.
  - split; intros Ha; apply Hsw; [exact Hab | exact Ha | apply Isym; exact Hab | exact Ha].
  - tauto.
  - tauto.
Qed.

Section Proj.
  Context {EA EB : Type}.

  Definition pA (x : EA + EB) : list EA := match x with inl a => [a] | inr _ => [] end.
  Definition pB (x : EA + EB) : list EB := match x with inl _ => [] | inr b => [b] end.
  Definition projA (l : list (EA + EB)) : list EA := flat_map pA l.
  Definition projB (l : list (EA + EB)) : list EB := flat_map pB l.

  Lemma projA_app : forall l r, projA (l ++ r) = projA l ++ projA r.
  Proof. intros l r. apply rd_flat_map_app. Qed.
  Lemma projB_app : forall l r, projB (l ++ r) = projB l ++ projB r.
  Proof. intros l r. apply rd_flat_map_app. Qed.
  Lemma projA_inl : forall p, projA (map inl p) = p.
  Proof. induction p as [| a p IH]; [reflexivity |]. simpl. f_equal. exact IH. Qed.
  Lemma projA_inr : forall v, projA (map inr v) = [].
  Proof. induction v as [| b v IH]; [reflexivity |]. exact IH. Qed.
  Lemma projB_inl : forall p, projB (map inl p) = [].
  Proof. induction p as [| a p IH]; [reflexivity |]. exact IH. Qed.
  Lemma projB_inr : forall v, projB (map inr v) = v.
  Proof. induction v as [| b v IH]; [reflexivity |]. simpl. f_equal. exact IH. Qed.

  Lemma in_projA : forall l a, In a (projA l) <-> In (inl a) l.
  Proof.
    intros l a. unfold projA. rewrite in_flat_map. split.
    - intros [[a' | b] [Hx Ha]]; simpl in Ha; [destruct Ha as [<- | []]; exact Hx | destruct Ha].
    - intros H. exists (inl a). split; [exact H | left; reflexivity].
  Qed.
  Lemma in_projB : forall l b, In b (projB l) <-> In (inr b) l.
  Proof.
    intros l b. unfold projB. rewrite in_flat_map. split.
    - intros [[a | b'] [Hx Hb]]; simpl in Hb; [destruct Hb | destruct Hb as [<- | []]; exact Hx].
    - intros H. exists (inr b). split; [exact H | left; reflexivity].
  Qed.

  Lemma in_map_inl : forall p a, In (inl a) (map (@inl EA EB) p) <-> In a p.
  Proof.
    intros p a. rewrite in_map_iff. split; [intros [a' [E H]]; injection E as ->; exact H |].
    intros H. exists a. split; [reflexivity | exact H].
  Qed.
  Lemma in_map_inr : forall v b, In (inr b) (map (@inr EA EB) v) <-> In b v.
  Proof.
    intros v b. rewrite in_map_iff. split; [intros [b' [E H]]; injection E as ->; exact H |].
    intros H. exists b. split; [reflexivity | exact H].
  Qed.
  Lemma not_in_inl_inr : forall v a, ~ In (inl a) (map (@inr EA EB) v).
  Proof. intros v a H. apply in_map_iff in H. destruct H as [b [E _]]. discriminate E. Qed.
  Lemma not_in_inr_inl : forall p b, ~ In (inr b) (map (@inl EA EB) p).
  Proof. intros p b H. apply in_map_iff in H. destruct H as [a [E _]]. discriminate E. Qed.

  (* A continuation of B-events only. *)
  Definition AllB (q : list (EA + EB)) : Prop := forall x, In x q -> exists b, x = inr b.

  Lemma allB_inr : forall q, AllB q -> q = map inr (projB q).
  Proof.
    induction q as [| x q IH]; intros H; [reflexivity |].
    destruct (H x (or_introl eq_refl)) as [b ->]. simpl. f_equal.
    apply IH. intros y Hy. apply H. right. exact Hy.
  Qed.

  Lemma allB_map : forall v, AllB (map inr v).
  Proof. intros v x Hx. apply in_map_iff in Hx. destruct Hx as [b [<- _]]. exists b. reflexivity. Qed.

  Lemma perm_projA : forall l l', Permutation l l' -> Permutation (projA l) (projA l').
  Proof. intros l l' H. apply rd_perm_flat_map. exact H. Qed.
  Lemma perm_projB : forall l l', Permutation l l' -> Permutation (projB l) (projB l').
  Proof. intros l l' H. apply rd_perm_flat_map. exact H. Qed.

  Lemma tequiv_projA : forall (IX : EA + EB -> EA + EB -> Prop) l l', tequiv IX l l' ->
    tequiv (fun a a' => IX (inl a) (inl a')) (projA l) (projA l').
  Proof.
    intros IX l l' H. induction H as [l | l x y r Hxy | l1 l2 _ IH | l1 l2 l3 _ IH1 _ IH2].
    - apply teq_refl.
    - rewrite !projA_app. destruct x as [a | b]; destruct y as [a' | b']; simpl.
      + apply teq_swap. exact Hxy.
      + apply teq_refl.
      + apply teq_refl.
      + apply teq_refl.
    - apply teq_sym. exact IH.
    - exact (teq_trans _ _ _ _ IH1 IH2).
  Qed.

  Lemma tequiv_projB : forall (IX : EA + EB -> EA + EB -> Prop) l l', tequiv IX l l' ->
    tequiv (fun b b' => IX (inr b) (inr b')) (projB l) (projB l').
  Proof.
    intros IX l l' H. induction H as [l | l x y r Hxy | l1 l2 _ IH | l1 l2 l3 _ IH1 _ IH2].
    - apply teq_refl.
    - rewrite !projB_app. destruct x as [a | b]; destruct y as [a' | b']; simpl.
      + apply teq_refl.
      + apply teq_refl.
      + apply teq_refl.
      + apply teq_swap. exact Hxy.
    - apply teq_sym. exact IH.
    - exact (teq_trans _ _ _ _ IH1 IH2).
  Qed.
End Proj.

