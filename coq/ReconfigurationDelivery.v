Section Free.
  Context {SA EA SB EB : Type}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).
  Local Notation runX := (runT (stepX stepB tau)).

  (* Free delivery: every sequence, compared up to permutation; a barrier run has no A-event after
     the switch. *)
  Definition AdmF (_ : list (EA + EB)) : Prop := True.
  Definition QF (_ : list EA) (q : list (EA + EB)) : Prop := AllB q.

  Lemma convX_perm_iff : forall y,
    ConvXD stepB eqvB tau AdmF (@Permutation _) y <-> PermB stepB eqvB y.
  Proof.
    intros y. split.
    - intros H v v' P. rewrite <- !(runX_inr stepB tau). apply H; [exact I | exact I |].
      apply Permutation_map. exact P.
    - intros H w1 w2 _ _ P. rewrite !runX_map. apply H. apply Permutation_map. exact P.
  Qed.

  Lemma s1_free_iff : forall s0, S1D stepA stepB eqvB M tau AdmF s0 <-> DS1 stepA stepB eqvB M tau s0.
  Proof. intros s0. unfold S1D, DS1, AdmF. split; intros H u a; [apply H; exact I | intros _; apply H]. Qed.

  Theorem free_live_exact : forall s0,
    LiveD stepA stepB eqvB M tau AdmF (@Permutation _) s0 <-> DLive stepA stepB eqvB M tau s0.
  Proof.
    intros s0.
    rewrite (live_delivery_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau AdmF
               (@Permutation _) (fun _ _ _ => I) (fun l _ => Permutation_refl l) s0).
    rewrite (det_live_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau s0).
    rewrite convX_perm_iff, s1_free_iff. tauto.
  Qed.

  Lemma glue_free : Glue AdmF (@Permutation _) QF.
  Proof.
    intros p1 q1 p2 q2 Q1 Q2 _ _ P.
    destruct (allB_ex q1 Q1) as [v1 ->]. destruct (allB_ex q2 Q2) as [v2 ->].
    pose proof (perm_projA _ _ P) as PA. rewrite !projA_app, !projA_inl, !projA_inr, !app_nil_r in PA.
    pose proof (perm_projB _ _ P) as PB. rewrite !projB_app, !projB_inl, !projB_inr in PB. simpl in PB.
    split; [apply Permutation_map; exact PA |]. split; [exact Q1 |]. split; [exact I |].
    apply Permutation_app_head. apply Permutation_map. exact PB.
  Qed.

  Lemma barB_free_iff : forall s0,
    BarBD stepA stepB eqvB M tau AdmF (@Permutation _) QF s0 <-> forall u, PermB stepB eqvB (M (runA u s0)).
  Proof.
    intros s0. split.
    - intros H u v v' P. rewrite <- !(runX_inr stepB tau).
      apply (H u); [apply allB_map | apply allB_map | exact I | exact I |].
      apply Permutation_app_head. apply Permutation_map. exact P.
    - intros H p q1 q2 Q1 Q2 _ _ P. apply Permutation_app_inv_l in P.
      destruct (allB_ex q1 Q1) as [v1 ->]. destruct (allB_ex q2 Q2) as [v2 ->].
      rewrite !runX_inr. apply H.
      pose proof (perm_projB _ _ P) as PB. rewrite !projB_inr in PB. exact PB.
  Qed.

  Lemma amodm_free_iff : forall s0, AmodMD stepA eqvB M AdmF (@Permutation _) s0 <->
    (forall u u', Permutation u u' -> eqvB (M (runA u s0)) (M (runA u' s0))).
  Proof.
    intros s0. split.
    - intros H u u' P. apply H; [exact I | exact I | apply Permutation_map; exact P].
    - intros H p1 p2 _ _ P. apply H. pose proof (perm_projA _ _ P) as PA. rewrite !projA_inl in PA. exact PA.
  Qed.

  Theorem free_barrier_exact : forall s0,
    BarD stepA stepB eqvB M tau AdmF (@Permutation _) QF s0 <-> DBar stepA stepB eqvB M s0.
  Proof.
    intros s0.
    rewrite (barrier_delivery_exact stepA stepB eqvB eqvB_trans stepB_ext M tau AdmF _ QF
               (fun _ _ _ => I) (fun p x H => match H with end) glue_free s0).
    rewrite (det_barrier_exact stepA stepB eqvB eqvB_trans stepB_ext M s0), barB_free_iff, amodm_free_iff.
    tauto.
  Qed.

  (* det_barrier_closure_exact at free delivery. *)
  Theorem free_barrier_closure_exact : forall s0,
    BarD stepA stepB eqvB M tau AdmF (@Permutation _) QF s0 <->
    (forall u, PermB stepB eqvB (M (runA u s0))) /\ ClosureOK stepA M eqvB s0.
  Proof.
    intros s0. rewrite free_barrier_exact.
    exact (det_barrier_closure_exact stepA stepB eqvB eqvB_refl eqvB_trans stepB_ext M s0).
  Qed.
End Free.

