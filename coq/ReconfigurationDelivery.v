(* ---- The cross pair: an in-flight A-event against a B-event. ----
   A: one event that sets a flag. B: set (the image of A's event) and toggle. M the identity.
   A converges, DS1 holds, B's set and toggle do not commute. Declaring nothing (ix0) the switch
   is online; declaring only the pair (in-flight set, toggle) (ix1) the live switch diverges and the
   barrier switch converges. *)
Definition xsA (_ : unit) (_ : bool) : bool := true.
Definition xsB (e : bool) (y : bool) : bool := if e then true else negb y.
