(* The pair closure seeded with declared pairs only. *)
Section DeclClosure.
  Context {S E O : Type}.
  Variable step : E -> S -> S.
  Variable obs : S -> O.
  Variable eqv : O -> O -> Prop.
  Variable I : E -> E -> Prop.

  Local Notation run := (runT step).

  Inductive PCI (s0 : S) : S -> S -> Prop :=
  | pci_seed : forall u a b, I a b -> PCI s0 (step b (step a (run u s0))) (step a (step b (run u s0)))
  | pci_step : forall e x y, PCI s0 x y -> PCI s0 (step e x) (step e y).

  Definition ClosureI (s0 : S) : Prop := forall x y, PCI s0 x y -> eqv (obs x) (obs y).

  Lemma pci_run : forall s0 w x y, PCI s0 x y -> PCI s0 (run w x) (run w y).
  Proof.
    intros s0 w. induction w as [| e w IH]; intros x y H; [exact H |].
    rewrite !runT_cons. apply IH. apply pci_step. exact H.
  Qed.

  Theorem pci_iff : forall s0 x y, PCI s0 x y <->
    exists u a b w, I a b /\ x = run w (step b (step a (run u s0))) /\ y = run w (step a (step b (run u s0))).
  Proof.
    intros s0 x y. split.
    - intros H. induction H as [u a b Hab | e x y _ [u [a [b [w [Hab [-> ->]]]]]]].
      + exists u, a, b, []. split; [exact Hab | split; reflexivity].
      + exists u, a, b, (w ++ [e]). rewrite !runT_app. split; [exact Hab | split; reflexivity].
    - intros [u [a [b [w [Hab [-> ->]]]]]]. apply pci_run. apply pci_seed. exact Hab.
  Qed.

  Theorem closureI_swap_exact : forall s0, ClosureI s0 <->
    forall u a b w, I a b -> eqv (obs (run w (step b (step a (run u s0))))) (obs (run w (step a (step b (run u s0))))).
  Proof.
    intros s0. split.
    - intros H u a b w Hab. apply H. apply pci_iff. exists u, a, b, w. split; [exact Hab | split; reflexivity].
    - intros H x y P. apply pci_iff in P. destruct P as [u [a [b [w [Hab [-> ->]]]]]]. apply H. exact Hab.
  Qed.

  (* Finite instances: the closure is a finite search that finds a witness iff there is one. *)
  Section DeclClosureFinite.
    Variable eqS : forall a b : S, {a = b} + {a <> b}.
    Variable allS : list S.
    Hypothesis allS_full : forall s, In s allS.
    Variable evs : list E.
    Hypothesis evs_full : forall e, In e evs.
    Hypothesis I_dec : forall a b, {I a b} + {~ I a b}.
    Hypothesis eqv_dec : forall x y, {eqv (obs x) (obs y)} + {~ eqv (obs x) (obs y)}.

    Theorem pci_star_iff : forall s0 x y, PCI s0 x y <->
      exists t a b, (exists u, t = run u s0) /\ I a b /\
        star (Rsucc (psucc step evs)) (step b (step a t), step a (step b t)) (x, y).
    Proof.
      intros s0 x y. split.
      - intros H. induction H as [u a b Hab | e x y _ [t [a [b [Ht [Hab Hs]]]]]].
        + exists (run u s0), a, b. split; [exists u; reflexivity | split; [exact Hab | apply star_refl]].
        + exists t, a, b. split; [exact Ht | split; [exact Hab |]]. eapply star_trans; [exact Hs |]. apply star_one.
          unfold Rsucc, psucc. exact (in_map (fun e => (step e (fst (x, y)), step e (snd (x, y)))) evs e (evs_full e)).
      - intros [t [a [b [[u ->] [Hab Hs]]]]].
        refine (NC.GovernanceConverse.star_closed (Rsucc (psucc step evs)) (fun p => PCI s0 (fst p) (snd p)) _ _ (x, y) _ Hs).
        + intros p q Hp Hq. unfold Rsucc, psucc in Hq. apply in_map_iff in Hq.
          destruct Hq as [e [<- _]]. simpl. apply pci_step. exact Hp.
        + apply pci_seed. exact Hab.
    Qed.

    Lemma pci_dec : forall s0 x y, {PCI s0 x y} + {~ PCI s0 x y}.
    Proof.
      intros s0 x y. apply (dec_iff _ _ (iff_sym (pci_star_iff s0 x y))).
      apply (dec_exists_fin allS allS_full). intros t.
      apply (dec_exists_fin evs evs_full). intros a.
      apply (dec_exists_fin evs evs_full). intros b.
      apply dec_and; [apply (run_dec step eqS allS allS_full evs evs_full) |]. apply dec_and; [apply I_dec |].
      exact (star_fin_dec (prod_eq_dec eqS eqS) (list_prod allS allS) (prod_full allS allS allS_full allS_full)
               (psucc step evs) _ _).
    Qed.

    Theorem closureI_dec : forall s0, {ClosureI s0} + {~ ClosureI s0}.
    Proof.
      intros s0.
      assert (Iff : (forall p : S * S, PCI s0 (fst p) (snd p) -> eqv (obs (fst p)) (obs (snd p))) <-> ClosureI s0).
      { split; [intros H x y P; exact (H (x, y) P) | intros H [x y] P; exact (H x y P)]. }
      apply (dec_iff _ _ Iff).
      apply (dec_forall_fin (list_prod allS allS) (prod_full allS allS allS_full allS_full)).
      intros [x y]. apply dec_imp; [apply pci_dec | apply eqv_dec].
    Qed.

    Theorem closureI_witness_exact : forall s0,
      ~ ClosureI s0 <-> exists x y, PCI s0 x y /\ ~ eqv (obs x) (obs y).
    Proof.
      intros s0. split.
      - intros N. destruct (list_forall_or_witness (fun p : S * S => PCI s0 (fst p) (snd p) -> eqv (obs (fst p)) (obs (snd p)))
                              (list_prod allS allS)) as [H | [[x y] [_ Hn]]].
        + intros [x y]. apply dec_imp; [apply pci_dec | apply eqv_dec].
        + exfalso. apply N. intros x y P. exact (H (x, y) (prod_full allS allS allS_full allS_full (x, y)) P).
        + exists x, y. simpl in Hn. destruct (pci_dec s0 x y) as [P | P].
          * split; [exact P |]. intro Q. exact (Hn (fun _ => Q)).
          * exfalso. apply Hn. intro P'. contradiction.
      - intros [x [y [P N]]] H. exact (N (H x y P)).
    Qed.
  End DeclClosureFinite.
End DeclClosure.

Section DeclaredFree.
  Context {SA EA SB EB : Type}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.
  Variable IX : EA + EB -> EA + EB -> Prop.
  Hypothesis IX_sym : forall x y, IX x y -> IX y x.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).
  Local Notation runX := (runT (stepX stepB tau)).

  Lemma admF_prefix : forall l r : list (EA + EB), AdmF (l ++ r) -> AdmF l.
  Proof. intros l r _. exact I. Qed.
  Lemma admF_swap : forall l (a b : EA + EB) r, IX a b -> AdmF (l ++ a :: b :: r) -> AdmF (l ++ b :: a :: r).
  Proof. intros l a b r _ _. exact I. Qed.
  Lemma admF_split : forall p v, @AdmF EA EB (map inl p ++ map inr v) <-> AdmA (@AdmF EA EB) p /\ AdmB (@AdmF EA EB) v.
  Proof. intros p v. split; [intros _; split; exact I | intros _; exact I]. Qed.

  (* Live: every declared pair of the combined alphabet (A-pairs translated, an in-flight A-event
     with a B-event, B-pairs) commutes at every state reached from M s0, and DS1. *)
  Theorem live_declared_exact : forall s0,
    LiveD stepA stepB eqvB M tau AdmF (tequiv IX) s0 <->
    (forall w x y, IX x y ->
       eqvB (stepX stepB tau y (stepX stepB tau x (runX w (M s0)))) (stepX stepB tau x (stepX stepB tau y (runX w (M s0))))) /\
    DS1 stepA stepB eqvB M tau s0.
  Proof.
    intros s0. rewrite (live_trace_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau AdmF IX IX_sym
                          admF_prefix admF_swap s0).
    rewrite s1_free_iff. unfold CommS. split; intros [H1 H2]; split; try exact H2.
    - intros w x y Hxy. exact (H1 w x y I Hxy).
    - intros w x y _ Hxy. exact (H1 w x y Hxy).
  Qed.

  (* Barrier: B's declared pairs commute at every state B reaches from every migrated reachable
     state, and the pair closure seeded with A's declared pairs only migrates to equivalent states. *)
  Theorem barrier_declared_exact : forall s0,
    BarD stepA stepB eqvB M tau AdmF (tequiv IX) QT s0 <->
    (forall u v a b, IB IX a b ->
       eqvB (stepB b (stepB a (runB v (M (runA u s0))))) (stepB a (stepB b (runB v (M (runA u s0)))))) /\
    ClosureI stepA M eqvB (IA IX) s0.
  Proof.
    intros s0. rewrite (barrier_trace_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans stepB_ext M tau AdmF IX IX_sym
                          admF_prefix admF_swap admF_split s0).
    rewrite (amodt_swap_exact stepA eqvB eqvB_refl eqvB_sym eqvB_trans M AdmF IX IX_sym admF_swap s0).
    rewrite closureI_swap_exact. unfold CommS. split; intros [H1 H2]; split.
    - intros u v a b Hab. exact (H1 u I v a b I Hab).
    - intros u a b w Hab. pose proof (H2 u a b w I Hab) as K. rewrite !runT_app, !runT_cons in K. exact K.
    - intros u _ v a b _ Hab. exact (H1 u v a b Hab).
    - intros l a b r _ Hab. rewrite !runT_app, !runT_cons. exact (H2 l a b r Hab).
  Qed.
End DeclaredFree.

(* gsm's case decided on finite instances: Online, BarrierOnly or Unsafe, with no unknown. *)
Section DeclaredFinite.
  Context {SA EA SB EB : Type}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.
  Variable IX : EA + EB -> EA + EB -> Prop.
  Hypothesis IX_sym : forall x y, IX x y -> IX y x.
  Variable eqSA : forall a b : SA, {a = b} + {a <> b}.
  Variable eqSB : forall a b : SB, {a = b} + {a <> b}.
  Variable allA : list SA.
  Hypothesis allA_full : forall s, In s allA.
  Variable allB : list SB.
  Hypothesis allB_full : forall x, In x allB.
  Variable evsA : list EA.
  Hypothesis evsA_full : forall e, In e evsA.
  Variable evsB : list EB.
  Hypothesis evsB_full : forall e, In e evsB.
  Hypothesis eqvB_dec : forall x y, {eqvB x y} + {~ eqvB x y}.
  Hypothesis IX_dec : forall x y, {IX x y} + {~ IX x y}.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).
  Local Notation runX := (runT (stepX stepB tau)).

  Definition evsX : list (EA + EB) := map inl evsA ++ map inr evsB.
  Lemma evsX_full : forall x, In x evsX.
  Proof.
    intros [a | b]; apply in_or_app; [left; apply in_map_inl; apply evsA_full | right; apply in_map_inr; apply evsB_full].
  Qed.

  Lemma ds1_dec : forall s0, {DS1 stepA stepB eqvB M tau s0} + {~ DS1 stepA stepB eqvB M tau s0}.
  Proof.
    intros s0. unfold DS1.
    apply (forall_run_dec stepA eqSA allA allA_full evsA evsA_full s0
             (fun t => forall e, eqvB (M (stepA e t)) (stepB (tau e) (M t)))).
    intros t. apply (dec_forall_fin evsA evsA_full). intros e. apply eqvB_dec.
  Qed.

  Theorem live_declared_dec : forall s0,
    {LiveD stepA stepB eqvB M tau AdmF (tequiv IX) s0} + {~ LiveD stepA stepB eqvB M tau AdmF (tequiv IX) s0}.
  Proof.
    intros s0. apply (dec_iff _ _ (iff_sym (live_declared_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans
                                              stepB_ext M tau IX IX_sym s0))).
    apply dec_and; [| apply ds1_dec].
    refine (forall_run_dec (stepX stepB tau) eqSB allB allB_full evsX evsX_full (M s0)
              (fun t => forall x y, IX x y -> eqvB (stepX stepB tau y (stepX stepB tau x t))
                                                 (stepX stepB tau x (stepX stepB tau y t))) _). intros t.
    apply (dec_forall_fin evsX evsX_full). intros x. apply (dec_forall_fin evsX evsX_full). intros y.
    apply dec_imp; [apply IX_dec | apply eqvB_dec].
  Qed.

  Theorem barrier_declared_dec : forall s0,
    {BarD stepA stepB eqvB M tau AdmF (tequiv IX) QT s0} + {~ BarD stepA stepB eqvB M tau AdmF (tequiv IX) QT s0}.
  Proof.
    intros s0. apply (dec_iff _ _ (iff_sym (barrier_declared_exact stepA stepB eqvB eqvB_refl eqvB_sym eqvB_trans
                                              stepB_ext M tau IX IX_sym s0))).
    apply dec_and.
    - refine (forall_run_dec stepA eqSA allA allA_full evsA evsA_full s0
                (fun t => forall v a b, IB IX a b ->
                   eqvB (stepB b (stepB a (runB v (M t)))) (stepB a (stepB b (runB v (M t))))) _). intros t.
      apply (forall_run_dec stepB eqSB allB allB_full evsB evsB_full (M t)
               (fun z => forall a b, IB IX a b -> eqvB (stepB b (stepB a z)) (stepB a (stepB b z)))).
      intros z. apply (dec_forall_fin evsB evsB_full). intros a. apply (dec_forall_fin evsB evsB_full). intros b.
      apply dec_imp; [apply IX_dec | apply eqvB_dec].
    - apply (closureI_dec stepA M eqvB (IA IX) eqSA allA allA_full evsA evsA_full (fun a b => IX_dec (inl a) (inl b))
               (fun x y => eqvB_dec (M x) (M y))).
  Qed.

  Theorem classify_declared_complete : forall s0, {o : outcome | ClassD stepA stepB eqvB M tau AdmF (tequiv IX) QT s0 o}.
  Proof. intros s0. apply classD_decide; [apply live_declared_dec | apply barrier_declared_dec]. Qed.
End DeclaredFinite.

