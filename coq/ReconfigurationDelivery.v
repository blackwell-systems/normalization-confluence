(* ---- S1 at a duplicate prefix (at-least-once, live). ----
   A counts (not idempotent), B's image saturates at 1, M the identity. Every pair commutes and
   every event is idempotent after the switch, S1 holds at the duplicate-free prefixes, so the
   exactly-once (causal, no constraint) live switch is online; S1 fails at the prefix [a] with a
   delivered again, and the at-least-once live switch diverges. *)
Definition cdA (_ : unit) (s : nat) : nat := S s.
Definition cdB (_ : unit) (y : nat) : nat := Nat.max y 1.
Definition idN (s : nat) : nat := s.
Definition idU (e : unit) : unit := e.

Lemma cd_stepX : forall x y, stepX cdB idU x y = Nat.max y 1.
Proof. intros [[] | []] y; reflexivity. Qed.

Theorem count_dup_prefix :
  (CommND (stepX cdB idU) eq 0 /\ forall x, IdemND (stepX cdB idU) eq 0 x) /\
  ~ DS1 cdA cdB eq idN idU 0 /\
  ~ LiveD cdA cdB eq idN idU AdmF SameSet 0 /\
  LiveD cdA cdB eq idN idU (causal nohb) (@Permutation _) 0.
Proof.
  assert (Ds : ~ DS1 cdA cdB eq idN idU 0) by (intro H; specialize (H [tt] tt); discriminate H).
  split; [split | split; [exact Ds | split]].
  - intros p a b _ _. rewrite !cd_stepX. lia.
  - intros x u _. rewrite !cd_stepX. lia.
  - intro H. apply (live_free_alo_exact unit_dec' unit_dec' cdA cdB eq eq_refl' eq_sym' eq_trans' (eq_ext' cdB)
                      idN idU 0) in H. exact (Ds (proj2 H)).
  - apply (live_causal_exact cdA cdB eq eq_refl' eq_sym' eq_trans' (eq_ext' cdB) idN idU nohb 0). split.
    + intros p a b _ _. rewrite !cd_stepX. lia.
    + intros [| x u] [] Hc; [reflexivity |]. exfalso. destruct Hc as [Hnd _]. destruct x.
      inversion Hnd as [| ? ? Hn _]. apply Hn. apply in_or_app. right. left. reflexivity.
Qed.

(* ---- A duplicate straddling the barrier. ----
   A and B each set a flag; the migration resets it (M constant false), the event maps to B's set.
   B converges after every migrated state, A converges modulo M, and the exactly-once barrier is
   safe; but a redelivery after the switch of an event delivered before it sets B's flag: the
   at-least-once barrier diverges (AbsorbS fails, every other conjunct holds). *)
Definition rsA (_ : unit) (_ : bool) : bool := true.
Definition rsB (_ : unit) (_ : bool) : bool := true.
Definition rsM (_ : bool) : bool := false.

Lemma nohb_irrefl' : forall {E : Type} (x : E), ~ nohb x x.
Proof. intros E x []. Qed.
Lemma nohb_BA : forall {EA EB : Type} (a : EA) (b : EB), ~ @nohb (EA + EB) (inr b) (inl a).
Proof. intros EA EB a b []. Qed.

Theorem reset_straddle :
  ClassD rsA rsB eq rsM idU (causal nohb) (@Permutation _) QT false BarrierOnly /\
  ClassD rsA rsB eq rsM idU (causal_alo nohb) SameSet QA false Unsafe /\
  (forall p, causal_alo (hbA (@nohb (unit + unit))) p ->
     NC.DistributedDelivery.CCRonS rsB (hbB (@nohb (unit + unit))) eq (rsM (runT rsA p false)) /\
     forall b, NC.DistributedDelivery.IdemAtS rsB (hbB (@nohb (unit + unit))) eq (rsM (runT rsA p false)) b) /\
  AmodA rsA eq rsM (@nohb (unit + unit)) false /\ ~ AbsorbS rsA rsB eq rsM idU (@nohb (unit + unit)) false.
Proof.
  assert (NA : ~ AbsorbS rsA rsB eq rsM idU (@nohb (unit + unit)) false).
  { intro H.
    assert (A1 : causal_alo (hbA (@nohb (unit + unit))) [tt]) by (intros a b []).
    assert (A2 : causal_alo (hbB (@nohb (unit + unit))) []) by (intros a b []).
    specialize (H [tt] [] tt A1 A2 (or_introl eq_refl) (fun _ _ x => match x with end) (fun _ _ x => match x with end)).
    discriminate H. }
  split; [| split; [| split; [| split; [| exact NA]]]].
  - simpl. split.
    + apply (barrier_causal_exact rsA rsB eq eq_refl' eq_sym' eq_trans' (eq_ext' rsB) rsM idU nohb nohb_BA false).
      split; [intros p _ v a b _ _; reflexivity | intros p1 p2 _ _ _; reflexivity].
    + intro H. apply (live_causal_exact rsA rsB eq eq_refl' eq_sym' eq_trans' (eq_ext' rsB) rsM idU nohb false) in H.
      destruct H as [_ H]. specialize (H [] tt (causal_one _ (fun x => nohb_irrefl' x) tt)). discriminate H.
  - simpl. intro H.
    apply (barrier_alo_exact unit_dec' rsA rsB eq eq_refl' eq_sym' eq_trans' (eq_ext' rsB) rsM idU nohb
             nohb_irrefl' nohb_BA false) in H.
    exact (NA (proj1 (proj2 H))).
  - intros p _. split; [intros q a b _ _; reflexivity | intros b u _; reflexivity].
  - intros p1 p2 _ _ _. reflexivity.
Qed.

(* ---- Each barrier conjunct is needed under causal delivery. ---- *)
Definition lwB (b : bool) (_ : option bool) : option bool := Some b.
Definition unitA (_ : unit) (_ : unit) : unit := tt.
