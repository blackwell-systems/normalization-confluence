        delivery, cross_causal_online (the in-flight event ordered before the toggle) and
        cross_causal_barrier (concurrent with it). B's condition over the combined alphabet is
        needed, for exactly the cross pairs the class reorders.
      - count_dup_prefix: A counts, B's image saturates at 1, M the identity. Every pair commutes
        and every event is idempotent after the switch, and the exactly-once live switch is online;
        S1 fails at the prefix [a] delivered twice, so the at-least-once live switch diverges.
      - reset_straddle: A and B set a flag, M resets it. Exactly-once: BarrierOnly. At-least-once:
        Unsafe, by AbsorbS alone (B's condition and AmodA hold): a redelivery after the switch of
        an event delivered before it sets B's flag.
      - barrier_b_needed, barrier_a_needed: B diverging after the switch with A's part holding, and
        A diverging modulo M with B's part holding (causal delivery).
      - rescaled_max: max-registers, M and tau doubling: every condition of every class holds.
      - instances_classified: the three decision procedures run on the finite instances and return
        Online, BarrierOnly, Online, BarrierOnly, BarrierOnly, Unsafe.

   Scope. The deterministic model (gsm's runtime). Not covered: the rewriting model of
