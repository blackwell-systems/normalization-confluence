Section Generic.
  Context {SA EA SB EB : Type}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.

  (* After the switch an A-event x = inl a is applied as tau a, a B-event inr b as b. *)
  Definition trX (x : EA + EB) : EB := match x with inl a => tau a | inr b => b end.
  Definition stepX (x : EA + EB) (y : SB) : SB := stepB (trX x) y.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).
  Local Notation runX := (runT stepX).

  Lemma runX_map : forall w y, runX w y = runB (map trX w) y.
  Proof. induction w as [| x w IH]; intros y; [reflexivity |]. rewrite runT_cons. simpl map. rewrite runT_cons. apply IH. Qed.

  Lemma runX_inr : forall v y, runX (map inr v) y = runB v y.
  Proof. induction v as [| b v IH]; intros y; [reflexivity |]. simpl map. rewrite !runT_cons. apply IH. Qed.

  Lemma runX_ext : forall w x y, eqvB x y -> eqvB (runX w x) (runX w y).
  Proof.
    induction w as [| e w IH]; intros x y H; [exact H |].
    rewrite !runT_cons. apply IH. apply stepB_ext. exact H.
  Qed.

  (* A switched run: p delivered under A, the switch, then q (in-flight A-events and B-events)
     under B. *)
  Definition outD (s0 : SA) (p : list EA) (q : list (EA + EB)) : SB := runX q (M (runA p s0)).

  (* The delivery class: the admissible delivery sequences of the combined alphabet, closed under
     prefixes, compared by a relation reflexive on them (as in DistributedDelivery.v). *)
  Variable Adm : list (EA + EB) -> Prop.
  Variable Rel : list (EA + EB) -> list (EA + EB) -> Prop.

  (* Live: the switch may fall anywhere before the first B-event. *)
  Definition LiveD (s0 : SA) : Prop :=
    forall p1 q1 p2 q2, Adm (map inl p1 ++ q1) -> Adm (map inl p2 ++ q2) ->
      Rel (map inl p1 ++ q1) (map inl p2 ++ q2) -> eqvB (outD s0 p1 q1) (outD s0 p2 q2).

  (* B's class condition from y over the combined alphabet (every delivery after the switch). *)
  Definition ConvXD (y : SB) : Prop :=
    forall w1 w2, Adm w1 -> Adm w2 -> Rel w1 w2 -> eqvB (runX w1 y) (runX w2 y).

  (* S1 at the A-prefixes the class admits: an in-flight event commutes with the switch. *)
  Definition S1D (s0 : SA) : Prop :=
    forall u a, Adm (map inl (u ++ [a])) ->
      eqvB (M (stepA a (runA u s0))) (stepB (tau a) (M (runA u s0))).

  Section Live.
    Hypothesis adm_prefix : forall l r, Adm (l ++ r) -> Adm l.
    Hypothesis rel_refl : forall l, Adm l -> Rel l l.

    Lemma M_runD : forall s0, S1D s0 -> forall u, Adm (map inl u) ->
      eqvB (M (runA u s0)) (runX (map inl u) (M s0)).
    Proof.
      intros s0 HS u. induction u as [| a u IH] using rev_ind; intros Ha; [apply eqvB_refl |].
      rewrite map_app in Ha. pose proof (adm_prefix _ _ Ha) as Hu.
      rewrite runT_app, map_app, runT_app. simpl.
      apply (eqvB_trans _ _ _ (HS u a (eq_ind_r Adm Ha (map_app inl u [a])))).
      apply stepB_ext. exact (IH Hu).
    Qed.

    Theorem live_delivery_exact : forall s0, LiveD s0 <-> ConvXD (M s0) /\ S1D s0.
    Proof.
      intros s0. split.
      - intros H. split.
        + intros w1 w2 H1 H2 HR. exact (H [] w1 [] w2 H1 H2 HR).
        + intros u a Ha. rewrite map_app in Ha.
          pose proof (H (u ++ [a]) [] u [inl a]) as K. unfold outD in K.
          rewrite map_app, app_nil_r in K. specialize (K Ha Ha (rel_refl _ Ha)).
          rewrite runT_app in K. exact K.
      - intros [HC HS] p1 q1 p2 q2 H1 H2 HR. unfold outD.
        assert (K : forall p q, Adm (map inl p ++ q) ->
                  eqvB (runX q (M (runA p s0))) (runX (map inl p ++ q) (M s0))).
        { intros p q Hpq. rewrite runT_app. apply runX_ext. apply M_runD; [exact HS |].
          exact (adm_prefix _ _ Hpq). }
        apply (eqvB_trans _ _ _ (K p1 q1 H1)). apply (eqvB_trans _ (runX (map inl p2 ++ q2) (M s0))).
        + apply HC; assumption.
        + apply eqvB_sym. exact (K p2 q2 H2).
    Qed.
  End Live.

  (* Barrier: the switch falls only where the continuation q is allowed by Q p q (exactly-once
     classes: B-events only; at-least-once classes: B-events and redeliveries of A-events already
     delivered). *)
  Variable Q : list EA -> list (EA + EB) -> Prop.

  Definition BarD (s0 : SA) : Prop :=
    forall p1 q1 p2 q2, Q p1 q1 -> Q p2 q2 -> Adm (map inl p1 ++ q1) -> Adm (map inl p2 ++ q2) ->
      Rel (map inl p1 ++ q1) (map inl p2 ++ q2) -> eqvB (outD s0 p1 q1) (outD s0 p2 q2).

  (* A converges under the class modulo M. *)
  Definition AmodMD (s0 : SA) : Prop :=
    forall p1 p2, Adm (map inl p1) -> Adm (map inl p2) -> Rel (map inl p1) (map inl p2) ->
      eqvB (M (runA p1 s0)) (M (runA p2 s0)).

  (* B's class condition after a quiescent switch at every migrated reachable state. *)
  Definition BarBD (s0 : SA) : Prop :=
    forall p q1 q2, Q p q1 -> Q p q2 -> Adm (map inl p ++ q1) -> Adm (map inl p ++ q2) ->
      Rel (map inl p ++ q1) (map inl p ++ q2) -> eqvB (runX q1 (M (runA p s0))) (runX q2 (M (runA p s0))).

  (* The class lets the A part and the B part of two related barrier runs be compared separately. *)
  Definition Glue : Prop :=
    forall p1 q1 p2 q2, Q p1 q1 -> Q p2 q2 -> Adm (map inl p1 ++ q1) -> Adm (map inl p2 ++ q2) ->
      Rel (map inl p1 ++ q1) (map inl p2 ++ q2) ->
      Rel (map inl p1) (map inl p2) /\ Q p2 q1 /\ Adm (map inl p2 ++ q1) /\
      Rel (map inl p2 ++ q1) (map inl p2 ++ q2).

  Section Barrier.
    Hypothesis adm_prefix : forall l r, Adm (l ++ r) -> Adm l.
    Hypothesis q_nil : forall p, Q p [].
    Hypothesis glue : Glue.

    Theorem barrier_delivery_exact : forall s0, BarD s0 <-> BarBD s0 /\ AmodMD s0.
    Proof.
      intros s0. split.
      - intros H. split.
        + intros p q1 q2 Q1 Q2 H1 H2 HR. exact (H p q1 p q2 Q1 Q2 H1 H2 HR).
        + intros p1 p2 H1 H2 HR.
          pose proof (H p1 [] p2 [] (q_nil p1) (q_nil p2)) as K. unfold outD in K.
          rewrite !app_nil_r in K. exact (K H1 H2 HR).
      - intros [HB HA] p1 q1 p2 q2 Q1 Q2 H1 H2 HR. unfold outD.
        destruct (glue p1 q1 p2 q2 Q1 Q2 H1 H2 HR) as [RA [Q21 [H21 R2]]].
        apply (eqvB_trans _ (runX q1 (M (runA p2 s0)))).
        + apply runX_ext. apply HA; [exact (adm_prefix _ _ H1) | exact (adm_prefix _ _ H2) | exact RA].
        + exact (HB p2 q1 q2 Q21 Q2 H21 H2 R2).
    Qed.
  End Barrier.

  Theorem live_implies_barrier_d : forall s0, LiveD s0 -> BarD s0.
  Proof. intros s0 H p1 q1 p2 q2 _ _. apply H. Qed.
End Generic.

(* Outcome of a switch under a class: Online, BarrierOnly or Unsafe, as in Reconfiguration.v. *)
Definition ClassD {SA EA SB EB : Type} (stepA : EA -> SA -> SA) (stepB : EB -> SB -> SB)
  (eqvB : SB -> SB -> Prop) (M : SA -> SB) (tau : EA -> EB) (Adm : list (EA + EB) -> Prop)
  (Rel : list (EA + EB) -> list (EA + EB) -> Prop) (Q : list EA -> list (EA + EB) -> Prop)
  (s0 : SA) (o : outcome) : Prop :=
  match o with
  | Online => LiveD stepA stepB eqvB M tau Adm Rel s0
  | BarrierOnly => BarD stepA stepB eqvB M tau Adm Rel Q s0 /\ ~ LiveD stepA stepB eqvB M tau Adm Rel s0
  | Unsafe => ~ BarD stepA stepB eqvB M tau Adm Rel Q s0
  end.

Theorem classD_unique : forall {SA EA SB EB : Type} stepA stepB eqvB (M : SA -> SB) (tau : EA -> EB)
  (Adm : list (EA + EB) -> Prop) Rel Q s0 o1 o2,
  ClassD stepA stepB eqvB M tau Adm Rel Q s0 o1 -> ClassD stepA stepB eqvB M tau Adm Rel Q s0 o2 -> o1 = o2.
Proof.
  intros SA EA SB EB stepA stepB eqvB M tau Adm Rel Q s0 o1 o2 H1 H2.
  pose proof (live_implies_barrier_d stepA stepB eqvB M tau Adm Rel Q s0) as LB.
  destruct o1, o2; simpl in *; try reflexivity; try tauto.
Qed.

Theorem classD_decide : forall {SA EA SB EB : Type} stepA stepB eqvB (M : SA -> SB) (tau : EA -> EB)
  (Adm : list (EA + EB) -> Prop) Rel Q s0,
  {LiveD stepA stepB eqvB M tau Adm Rel s0} + {~ LiveD stepA stepB eqvB M tau Adm Rel s0} ->
  {BarD stepA stepB eqvB M tau Adm Rel Q s0} + {~ BarD stepA stepB eqvB M tau Adm Rel Q s0} ->
  {o : outcome | ClassD stepA stepB eqvB M tau Adm Rel Q s0 o}.
Proof.
  intros SA EA SB EB stepA stepB eqvB M tau Adm Rel Q s0 [L | L] [Bc | Bc].
  - exists Online. exact L.
  - exists Online. exact L.
  - exists BarrierOnly. split; assumption.
  - exists Unsafe. exact Bc.
Qed.

(* Two relations that agree on admissible sequences give the same outcome. *)
Lemma liveD_rel_ext : forall {SA EA SB EB : Type} stepA stepB eqvB (M : SA -> SB) (tau : EA -> EB)
  (Adm : list (EA + EB) -> Prop) Rel Rel',
  (forall w1 w2, Adm w1 -> Adm w2 -> (Rel w1 w2 <-> Rel' w1 w2)) ->
  forall s0, LiveD stepA stepB eqvB M tau Adm Rel s0 <-> LiveD stepA stepB eqvB M tau Adm Rel' s0.
Proof.
  intros SA EA SB EB stepA stepB eqvB M tau Adm Rel Rel' H s0.
  split; intros L p1 q1 p2 q2 H1 H2 R; apply L; try assumption; apply (H _ _ H1 H2); exact R.
Qed.

Lemma barD_rel_ext : forall {SA EA SB EB : Type} stepA stepB eqvB (M : SA -> SB) (tau : EA -> EB)
  (Adm : list (EA + EB) -> Prop) Rel Rel' Q,
  (forall w1 w2, Adm w1 -> Adm w2 -> (Rel w1 w2 <-> Rel' w1 w2)) ->
  forall s0, BarD stepA stepB eqvB M tau Adm Rel Q s0 <-> BarD stepA stepB eqvB M tau Adm Rel' Q s0.
Proof.
  intros SA EA SB EB stepA stepB eqvB M tau Adm Rel Rel' Q H s0.
  split; intros L p1 q1 p2 q2 Q1 Q2 H1 H2 R; apply L; try assumption; apply (H _ _ H1 H2); exact R.
Qed.

Lemma allB_ex : forall {EA EB : Type} (q : list (EA + EB)), AllB q -> exists v, q = map inr v.
Proof. intros EA EB q H. exists (projB q). apply allB_inr. exact H. Qed.

