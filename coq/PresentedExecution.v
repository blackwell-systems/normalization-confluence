(* 4d. Declared pairs: AtLeastOnceDeclared.tconv_exact (a trace monoid), through P1             *)
(* ============================================================================================ *)

Section DeclaredP.
  Context {S E : Type}.
  Variable step : E -> S -> S.
  Variable Ev : E -> Prop.
  Variable hb I : E -> E -> Prop.
  Hypothesis I_sym : forall a b, I a b -> I b a.
  Hypothesis I_irrefl : forall a, ~ I a a.
  Hypothesis I_hb : forall a b, I a b -> ~ hb a b.
  Variable s0 : S.

  Local Notation causal := (CausalReplay.causal hb).
  Local Notation sem := (msem step (fun x => x) s0).

  (* Admissible: a history over Ev. Generator: a declared pair at a point where it is deliverable. *)
  Definition dg_adm (t : list E) : Prop := Forall Ev t /\ causal t.
  Definition dg_gen (p u v : list E) : Prop :=
    exists a b, I a b /\ Forall Ev (p ++ [a; b]) /\ causal (p ++ [a; b]) /\ u = [a; b] /\ v = [b; a].

  Lemma dg_prefix : AdmPrefix dg_adm.
  Proof.
    intros t w [Hf Hc]. split; [| exact (GovernanceConverse.causal_prefix hb t w Hc)].
    apply Forall_app in Hf. exact (proj1 Hf).
  Qed.

  Lemma dg_tequiv_peq : forall o1 o2, tequiv I o1 o2 -> dg_adm o1 -> PEq dg_adm dg_gen o1 o2.
  Proof.
    intros o1 o2 H. induction H as [l | l a b r Hab | l1 l2 H IH | l1 l2 l3 H1 IH1 H2 IH2]; intros Ha.
    - apply ac_refl. exact Ha.
    - destruct Ha as [Hf Hc].
      assert (Hb : dg_adm (l ++ b :: a :: r)).
      { split; [exact (Permutation_Forall (Permutation_app_head l (perm_swap b a r)) Hf) |].
        exact (AtLeastOnceDeclared.tequiv_I_causal hb I I_sym I_irrefl I_hb _ _ (teq_swap I l a b r Hab) Hc). }
      apply ac_gen; [split; assumption | exact Hb |]. exists l, [a; b], [b; a], r.
      split; [| split; reflexivity]. exists a, b. split; [exact Hab |].
      replace (l ++ a :: b :: r) with ((l ++ [a; b]) ++ r) in Hf, Hc by (rewrite <- app_assoc; reflexivity).
      split; [apply Forall_app in Hf; exact (proj1 Hf) |].
      split; [exact (GovernanceConverse.causal_prefix hb _ r Hc) | split; reflexivity].
    - apply ac_sym. apply IH. destruct Ha as [Hf Hc]. split.
      + exact (Permutation_Forall (Permutation_sym (tequiv_perm _ _ _ H)) Hf).
      + exact (AtLeastOnceDeclared.tequiv_I_causal hb I I_sym I_irrefl I_hb _ _ (teq_sym _ _ _ H) Hc).
    - eapply ac_trans; [apply IH1; exact Ha |]. apply IH2. destruct Ha as [Hf Hc]. split.
      + exact (Permutation_Forall (tequiv_perm _ _ _ H1) Hf).
      + exact (AtLeastOnceDeclared.tequiv_I_causal hb I I_sym I_irrefl I_hb _ _ H1 Hc).
  Qed.

  Lemma dg_peq_tequiv : forall o1 o2, PEq dg_adm dg_gen o1 o2 -> tequiv I o1 o2.
  Proof.
    intros o1 o2 H. induction H as [t _ | t t' _ _ (p & u & v & w & (a & b & Hab & _ & _ & -> & ->) & -> & ->)
                                   | t t' _ IH | t t' t'' _ IH1 _ IH2].
    - apply teq_refl.
    - apply teq_swap. exact Hab.
    - apply teq_sym. exact IH.
    - eapply teq_trans; eassumption.
  Qed.

  Theorem tconv_exact_recovered :
    AtLeastOnceDeclared.TConvI step Ev hb I s0 <-> AtLeastOnceDeclared.CommI step Ev hb I s0.
  Proof.
    assert (S1 : AtLeastOnceDeclared.TConvI step Ev hb I s0 <-> PInv dg_adm dg_gen sem eq).
    { split.
      - intros H t t' Hq. destruct (ac_adm' dg_adm (Whisk dg_gen) t t' Hq)
          as [[Hf Hc] _].
        exact (H t t' Hf Hc (dg_peq_tequiv t t' Hq)).
      - intros H o1 o2 Hf Hc T. apply H. apply dg_tequiv_peq; [exact T | split; assumption]. }
    assert (S2 : PInv dg_adm dg_gen sem eq <-> PSeedOK dg_adm dg_gen sem eq).
    { apply local_exact_all; [exact (@eq_refl _) | exact (@eq_sym _) | exact (@eq_trans _)
                              | exact dg_prefix |].
      intros t t' e _ _. apply msem_eq_resp. }
    rewrite S1, S2. split.
    - intros H p a b Hf Hc Hab.
      assert (Hb : dg_adm (p ++ [b; a])).
      { split; [exact (Permutation_Forall (Permutation_app_head p (perm_swap b a [])) Hf) |].
        exact (AtLeastOnceDeclared.tequiv_I_causal hb I I_sym I_irrefl I_hb _ _ (teq_swap I p a b [] Hab) Hc). }
      pose proof (H p [a; b] [b; a]
                    (ex_intro _ a (ex_intro _ b (conj Hab (conj Hf (conj Hc (conj eq_refl eq_refl))))))
                    (conj Hf Hc) Hb) as K.
      unfold msem in K. rewrite !runT_app in K. exact K.
    - intros H p u v (a & b & Hab & Hf & Hc & -> & ->) _ _. unfold msem. rewrite !runT_app.
      exact (H p a b Hf Hc Hab).
  Qed.
End DeclaredP.

