(* 4e. At-least-once delivery: legal duplicate landings, through P1                             *)
(* ============================================================================================ *)

Section ALOP.
  Context {S E : Type}.
  Variable dec : forall x y : E, {x = y} + {x <> y}.
  Variable step : E -> S -> S.
  Variable Ev : E -> Prop.
  Variable hb : E -> E -> Prop.
  Hypothesis hb_irrefl : forall x, ~ hb x x.
  Variable s0 : S.

  Local Notation causal := (CausalReplay.causal hb).
  Local Notation adm := (CanonicalInstances.alo_adm Ev hb).
  Local Notation sem := (msem step (fun x => x) s0).

  (* Generators: a concurrent swap at a causal point, and the legal duplicate landing: a second
     copy right after the first delivery, which ends an exactly-once causal prefix. *)
  Definition ag_gen (p u v : list E) : Prop :=
    (exists a b, CausalReplay.concurrent hb a b /\ causal (p ++ [a; b]) /\ u = [a; b] /\ v = [b; a]) \/
    (exists a, causal (p ++ [a]) /\ u = [a; a] /\ v = [a]).

  Lemma ag_prefix : AdmPrefix adm.
  Proof.
    intros t w [Hf Hc]. split; [apply Forall_app in Hf; exact (proj1 Hf) |].
    intros a b Hab l r Ed Hb Ha. apply (Hc a b Hab l (r ++ w)); [| exact Hb | apply in_or_app; left; exact Ha].
    rewrite Ed, app_assoc. reflexivity.
  Qed.

  Lemma ag_whisk : forall t t', Whisk ag_gen t t' <-> CanonicalInstances.G_idem hb t t'.
  Proof.
    intros t t'. split.
    - intros (p & u & v & w & [(a & b & Hab & Hc & -> & ->) | (a & Hc & -> & ->)] & -> & ->).
      + left. exists p, a, b, w. tauto.
      + right. exists p, a, w. split; [exact Hc | split; reflexivity].
    - intros [(p & a & b & r & Hab & Hc & -> & ->) | (p & a & r & Hc & -> & ->)].
      + exists p, [a; b], [b; a], r. split; [left; exists a, b; tauto | split; reflexivity].
      + exists p, [a; a], [a], r. split; [right; exists a; tauto | split; reflexivity].
  Qed.

  Lemma ag_peq : forall t t', PEq adm ag_gen t t' <-> AC adm (CanonicalInstances.G_idem hb) t t'.
  Proof. intros t t'. split; apply ac_impl; intros x y _ _ H; apply ag_whisk; exact H. Qed.

  Theorem causal_alo_idem_recovered :
    AtLeastOnceExact.CALOConv step Ev hb s0 <->
    AtLeastOnceExact.CCRon step Ev hb s0 /\ forall a, AtLeastOnceExact.IdemAt step Ev hb s0 a.
  Proof.
    pose proof (CanonicalInstances.alo_adequate_idem dec Ev hb hb_irrefl) as HA.
    assert (S1 : AtLeastOnceExact.CALOConv step Ev hb s0 <-> PInv adm ag_gen sem eq).
    { rewrite (CanonicalInstances.caloconv_hd dec step Ev hb hb_irrefl s0). split.
      - intros H t t' Hq. apply ag_peq in Hq.
        destruct (ac_adm' adm (CanonicalInstances.G_idem hb) t t' Hq) as [Ht Ht'].
        exact (H t t' Ht Ht' (proj2 (HA t t' Ht Ht') Hq)).
      - intros H t u Ht Hu Hs. apply (H t u). apply ag_peq. exact (proj1 (HA t u Ht Hu) Hs). }
    assert (S2 : PInv adm ag_gen sem eq <-> PSeedOK adm ag_gen sem eq).
    { apply local_exact_all; [exact (@eq_refl _) | exact (@eq_sym _) | exact (@eq_trans _)
                              | exact ag_prefix |].
      intros t t' e _ _. apply msem_eq_resp. }
    rewrite S1, S2. split.
    - intros H. split.
      + intros p a b Hev Hab Hc.
        assert (Hc' : causal (p ++ [b; a]))
          by exact (GovernanceConverse.causal_swap hb p a b [] (proj1 (proj2 Hab)) Hc).
        assert (Hev' : Forall Ev (p ++ [b; a]))
          by exact (Permutation_Forall (Permutation_app_head p (perm_swap b a [])) Hev).
        pose proof (H p [a; b] [b; a]
                      (or_introl (ex_intro _ a (ex_intro _ b (conj Hab (conj Hc (conj eq_refl eq_refl))))))
                      (CanonicalInstances.adm_causal Ev hb _ Hc Hev)
                      (CanonicalInstances.adm_causal Ev hb _ Hc' Hev')) as K.
        unfold msem in K. rewrite !runT_app in K. exact K.
      + intros a u Hev Hc.
        assert (Hx : Ev a) by (rewrite Forall_forall in Hev; apply Hev; apply in_or_app; right; left; reflexivity).
        assert (Hns : forall b, In b (u ++ [a]) -> ~ hb a b).
        { intros b Hb Hab. apply in_app_or in Hb. destruct Hb as [Hb | [<- | []]]; [| exact (hb_irrefl a Hab)].
          destruct Hc as [Hnd Hcc]. apply (CausalReplay.prec_before_contra u a [] b Hnd Hb).
          apply Hcc; [exact Hab | apply in_or_app; right; left; reflexivity | apply in_or_app; left; exact Hb]. }
        pose proof (CanonicalInstances.adm_snoc Ev hb (u ++ [a]) a Hc Hev Hx Hns) as A1.
        rewrite <- app_assoc in A1.
        pose proof (H u [a; a] [a] (or_intror (ex_intro _ a (conj Hc (conj eq_refl eq_refl))))
                      A1 (CanonicalInstances.adm_causal Ev hb _ Hc Hev)) as K.
        unfold msem in K. rewrite !runT_app in K. exact K.
    - intros [HC HI] p u v [(a & b & Hab & Hc & -> & ->) | (a & Hc & -> & ->)] [Hf _] _;
        unfold msem; rewrite !runT_app.
      + exact (HC p a b Hf Hab Hc).
      + apply HI; [| exact Hc].
        replace (p ++ [a; a]) with ((p ++ [a]) ++ [a]) in Hf by (rewrite <- app_assoc; reflexivity).
        apply Forall_app in Hf. exact (proj1 Hf).
  Qed.
End ALOP.

(* AtLeastOnceExact.alo_exact, the free instance (hb empty) of causal_alo_idem_recovered. *)
Theorem alo_exact_recovered : forall {S E : Type} (dec : forall x y : E, {x = y} + {x <> y})
  (step : E -> S -> S) (Ev : E -> Prop) (s0 : S),
  AtLeastOnceExact.ALOConv step Ev s0 <->
  AtLeastOnceExact.CommReach step Ev s0 /\ forall a, AtLeastOnceExact.IdemReach step Ev s0 a.
Proof.
  intros S E dec step Ev s0.
  rewrite AtLeastOnceExact.aloconv_iff,
    (causal_alo_idem_recovered dec step Ev AtLeastOnceExact.nohb AtLeastOnceExact.nohb_irrefl s0),
    AtLeastOnceExact.comm_iff.
  split; intros [HC H]; split; try exact HC; intros a; apply AtLeastOnceExact.idem_iff; exact (H a).
Qed.

