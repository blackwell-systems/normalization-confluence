    Reconfiguration.PermB stepB eqvB (M s0) /\ Reconfiguration.DS1 stepA stepB eqvB M tau s0.
  Proof. rewrite lv_dlive_inv, lv_local, lv_seeds_iff. exact lv_seeds_live. Qed.
