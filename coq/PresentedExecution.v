(* PresentedExecution.v: layer A of the regime map, the execution algebra, as a presented
   admissible path system. Axiom-free.

   The question layer A answers: which executions count as the same, and when is the semantics
   invariant under that identification. Executions do not form a free monoid in general: only
   admissible words are executions (causal delivery, typed phases, legal duplicate landings), so
   the structure is an admissible path system. Here a path is a word of labels from a fixed start,
   admissibility is a predicate Adm on words (closed under prefixes where a theorem needs it), and
   the elementary alternative executions are generator pairs Gen p u v: at the point p (an
   admissible prefix) the fragments u and v are interchangeable. Examples: a swap of independent
   events u = [a; b], v = [b; a]; a legal duplicate landing u = [a; a], v = [a]; a switch square
   u = [a; sw], v = [sw; tau a] between typed phases. The generated equivalence PEq is the
   equivalence closure, with every vertex admissible, of the whiskered generators
     p ++ u ++ w  ~  p ++ v ++ w    (Gen p u v, both sides admissible)
   (pre-composition is the choice of the point p, post-composition the continuation w). It is
   CanonicalExecution.AC on the whiskered generators, so every intermediate execution is
   admissible. Free delivery is the degenerate case (Adm everything, Gen independent of the
   point): PEq is then the monoid congruence generated by the generator pairs (free_congruence),
   and with the adjacent swaps it is Permutation (swap_peq_perm).

   The semantics is a map sem from words to values compared by an equivalence eqv (for a state
   machine: sem t = obs (run t s0)). PInv: sem is constant, up to eqv, on PEq classes.

   1. Generic (section Presented).
      - PPC, the continuation closure of the generators: the seeds (p ++ u, p ++ v) with both
        sides admissible, closed under appending the same event to both sides when both stay
        admissible. ReconfigurationClosure.PC is the free instance (amodm_closure_recovered).
        ppc_least: PPC is contained in every relation that contains the seeds and is closed under
        admissible one-event continuation. ppc_iff_whisk: under prefix closure, PPC is exactly the
        set of whiskered generator pairs with both sides admissible.
      - (P2) closure_exact: AdmPrefix -> (PInv <-> PClosOK): invariance holds iff sem agrees on
        the continuation closure.
      - (P1) local_exact: if a predicate Q holds on both sides of every seed, is preserved by
        admissible one-event extension, and the semantics respects the future on Q (eqv-related
        Q-paths stay eqv-related after the same admissible event, RespOn), then
          PInv <-> PSeedOK,
        PSeedOK: every generator pair is observationally equal at its point. local_exact_all is
        Q = everything; seeds_necessary: PInv -> PSeedOK with no hypothesis.
      - Section StateMachine: sem t = obs (run t s0); resp_of_compat derives RespOn from
        compatibility of obs with the steps (the hypothesis of
        ReconfigurationClosure.perm_local_exact).
   2. The seeds alone do not suffice without RespOn (section HiddenWrite): writes to a hidden
      register and a reveal event. hw_seeds_ok: every swap seed is observationally equal at every
      point; hw_not_inv: invariance fails; hw_closure_witness: the closure pair that separates is
      a seed continued by the reveal event. So the continuation closure is needed in P2, and
      RespOn cannot be dropped from P1.
   3. The state side (section StateSide). State descent (CC2 in its all-events form,
      CanonicalExecution.state_descent_iff_cc2) compares the SAME word from a state and from its
      canonical form: it relates two states, not two parallel paths from one point, so it is not
      a generator. It enters through the semantics: state_side_transfer, under StateDescent the
      normalized raw semantics and the governed semantics from N s0 are the same function on
      words, so invariance of one under any path presentation is invariance of the other.
   4. Instances (each recovered statement is proved from P1 or P2).
      - history_descent_recovered: CanonicalExecution.history_descent_exact, through the one-step
        path system (executions as one-letter words; P1 with RespOn vacuous).
      - amodm_closure_recovered, amodm_swap_recovered: ReconfigurationClosure.amodm_closure_exact
        and amodm_swap_exact through P2 (free delivery, adjacent swaps, M not compatible).
      - causal_exact_recovered: GovernanceConverse.causal_exact through P1 (admissibility =
        causal consistency, generators = adjacent concurrent swaps at a causal point).
      - tconv_exact_recovered: AtLeastOnceDeclared.tconv_exact through P1 (declared pairs: the
        trace monoid of I, restricted to causal histories over Ev).
      - causal_alo_idem_recovered, alo_exact_recovered: AtLeastOnceExact.causal_alo_exact_idem
        and alo_exact through P1 (generators = concurrent swaps plus the legal duplicate landing
        [a; a] ~ [a] right after a first delivery).
      - det_live_recovered: Reconfiguration.det_live_exact through P1 with Q = "past the switch"
        (typed phases A, then B; generators = switch squares [LA a; LS] ~ [LS; LT a] and swaps
        after the switch). *)

