(* 4f. Typed phases: switch squares, Reconfiguration.det_live_exact through P1                  *)
(* ============================================================================================ *)

(* Labels of a live reconfiguration run: an A-event, the switch, an in-flight A-event applied after
   the switch (translated), a native B-event. *)
Inductive SwLab {EA EB : Type} : Type :=
| LA (a : EA) | LS | LT (a : EA) | LB (b : EB).
Arguments SwLab : clear implicits.

Definition isPost {EA EB : Type} (l : SwLab EA EB) : Prop :=
  match l with LT _ | LB _ => True | _ => False end.

(* Typed phases: A-events, then at most one switch, then only post-switch labels. *)
Fixpoint phA {EA EB : Type} (w : list (SwLab EA EB)) : Prop :=
  match w with
  | [] => True
  | LA _ :: w' => phA w'
  | LS :: w' => Forall isPost w'
  | _ => False
  end.

Lemma phA_prefix : forall {EA EB : Type}, AdmPrefix (@phA EA EB).
Proof.
  intros EA EB t. induction t as [| [a | | a | b] t IH]; intros w H; simpl in *; try tauto.
  - exact (IH w H).
  - apply Forall_app in H. exact (proj1 H).
Qed.

Lemma phA_mapA : forall {EA EB : Type} (u : list EA) (r : list (SwLab EA EB)),
  phA (map LA u ++ r) <-> phA r.
Proof. intros EA EB u r. induction u as [| a u IH]; simpl; tauto. Qed.

(* An admissible word is all A, or A, the switch, then post labels. *)
Lemma phA_shape : forall {EA EB : Type} (w : list (SwLab EA EB)), phA w ->
  (exists u, w = map LA u) \/ (exists u x, w = map LA u ++ LS :: x /\ Forall isPost x).
Proof.
  intros EA EB w. induction w as [| [a | | a | b] w IH]; intros H; simpl in H; try contradiction.
  - left. exists []. reflexivity.
  - destruct (IH H) as [[u ->] | (u & x & -> & Hx)].
    + left. exists (a :: u). reflexivity.
    + right. exists (a :: u), x. split; [reflexivity | exact Hx].
  - right. exists [], w. split; [reflexivity | exact H].
Qed.

(* A post label in an admissible word comes after the switch. *)
Lemma phA_post_LS : forall {EA EB : Type} (w : list (SwLab EA EB)) l, phA w -> In l w -> isPost l ->
  In LS w.
Proof.
  intros EA EB w l H Hl Hp. destruct (phA_shape w H) as [[u ->] | (u & x & -> & _)].
  - apply in_map_iff in Hl. destruct Hl as [a [<- _]]. simpl in Hp. contradiction.
  - apply in_or_app. right. left. reflexivity.
Qed.

Lemma phA_A_point : forall {EA EB : Type} (p r : list (SwLab EA EB)) a, phA (p ++ LA a :: r) ->
  exists u, p = map LA u.
Proof.
  intros EA EB p r a H. destruct (phA_shape p (phA_prefix p _ H)) as [[u ->] | (u & x & -> & Hx)].
  - exists u. reflexivity.
  - exfalso. rewrite <- app_assoc in H. apply phA_mapA in H. simpl in H.
    apply Forall_app in H. destruct H as [_ H]. inversion H as [| ? ? Hc _]. exact Hc.
Qed.

Lemma phA_post_point : forall {EA EB : Type} (p r : list (SwLab EA EB)) l, isPost l -> phA (p ++ l :: r) ->
  exists u x, p = map LA u ++ LS :: x /\ Forall isPost x.
Proof.
  intros EA EB p r l Hl H. destruct (phA_shape p (phA_prefix p _ H)) as [[u ->] | Hs]; [| exact Hs].
  exfalso. apply phA_mapA in H. destruct l; simpl in H, Hl; contradiction.
Qed.

(* The B-events a word contributes after the switch, the A-events and the native B-events. *)
Definition labo {EA EB : Type} (tau : EA -> EB) (l : SwLab EA EB) : list EB :=
  match l with LT a => [tau a] | LB b => [b] | _ => [] end.
Definition aOf {EA EB : Type} (w : list (SwLab EA EB)) : list EA :=
  flat_map (fun l => match l with LA a | LT a => [a] | _ => [] end) w.
Definition bOf {EA EB : Type} (w : list (SwLab EA EB)) : list EB :=
  flat_map (fun l => match l with LB b => [b] | _ => [] end) w.
Definition tOf {EA EB : Type} (w : list (SwLab EA EB)) : list EA :=
  flat_map (fun l => match l with LT a => [a] | _ => [] end) w.

Lemma labo_perm : forall {EA EB : Type} (tau : EA -> EB) (x : list (SwLab EA EB)),
  Permutation (flat_map (labo tau) x) (map tau (tOf x) ++ bOf x).
Proof.
  intros EA EB tau x. induction x as [| [a | | a | b] x IH]; simpl; try exact IH.
  - apply Permutation_refl.
  - apply perm_skip. exact IH.
  - apply (Permutation_trans (perm_skip b IH)). apply Permutation_middle.
Qed.

Section LiveP.
  Context {SA EA SB EB : Type}.
  Variable stepA : EA -> SA -> SA.
  Variable stepB : EB -> SB -> SB.
  Variable eqvB : SB -> SB -> Prop.
  Hypothesis eqvB_refl : forall x, eqvB x x.
  Hypothesis eqvB_sym : forall x y, eqvB x y -> eqvB y x.
  Hypothesis eqvB_trans : forall x y z, eqvB x y -> eqvB y z -> eqvB x z.
  Hypothesis stepB_ext : forall e x y, eqvB x y -> eqvB (stepB e x) (stepB e y).
  Variable M : SA -> SB.
  Variable tau : EA -> EB.
  Variable s0 : SA.

  Local Notation runA := (runT stepA).
  Local Notation runB := (runT stepB).
  Local Notation Lab := (SwLab EA EB).

  (* One state machine for both phases; ill-typed labels act as the identity (never admissible). *)
  Definition lv_step (l : Lab) (x : SA + SB) : SA + SB :=
    match l, x with
    | LA a, inl s => inl (stepA a s)
    | LS, inl s => inr (M s)
    | LT a, inr y => inr (stepB (tau a) y)
    | LB b, inr y => inr (stepB b y)
    | _, x => x
    end.
  Definition lv_obs (x : SA + SB) : SB := match x with inl s => M s | inr y => y end.
  Local Notation sem := (msem lv_step lv_obs (inl s0)).

  (* Generators: the switch square, and a swap of two post-switch labels. *)
  Definition lv_gen (_ u v : list Lab) : Prop :=
    (exists a, u = [LA a; LS] /\ v = [LS; LT a]) \/
    (exists x y, isPost x /\ isPost y /\ u = [x; y] /\ v = [y; x]).

  Lemma lv_run_A : forall u s, runT lv_step (map LA u) (inl s) = inl (runA u s).
  Proof.
    induction u as [| a u IH]; intros s; [reflexivity |].
    change (map LA (a :: u)) with (@LA EA EB a :: map LA u). rewrite !runT_cons. apply IH.
  Qed.

  Lemma lv_run_post : forall x y, runT lv_step x (inr y) = inr (runB (flat_map (labo tau) x) y).
  Proof.
    induction x as [| [a | | a | b] x IH]; intros y; [reflexivity | | | |]; rewrite runT_cons;
      cbn [lv_step]; rewrite IH; reflexivity.
  Qed.

  Lemma lv_sem_complete : forall u x,
    sem (map LA u ++ LS :: x) = runB (flat_map (labo tau) x) (M (runA u s0)).
  Proof.
    intros u x. unfold msem. rewrite runT_app, lv_run_A, runT_cons. simpl. rewrite lv_run_post.
    reflexivity.
  Qed.

  Lemma lv_sem_A : forall u, sem (map LA u) = M (runA u s0).
  Proof. intros u. unfold msem. rewrite lv_run_A. reflexivity. Qed.

  Lemma lv_run_inr : forall t y, exists y', runT lv_step t (inr y) = inr y'.
  Proof. intros t y. rewrite lv_run_post. eexists. reflexivity. Qed.

  Lemma lv_run_LS : forall t x, In LS t -> exists y, runT lv_step t x = inr y.
  Proof.
    induction t as [| l t IH]; intros x H; [destruct H |]. rewrite runT_cons.
    destruct H as [-> | H]; [| apply IH; exact H].
    destruct x as [s | y]; simpl; apply lv_run_inr.
  Qed.

  (* Past the switch the semantics respects the future. *)
  Lemma lv_resp : RespOn phA sem eqvB (fun t : list Lab => In LS t).
  Proof.
    intros t t' e Q1 Q2 _ _ H. unfold msem in *. rewrite !runT_app.
    destruct (lv_run_LS t (inl s0) Q1) as [y Hy]. destruct (lv_run_LS t' (inl s0) Q2) as [y' Hy'].
    rewrite Hy, Hy' in *. simpl in H. destruct e; simpl; auto.
  Qed.

  Lemma lv_qseeds : QSeeds phA lv_gen (fun t : list Lab => In LS t).
  Proof.
    intros p u v [(a & -> & ->) | (x & y & Hx & Hy & -> & ->)] Hu Hv; split.
    - apply in_or_app. right. right. left. reflexivity.
    - apply in_or_app. right. left. reflexivity.
    - apply (phA_post_LS _ x Hu); [apply in_or_app; right; left; reflexivity | exact Hx].
    - apply (phA_post_LS _ y Hv); [apply in_or_app; right; left; reflexivity | exact Hy].
  Qed.

  Lemma lv_qext : QExt phA (fun t : list Lab => In LS t).
  Proof. intros t e H _. apply in_or_app. left. exact H. Qed.

  (* P1: invariance iff the seeds. *)
  Lemma lv_local : PInv phA lv_gen sem eqvB <-> PSeedOK phA lv_gen sem eqvB.
  Proof.
    exact (local_exact phA lv_gen sem eqvB eqvB_refl eqvB_sym eqvB_trans (fun t : list Lab => In LS t)
             phA_prefix lv_qseeds lv_qext lv_resp).
  Qed.

  (* ----- the seeds are DS1 and the post-switch swaps ----- *)

  Definition SwapAll : Prop := forall u v a b,
    eqvB (stepB b (stepB a (runB v (M (runA u s0))))) (stepB a (stepB b (runB v (M (runA u s0))))).

  Lemma labo_LB : forall v, flat_map (labo tau) (map (@LB EA EB) v) = v.
  Proof. induction v as [| b v IH]; [reflexivity |]. simpl. rewrite IH. reflexivity. Qed.

  Lemma labo_LT_LB : forall r v, flat_map (labo tau) (map (@LT EA EB) r ++ map LB v) = map tau r ++ v.
  Proof.
    intros r v. rewrite flat_map_app, labo_LB. f_equal.
    induction r as [| a r IH]; [reflexivity |]. simpl. rewrite IH. reflexivity.
  Qed.

  Lemma lv_sem_post : forall u x l1 l2,
    sem ((map LA u ++ LS :: x) ++ [l1; l2]) =
    runB (flat_map (labo tau) [l1; l2]) (runB (flat_map (labo tau) x) (M (runA u s0))).
  Proof.
    intros u x l1 l2. rewrite <- app_assoc. change ((LS :: x) ++ [l1; l2]) with (LS :: (x ++ [l1; l2])).
    rewrite lv_sem_complete, flat_map_app, runT_app. reflexivity.
  Qed.

  Lemma forall_LB : forall v, Forall isPost (map (@LB EA EB) v).
  Proof.
    intros v. apply Forall_forall. intros l Hl. apply in_map_iff in Hl. destruct Hl as [b [<- _]]. exact I.
  Qed.

  Lemma lv_seeds_iff : PSeedOK phA lv_gen sem eqvB <-> Reconfiguration.DS1 stepA stepB eqvB M tau s0 /\ SwapAll.
  Proof.
    split.
    - intros H. split.
      + intros u e.
        assert (A1 : phA (map (@LA EA EB) u ++ [LA e; LS])) by (apply phA_mapA; simpl; apply Forall_nil).
        assert (A2 : phA (map (@LA EA EB) u ++ [LS; LT e])) by (apply phA_mapA; simpl; repeat constructor).
        pose proof (H (map LA u) [LA e; LS] [LS; LT e] (or_introl (ex_intro _ e (conj eq_refl eq_refl)))
                      A1 A2) as K.
        unfold msem in K. rewrite !runT_app, !lv_run_A in K. exact K.
      + intros u v a b.
        assert (A1 : phA ((map (@LA EA EB) u ++ LS :: map LB v) ++ [LB a; LB b])).
        { rewrite <- app_assoc. apply phA_mapA. simpl. apply Forall_app.
          split; [apply forall_LB | repeat constructor]. }
        assert (A2 : phA ((map (@LA EA EB) u ++ LS :: map LB v) ++ [LB b; LB a])).
        { rewrite <- app_assoc. apply phA_mapA. simpl. apply Forall_app.
          split; [apply forall_LB | repeat constructor]. }
        pose proof (H (map LA u ++ LS :: map LB v) [LB a; LB b] [LB b; LB a]
                      (or_intror (ex_intro _ (LB a) (ex_intro _ (LB b) (conj I (conj I (conj eq_refl eq_refl))))))
                      A1 A2) as K.
        rewrite !lv_sem_post, labo_LB in K. exact K.
    - intros [HD HS] p u v [(a & -> & ->) | (x & y & Hx & Hy & -> & ->)] Hu Hv.
      + destruct (phA_A_point p [LS] a Hu) as [u0 ->].
        unfold msem. rewrite !runT_app, !lv_run_A. exact (HD u0 a).
      + destruct (phA_post_point p [y] x Hx Hu) as (u0 & x0 & -> & _).
        rewrite !lv_sem_post.
        destruct x as [| | a1 | b1]; destruct y as [| | a2 | b2]; simpl in Hx, Hy; try contradiction;
          exact (HS u0 (flat_map (labo tau) x0) _ _).
  Qed.

  (* ----- DS1 and the swaps everywhere after a switch, versus PermB at the migrated start ----- *)

  Lemma lv_runB_ext : forall v x y, eqvB x y -> eqvB (runB v x) (runB v y).
  Proof.
    induction v as [| e v IH]; intros x y H; [exact H |]. rewrite !runT_cons. apply IH. apply stepB_ext. exact H.
  Qed.

  Lemma lv_M_run : Reconfiguration.DS1 stepA stepB eqvB M tau s0 ->
    forall u, eqvB (M (runA u s0)) (runB (map tau u) (M s0)).
  Proof.
    intros H u. induction u as [| e u IH] using rev_ind; [apply eqvB_refl |].
    rewrite runT_app, map_app, runT_app. simpl.
    apply (eqvB_trans _ _ _ (H u e)). apply stepB_ext. exact IH.
  Qed.

  (* PermB is local: P1 for free delivery, stepB respecting eqvB. *)
  Lemma lv_permB_local : forall x, Reconfiguration.PermB stepB eqvB x <->
    forall v a b, eqvB (stepB b (stepB a (runB v x))) (stepB a (stepB b (runB v x))).
  Proof.
    intros x. unfold Reconfiguration.PermB.
    assert (S1 : (forall v v', Permutation v v' -> eqvB (runB v x) (runB v' x)) <->
                 PInv (@fs_adm EB) fs_gen (msem stepB (fun y => y) x) eqvB).
    { split.
      - intros H t t' Hq. apply H. apply swap_peq_perm. exact Hq.
      - intros H v v' P. apply H. apply swap_peq_perm. exact P. }
    rewrite S1, (local_exact_all fs_adm fs_gen (msem stepB (fun y => y) x) eqvB eqvB_refl eqvB_sym eqvB_trans
                   fs_prefix).
    - split.
      + intros H v a b. pose proof (H v [a; b] [b; a] (ex_intro _ a (ex_intro _ b (conj eq_refl eq_refl))) I I) as K.
        unfold msem in K. rewrite !runT_app in K. exact K.
      + intros H p u v (a & b & -> & ->) _ _. unfold msem. rewrite !runT_app. apply H.
    - intros t t' e _ _ H. rewrite !msem_snoc. apply stepB_ext. exact H.
  Qed.

  Lemma lv_seeds_live : Reconfiguration.DS1 stepA stepB eqvB M tau s0 /\ SwapAll <->
    Reconfiguration.PermB stepB eqvB (M s0) /\ Reconfiguration.DS1 stepA stepB eqvB M tau s0.
  Proof.
    split.
    - intros [HD HS]. split; [| exact HD]. apply lv_permB_local. intros v a b. exact (HS [] v a b).
    - intros [HP HD]. split; [exact HD |]. intros u v a b.
      assert (HYZ : eqvB (runB v (M (runA u s0))) (runB (map tau u ++ v) (M s0))).
      { rewrite runT_app. apply lv_runB_ext. apply lv_M_run. exact HD. }
      pose proof (proj1 (lv_permB_local (M s0)) HP (map tau u ++ v) a b) as HL.
      apply (eqvB_trans _ _ _ (stepB_ext b _ _ (stepB_ext a _ _ HYZ))).
      apply (eqvB_trans _ _ _ HL). apply eqvB_sym. apply stepB_ext. apply stepB_ext. exact HYZ.
  Qed.

  (* ----- live runs and paths: DLive is invariance under the presentation ----- *)

  Lemma phA_complete : forall u (x : list Lab), phA (map LA u ++ LS :: x) <-> Forall isPost x.
  Proof. intros u x. rewrite phA_mapA. reflexivity. Qed.

  (* Post-switch labels can be permuted. *)
  Lemma lv_post_perm : forall l l' : list Lab, Permutation l l' -> forall u x0,
    Forall isPost (x0 ++ l) -> PEq phA lv_gen (map LA u ++ LS :: x0 ++ l) (map LA u ++ LS :: x0 ++ l').
  Proof.
    intros l l' Q. induction Q as [| x l l' Q IH | x y l | l l' l'' Q1 IH1 Q2 IH2]; intros u x0 H.
    - apply ac_refl. apply phA_complete. exact H.
    - replace (x0 ++ x :: l) with ((x0 ++ [x]) ++ l) by (rewrite <- app_assoc; reflexivity).
      replace (x0 ++ x :: l') with ((x0 ++ [x]) ++ l') by (rewrite <- app_assoc; reflexivity).
      apply IH. rewrite <- app_assoc. exact H.
    - assert (H' : Forall isPost (x0 ++ x :: y :: l))
        by exact (Permutation_Forall (Permutation_app_head x0 (perm_swap x y l)) H).
      pose proof H as Hc. apply Forall_app in Hc. destruct Hc as [_ Hc].
      inversion Hc as [| ? ? Hy Hc' E1]; subst. inversion Hc' as [| ? ? Hx _ E2]; subst.
      apply ac_gen; [apply phA_complete; exact H | apply phA_complete; exact H' |].
      exists (map LA u ++ LS :: x0), [y; x], [x; y], l.
      split; [right; exists y, x; tauto |]. rewrite <- !app_assoc. split; reflexivity.
    - eapply ac_trans; [apply IH1; exact H |]. apply IH2.
      exact (Permutation_Forall (Permutation_app_head x0 Q1) H).
  Qed.

  (* In-flight A-events cross the switch, one switch square at a time. *)
  Lemma lv_switch_front : forall u (x : list Lab), Forall isPost x ->
    PEq phA lv_gen (map LA u ++ LS :: x) (LS :: map LT u ++ x).
  Proof.
    intros u. induction u as [| a u IH] using rev_ind; intros x Hx.
    - apply ac_refl. exact Hx.
    - rewrite !map_app, <- !app_assoc. simpl.
      apply ac_trans with (map LA u ++ LS :: LT a :: x).
      + apply ac_gen; [apply phA_mapA; simpl; exact Hx | apply phA_complete; constructor; [exact I | exact Hx] |].
        exists (map LA u), [LA a; LS], [LS; LT a], x. split; [left; exists a; split; reflexivity |].
        split; reflexivity.
      + apply IH. constructor; [exact I | exact Hx].
  Qed.

  Lemma lv_aOf_complete : forall u (x : list Lab), Forall isPost x ->
    aOf (map LA u ++ LS :: x) = u ++ tOf x.
  Proof.
    intros u x Hx. unfold aOf, tOf. rewrite flat_map_app. f_equal.
    - induction u as [| a u IH]; [reflexivity |]. simpl. rewrite IH. reflexivity.
    - simpl. induction Hx as [| [a | | a | b] x Hl _ IH]; simpl in *; try contradiction; try rewrite IH; reflexivity.
  Qed.

  Lemma lv_bOf_complete : forall u (x : list Lab), bOf (map LA u ++ LS :: x) = bOf x.
  Proof.
    intros u x. unfold bOf. rewrite flat_map_app. simpl.
    induction u as [| a u IH]; [reflexivity |]. simpl. exact IH.
  Qed.

  Lemma lv_whisk_perm : forall t t', Whisk lv_gen t t' ->
    Permutation (aOf t) (aOf t') /\ Permutation (bOf t) (bOf t').
  Proof.
    intros t t' (p & u & v & w & Hg & -> & ->). unfold aOf, bOf. rewrite !flat_map_app.
    assert (FP : forall (B : Type) (f : Lab -> list B) x y, Permutation (flat_map f [x; y]) (flat_map f [y; x]))
      by (intros B f x y; simpl; rewrite !app_nil_r; apply Permutation_app_comm).
    destruct Hg as [(a & -> & ->) | (x & y & _ & _ & -> & ->)]; split.
    - apply Permutation_refl.
    - apply Permutation_refl.
    - apply Permutation_app_head, Permutation_app_tail, FP.
    - apply Permutation_app_head, Permutation_app_tail, FP.
  Qed.

  Lemma lv_peq_perm : forall t t', PEq phA lv_gen t t' ->
    Permutation (aOf t) (aOf t') /\ Permutation (bOf t) (bOf t').
  Proof.
    intros t t' H. induction H as [t _ | t t' _ _ Hw | t t' _ [IH1 IH2] | t t' t'' _ [A1 B1] _ [A2 B2]].
    - split; apply Permutation_refl.
    - exact (lv_whisk_perm t t' Hw).
    - split; apply Permutation_sym; assumption.
    - split; eapply Permutation_trans; eassumption.
  Qed.

  Lemma lv_whisk_LS : forall t t', phA t -> phA t' -> Whisk lv_gen t t' -> In LS t /\ In LS t'.
  Proof.
    intros t t' Ht Ht' (p & u & v & w & Hg & -> & ->).
    assert (Hu : phA (p ++ u)) by (apply (phA_prefix _ w); rewrite <- app_assoc; exact Ht).
    assert (Hv : phA (p ++ v)) by (apply (phA_prefix _ w); rewrite <- app_assoc; exact Ht').
    destruct (lv_qseeds p u v Hg Hu Hv) as [Q1 Q2].
    split; rewrite app_assoc; apply in_or_app; left; assumption.
  Qed.

  Lemma not_LS_A : forall u, ~ In LS (map (@LA EA EB) u).
  Proof. intros u H. apply in_map_iff in H. destruct H as [a [E _]]. discriminate E. Qed.

  Lemma lv_peq_LS : forall t t', PEq phA lv_gen t t' ->
    (In LS t <-> In LS t') /\ (~ In LS t -> t = t').
  Proof.
    intros t t' H. induction H as [t _ | t t' Ht Ht' Hw | t t' _ [IH1 IH2] | t t' t'' _ [A1 B1] _ [A2 B2]].
    - split; [reflexivity | reflexivity].
    - destruct (lv_whisk_LS t t' Ht Ht' Hw) as [Q1 Q2]. split; [tauto | intros N; contradiction].
    - split; [symmetry; exact IH1 |]. intros N. symmetry. apply IH2. rewrite IH1. exact N.
    - split; [rewrite A1; exact A2 |]. intros N. rewrite (B1 N). apply B2. rewrite <- A1. exact N.
  Qed.

  Lemma lv_out_path : forall t, phA t -> In LS t ->
    Reconfiguration.OutLive stepA stepB M tau s0 (aOf t) (bOf t) (sem t).
  Proof.
    intros t Ht HL. destruct (phA_shape t Ht) as [[u ->] | (u & x & -> & Hx)];
      [exfalso; exact (not_LS_A u HL) |].
    exists u, (tOf x), (flat_map (labo tau) x).
    rewrite (lv_aOf_complete u x Hx), lv_bOf_complete, lv_sem_complete.
    split; [apply Permutation_refl | split; [apply labo_perm | reflexivity]].
  Qed.

  Lemma lv_out_perm : forall Ea Ea' Eb Eb' y, Reconfiguration.OutLive stepA stepB M tau s0 Ea Eb y ->
    Permutation Ea Ea' -> Permutation Eb Eb' -> Reconfiguration.OutLive stepA stepB M tau s0 Ea' Eb' y.
  Proof.
    intros Ea Ea' Eb Eb' y (u & r & v & P1 & P2 & ->) Qa Qb. exists u, r, v.
    split; [exact (Permutation_trans P1 Qa) |].
    split; [exact (Permutation_trans P2 (Permutation_app_head _ Qb)) | reflexivity].
  Qed.

  (* Every live outcome is equivalent, under invariance, to the canonical path's semantics. *)
  Lemma lv_out_canon : PInv phA lv_gen sem eqvB -> forall Ea Eb y,
    Reconfiguration.OutLive stepA stepB M tau s0 Ea Eb y ->
    eqvB y (sem (LS :: map LT Ea ++ map LB Eb)).
  Proof.
    intros HI Ea Eb y (u & r & v & P1 & P2 & ->).
    assert (E1 : sem (map LA u ++ LS :: map LB v) = runB v (M (runA u s0)))
      by (rewrite lv_sem_complete, labo_LB; reflexivity).
    assert (E2 : sem (map LA u ++ LS :: map LB (map tau r ++ Eb)) =
                 sem (map LA u ++ LS :: (map LT r ++ map LB Eb)))
      by (rewrite !lv_sem_complete, labo_LB, labo_LT_LB; reflexivity).
    assert (C1 : PEq phA lv_gen (map LA u ++ LS :: map LB v) (map LA u ++ LS :: map LB (map tau r ++ Eb))).
    { exact (lv_post_perm _ _ (Permutation_map LB P2) u [] (forall_LB v)). }
    assert (Hx : Forall isPost (map (@LT EA EB) r ++ map LB Eb)).
    { apply Forall_app. split; [| apply forall_LB].
      apply Forall_forall. intros l Hl. apply in_map_iff in Hl. destruct Hl as [a [<- _]]. exact I. }
    assert (C2 : PEq phA lv_gen (map LA u ++ LS :: (map LT r ++ map LB Eb))
                   (LS :: map LT (u ++ r) ++ map LB Eb)).
    { rewrite map_app, <- app_assoc. exact (lv_switch_front u _ Hx). }
    assert (C3 : PEq phA lv_gen (LS :: map LT (u ++ r) ++ map LB Eb) (LS :: map LT Ea ++ map LB Eb)).
    { apply (lv_post_perm _ _ (Permutation_app_tail (map LB Eb) (Permutation_map LT P1)) [] []).
      simpl. apply Forall_app. split; [| apply forall_LB].
      apply Forall_forall. intros l Hl. apply in_map_iff in Hl. destruct Hl as [a [<- _]]. exact I. }
    rewrite <- E1. apply (eqvB_trans _ _ _ (HI _ _ C1)). rewrite E2.
    exact (HI _ _ (ac_trans _ _ _ _ _ C2 C3)).
  Qed.

  Lemma lv_dlive_inv : Reconfiguration.DLive stepA stepB eqvB M tau s0 <-> PInv phA lv_gen sem eqvB.
  Proof.
    split.
    - intros HD t t' Hq. destruct (ac_adm' phA (Whisk lv_gen) t t' Hq) as [Ht Ht'].
      destruct (lv_peq_LS t t' Hq) as [Hiff Heq].
      destruct (phA_shape t Ht) as [[u Eu] | (u & x & Eu & Hx)].
      + rewrite <- (Heq ltac:(rewrite Eu; apply not_LS_A)). apply eqvB_refl.
      + assert (HL : In LS t) by (rewrite Eu; apply in_or_app; right; left; reflexivity).
        destruct (lv_peq_perm t t' Hq) as [Pa Pb].
        apply (HD (aOf t) (bOf t)); [exact (lv_out_path t Ht HL) |].
        apply (lv_out_perm (aOf t') _ (bOf t')); [exact (lv_out_path t' Ht' (proj1 Hiff HL)) | |];
          apply Permutation_sym; assumption.
    - intros HI Ea Eb y1 y2 O1 O2. apply (eqvB_trans _ _ _ (lv_out_canon HI Ea Eb y1 O1)).
      apply eqvB_sym. exact (lv_out_canon HI Ea Eb y2 O2).
  Qed.

