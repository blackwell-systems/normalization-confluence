Section CausalP.
  Context {S E : Type}.
  Variable step : E -> S -> S.
  Variable hb : E -> E -> Prop.
  Variable s0 : S.

  Local Notation causal := (CausalReplay.causal hb).
  Local Notation sem := (msem step (fun x => x) s0).

  (* The generator: an adjacent concurrent pair at a point after which it is causally deliverable. *)
  Definition cg_gen (p u v : list E) : Prop :=
    exists a b, CausalReplay.concurrent hb a b /\ causal (p ++ [a; b]) /\ u = [a; b] /\ v = [b; a].

  Lemma cg_prefix : AdmPrefix causal.
  Proof. intros t w H. exact (GovernanceConverse.causal_prefix hb t w H). Qed.

  Lemma cg_whisk_cswap : forall t t', Whisk cg_gen t t' <-> CanonicalInstances.cswap hb t t'.
  Proof.
    intros t t'. split.
    - intros (p & u & v & w & (a & b & Hab & Hc & -> & ->) & -> & ->).
      exists p, a, b, w. tauto.
    - intros (p & a & b & r & Hab & Hc & -> & ->). exists p, [a; b], [b; a], r.
      split; [exists a, b; tauto | split; reflexivity].
  Qed.

  Lemma cg_peq : forall t t', PEq causal cg_gen t t' <-> AC causal (CanonicalInstances.cswap hb) t t'.
  Proof.
    intros t t'. split; apply ac_impl; intros x y _ _ H; apply cg_whisk_cswap; exact H.
  Qed.

  Theorem causal_exact_recovered :
    GovernanceConverse.CausalConv step hb s0 <-> GovernanceConverse.CCR step hb s0.
  Proof.
    assert (S1 : GovernanceConverse.CausalConv step hb s0 <-> PInv causal cg_gen sem eq).
    { split.
      - intros H t t' Hq. apply cg_peq in Hq.
        destruct (ac_adm' causal (CanonicalInstances.cswap hb) t t' Hq)
          as [Ht Ht'].
        exact (H t t' Ht Ht' (proj2 (CanonicalInstances.causal_adequate hb t t' Ht Ht') Hq)).
      - intros H o1 o2 H1 H2 P. apply (H o1 o2). apply cg_peq.
        exact (proj1 (CanonicalInstances.causal_adequate hb o1 o2 H1 H2) P). }
    assert (S2 : PInv causal cg_gen sem eq <-> PSeedOK causal cg_gen sem eq).
    { apply local_exact_all; [exact (@eq_refl _) | exact (@eq_sym _) | exact (@eq_trans _)
                              | exact cg_prefix |].
      intros t t' e _ _. apply msem_eq_resp. }
    rewrite S1, S2. split.
    - intros H p a b Hab Hc.
      assert (Hc' : causal (p ++ [b; a]))
        by exact (GovernanceConverse.causal_swap hb p a b [] (proj1 (proj2 Hab)) Hc).
      pose proof (H p [a; b] [b; a] (ex_intro _ a (ex_intro _ b (conj Hab (conj Hc (conj eq_refl eq_refl)))))
                    Hc Hc') as K.
      unfold msem in K. rewrite !runT_app in K. exact K.
    - intros H p u v (a & b & Hab & Hc & -> & ->) _ _. unfold msem. rewrite !runT_app.
      exact (H p a b Hab Hc).
  Qed.
End CausalP.

