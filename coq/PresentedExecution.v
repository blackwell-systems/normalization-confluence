(* Every vertex of AC is admissible (stated with explicit arguments). *)
Lemma ac_adm' : forall {T : Type} (Adm : T -> Prop) (G : T -> T -> Prop) t u,
  AC Adm G t u -> Adm t /\ Adm u.
Proof.
  intros T Adm G t u H. induction H as [t Ht | t u Ht Hu _ | t u _ [A1 A2] | t u v _ [A1 _] _ [_ A3]];
    split; assumption.
Qed.

(* ============================================================================================ *)
(* 1. Generic: whiskered generators, the continuation closure, P1 and P2                        *)
(* ============================================================================================ *)

Section Presented.
  Context {L Y : Type}.
  Variable Adm : list L -> Prop.                       (* admissible executions *)
  Variable Gen : list L -> list L -> list L -> Prop.   (* Gen p u v: u, v interchangeable at p *)
  Variable sem : list L -> Y.
  Variable eqv : Y -> Y -> Prop.
  Hypothesis eqv_refl : forall y, eqv y y.
  Hypothesis eqv_sym : forall y z, eqv y z -> eqv z y.
  Hypothesis eqv_trans : forall x y z, eqv x y -> eqv y z -> eqv x z.

  (* Whiskered generators: the point p before, any continuation w after. *)
  Definition Whisk (t t' : list L) : Prop :=
    exists p u v w, Gen p u v /\ t = p ++ u ++ w /\ t' = p ++ v ++ w.

  (* The generated equivalence: every vertex admissible. *)
  Definition PEq : list L -> list L -> Prop := AC Adm Whisk.

  Definition PInv : Prop := forall t t', PEq t t' -> eqv (sem t) (sem t').

  Definition AdmPrefix : Prop := forall t w, Adm (t ++ w) -> Adm t.

  (* The continuation closure of the generators. *)
  Inductive PPC : list L -> list L -> Prop :=
  | ppc_seed : forall p u v, Gen p u v -> Adm (p ++ u) -> Adm (p ++ v) -> PPC (p ++ u) (p ++ v)
  | ppc_cont : forall t t' e, PPC t t' -> Adm (t ++ [e]) -> Adm (t' ++ [e]) ->
      PPC (t ++ [e]) (t' ++ [e]).

  Definition PClosOK : Prop := forall t t', PPC t t' -> eqv (sem t) (sem t').

  Definition PSeedOK : Prop := forall p u v, Gen p u v -> Adm (p ++ u) -> Adm (p ++ v) ->
    eqv (sem (p ++ u)) (sem (p ++ v)).

  Lemma ppc_whisk : forall t t', PPC t t' -> Adm t /\ Adm t' /\ Whisk t t'.
  Proof.
    intros t t' H. induction H as [p u v Hg Hu Hv | t t' e _ [_ [_ (p & u & v & w & Hg & -> & ->)]] H1 H2].
    - split; [exact Hu | split; [exact Hv |]]. exists p, u, v, []. rewrite !app_nil_r.
      split; [exact Hg | split; reflexivity].
    - split; [exact H1 | split; [exact H2 |]]. exists p, u, v, (w ++ [e]).
      split; [exact Hg |]. rewrite <- !app_assoc. split; reflexivity.
  Qed.

  Lemma whisk_ppc_w : AdmPrefix -> forall p u v, Gen p u v ->
    forall w, Adm (p ++ u ++ w) -> Adm (p ++ v ++ w) -> PPC (p ++ u ++ w) (p ++ v ++ w).
  Proof.
    intros HP p u v Hg w. induction w as [| e w IH] using rev_ind; intros Hu Hv.
    - rewrite !app_nil_r in *. apply ppc_seed; assumption.
    - replace (p ++ u ++ w ++ [e]) with ((p ++ u ++ w) ++ [e]) in Hu |- *
        by (rewrite <- !app_assoc; reflexivity).
      replace (p ++ v ++ w ++ [e]) with ((p ++ v ++ w) ++ [e]) in Hv |- *
        by (rewrite <- !app_assoc; reflexivity).
      apply ppc_cont; [| exact Hu | exact Hv].
      apply IH; [exact (HP _ [e] Hu) | exact (HP _ [e] Hv)].
  Qed.

  Theorem ppc_iff_whisk : AdmPrefix -> forall t t', PPC t t' <-> Adm t /\ Adm t' /\ Whisk t t'.
  Proof.
    intros HP t t'. split; [apply ppc_whisk |].
    intros [Ht [Ht' (p & u & v & w & Hg & -> & ->)]]. apply whisk_ppc_w; assumption.
  Qed.

  (* The closure is the least relation containing the seeds and closed under admissible
     one-event continuation. *)
  Theorem ppc_least : forall R : list L -> list L -> Prop,
    (forall p u v, Gen p u v -> Adm (p ++ u) -> Adm (p ++ v) -> R (p ++ u) (p ++ v)) ->
    (forall t t' e, R t t' -> Adm (t ++ [e]) -> Adm (t' ++ [e]) -> R (t ++ [e]) (t' ++ [e])) ->
    forall t t', PPC t t' -> R t t'.
  Proof.
    intros R Hs Hc t t' H. induction H as [p u v Hg Hu Hv | t t' e _ IH H1 H2].
    - apply Hs; assumption.
    - apply Hc; assumption.
  Qed.

  (* (P2) Invariance iff the semantics agrees on the continuation closure. *)
  Theorem closure_exact : AdmPrefix -> (PInv <-> PClosOK).
  Proof.
    intros HP. split.
    - intros H t t' Hc. apply H. destruct (ppc_whisk t t' Hc) as [Ht [Ht' Hw]].
      apply ac_gen; assumption.
    - intros H t t' He. induction He as [t _ | t t' Ht Ht' Hw | t t' _ IH | t t' t'' _ IH1 _ IH2].
      + apply eqv_refl.
      + apply H. apply (proj2 (ppc_iff_whisk HP t t')). tauto.
      + apply eqv_sym. exact IH.
      + exact (eqv_trans _ _ _ IH1 IH2).
  Qed.

  (* The seed condition is always necessary. *)
  Theorem seeds_necessary : PInv -> PSeedOK.
  Proof.
    intros H p u v Hg Hu Hv. apply H. apply ac_gen; [exact Hu | exact Hv |].
    exists p, u, v, []. rewrite !app_nil_r. split; [exact Hg | split; reflexivity].
  Qed.

  (* (P1) When the semantics respects the future on a predicate Q that covers the seeds and is
     preserved by admissible extension, the generators suffice locally. *)
  Variable Q : list L -> Prop.

  Definition RespOn : Prop := forall t t' e, Q t -> Q t' -> Adm (t ++ [e]) -> Adm (t' ++ [e]) ->
    eqv (sem t) (sem t') -> eqv (sem (t ++ [e])) (sem (t' ++ [e])).

  Definition QSeeds : Prop :=
    forall p u v, Gen p u v -> Adm (p ++ u) -> Adm (p ++ v) -> Q (p ++ u) /\ Q (p ++ v).

  Definition QExt : Prop := forall t e, Q t -> Adm (t ++ [e]) -> Q (t ++ [e]).

  Theorem local_closure : QSeeds -> QExt -> RespOn -> (PClosOK <-> PSeedOK).
  Proof.
    intros HQs HQe HR. split.
    - intros H p u v Hg Hu Hv. apply H. apply ppc_seed; assumption.
    - intros H t t' Hc.
      assert (K : Q t /\ Q t' /\ eqv (sem t) (sem t')).
      { induction Hc as [p u v Hg Hu Hv | t t' e _ [Q1 [Q2 IH]] H1 H2].
        - destruct (HQs p u v Hg Hu Hv) as [Q1 Q2]. split; [exact Q1 | split; [exact Q2 |]].
          apply H; assumption.
        - split; [apply HQe; assumption | split; [apply HQe; assumption |]].
          apply HR; assumption. }
      tauto.
  Qed.

  Theorem local_exact : AdmPrefix -> QSeeds -> QExt -> RespOn -> (PInv <-> PSeedOK).
  Proof.
    intros HP HQs HQe HR. rewrite (closure_exact HP). exact (local_closure HQs HQe HR).
  Qed.
End Presented.

(* P1 with Q everywhere. *)
Theorem local_exact_all : forall {L Y : Type} (Adm : list L -> Prop) Gen (sem : list L -> Y) eqv,
  (forall y, eqv y y) -> (forall y z, eqv y z -> eqv z y) ->
  (forall x y z, eqv x y -> eqv y z -> eqv x z) ->
  AdmPrefix Adm ->
  (forall t t' e, Adm (t ++ [e]) -> Adm (t' ++ [e]) -> eqv (sem t) (sem t') ->
     eqv (sem (t ++ [e])) (sem (t' ++ [e]))) ->
  (PInv Adm Gen sem eqv <-> PSeedOK Adm Gen sem eqv).
Proof.
  intros L Y Adm Gen sem eqv Hr Hs Ht HP HR.
  apply (local_exact Adm Gen sem eqv Hr Hs Ht (fun _ => True) HP).
  - intros p u v _ _ _. split; exact I.
  - intros t e _ _. exact I.
  - intros t t' e _ _. apply HR.
Qed.

(* Free delivery: admissibility trivial and generators independent of the point. The generated
   equivalence is then a monoid congruence. *)
Theorem free_congruence : forall {L : Type} (Adm : list L -> Prop) Gen,
  (forall t, Adm t) -> (forall p p' u v, Gen p u v -> Gen p' u v) ->
  forall t t', PEq Adm Gen t t' -> forall l r, PEq Adm Gen (l ++ t ++ r) (l ++ t' ++ r).
Proof.
  intros L Adm Gen HA HG t t' H. induction H as [t _ | t t' _ _ (p & u & v & w & Hg & -> & ->)
                                                 | t t' _ IH | t t' t'' _ IH1 _ IH2]; intros l r.
  - apply ac_refl. apply HA.
  - apply ac_gen; [apply HA | apply HA |]. exists (l ++ p), u, v, (w ++ r).
    split; [exact (HG p _ u v Hg) |]. rewrite <- !app_assoc. split; reflexivity.
  - apply ac_sym. apply IH.
  - eapply ac_trans; [apply IH1 | apply IH2].
Qed.

(* A state machine semantics: respect of the future follows from compatibility of obs with the
   steps, with no admissibility. *)
Section StateMachine.
  Context {L S O : Type}.
  Variable step : L -> S -> S.
  Variable obs : S -> O.
  Variable eqv : O -> O -> Prop.
  Variable s0 : S.

  Definition msem (t : list L) : O := obs (runT step t s0).

  Lemma msem_snoc : forall t e, msem (t ++ [e]) = obs (step e (runT step t s0)).
  Proof. intros t e. unfold msem. rewrite runT_app. reflexivity. Qed.

  Theorem resp_of_compat : forall (Adm : list L -> Prop) (Q : list L -> Prop),
    (forall e x y, eqv (obs x) (obs y) -> eqv (obs (step e x)) (obs (step e y))) ->
    RespOn Adm msem eqv Q.
  Proof.
    intros Adm Q Hc t t' e _ _ _ _ H. rewrite !msem_snoc. apply Hc. exact H.
  Qed.
End StateMachine.

(* ============================================================================================ *)
(* 2. Seeds alone do not suffice: a hidden write revealed later                                 *)
(* ============================================================================================ *)

(* State (hidden, visible). Some b writes the hidden register; None reveals it. The observation is
   the visible register; the generators swap two writes, at every point, with free delivery. *)
Definition hw_step (e : option bool) (s : bool * bool) : bool * bool :=
  match e with Some b => (b, snd s) | None => (fst s, fst s) end.
Definition hw_adm (_ : list (option bool)) : Prop := True.
Definition hw_gen (_ u v : list (option bool)) : Prop :=
  exists a b, u = [Some a; Some b] /\ v = [Some b; Some a].
Definition hw_sem : list (option bool) -> bool := msem hw_step snd (false, false).

(* Every swap seed is observationally equal, at every point. *)
Theorem hw_seeds_ok : PSeedOK hw_adm hw_gen hw_sem eq.
Proof.
  intros p u v (a & b & -> & ->) _ _. unfold hw_sem, msem. rewrite !runT_app. reflexivity.
Qed.

(* The seed continued by the reveal event separates. *)
Theorem hw_closure_witness :
  PPC hw_adm hw_gen [Some true; Some false; None] [Some false; Some true; None] /\
  hw_sem [Some true; Some false; None] <> hw_sem [Some false; Some true; None].
Proof.
  split; [| discriminate].
  apply (ppc_cont hw_adm hw_gen [Some true; Some false] [Some false; Some true] None);
    [| exact I | exact I].
  apply (ppc_seed hw_adm hw_gen [] [Some true; Some false] [Some false; Some true]);
    [exists true, false; split; reflexivity | exact I | exact I].
Qed.

Theorem hw_not_inv : ~ PInv hw_adm hw_gen hw_sem eq.
Proof.
  intros H. destruct hw_closure_witness as [P N]. apply N. apply H.
  destruct (ppc_whisk hw_adm hw_gen _ _ P) as [A1 [A2 W]]. apply ac_gen; assumption.
Qed.

(* The hypothesis of P1 is what fails: the observation does not respect the future. *)
Theorem hw_not_resp : ~ RespOn hw_adm hw_sem eq (fun _ => True).
Proof.
  intros H. specialize (H [Some true; Some false] [Some false; Some true] None I I I I eq_refl).
  discriminate H.
Qed.

(* Seeds checked at every reachable point, invariance still fails: P2 needs the closure. *)
Theorem hw_seeds_insufficient : PSeedOK hw_adm hw_gen hw_sem eq /\ ~ PInv hw_adm hw_gen hw_sem eq.
Proof. exact (conj hw_seeds_ok hw_not_inv). Qed.

(* ============================================================================================ *)
(* 3. The state side: state descent enters through the semantics, not as a generator            *)
(* ============================================================================================ *)

(* State descent N (act e s) = N (act e (N s)) compares one word run from two different states
   (s and N s). It is not a pair of parallel paths from one point, so it has no place in Gen. Its
   role: it makes the normalized raw semantics equal to the governed semantics from N s0, as
   functions on words, so any path presentation gives the same invariance question for both. *)
Theorem state_side_transfer : forall {X Ev : Type} (N : X -> X) (act : Ev -> X -> X) (s0 : X),
  StateDescent N act ->
  forall (Adm : list Ev -> Prop) Gen (eqv : X -> X -> Prop),
    PInv Adm Gen (fun t => N (rawrun act t s0)) eqv <->
    PInv Adm Gen (fun t => grun N act t (N s0)) eqv.
Proof.
  intros X Ev N act s0 HS Adm Gen eqv.
  assert (K : forall t, N (rawrun act t s0) = grun N act t (N s0))
    by (intros t; apply normalization_descent; exact HS).
  split; intros H t t' E; [rewrite <- !K | rewrite !K]; apply H; exact E.
Qed.

(* ============================================================================================ *)
(* 4a. history_descent_exact, through the one-step path system                                  *)
(* ============================================================================================ *)

Section OneStep.
  Context {T Y : Type}.
  Variable Adm : T -> Prop.
  Variable G : T -> T -> Prop.
  Variable SemEq : T -> T -> Prop.
  Variable sem : T -> Y.
  Variable eqY : Y -> Y -> Prop.
  Hypothesis eqY_refl : forall y, eqY y y.
  Hypothesis eqY_sym : forall y z, eqY y z -> eqY z y.
  Hypothesis eqY_trans : forall x y z, eqY x y -> eqY y z -> eqY x z.

  (* Executions are one-letter words; the empty word is the start. *)
  Definition os_adm (w : list T) : Prop :=
    match w with [] => True | [t] => Adm t | _ => False end.
  Definition os_gen (p u v : list T) : Prop :=
    p = [] /\ exists t t', u = [t] /\ v = [t'] /\ G t t'.
  Definition os_sem (w : list T) : option Y :=
    match w with [t] => Some (sem t) | _ => None end.
  Definition os_eqv (a b : option Y) : Prop :=
    match a, b with Some x, Some y => eqY x y | None, None => True | _, _ => False end.

  Lemma os_eqv_refl : forall a, os_eqv a a.
  Proof. intros [a |]; simpl; [apply eqY_refl | exact I]. Qed.
  Lemma os_eqv_sym : forall a b, os_eqv a b -> os_eqv b a.
  Proof. intros [a |] [b |]; simpl; try tauto. apply eqY_sym. Qed.
  Lemma os_eqv_trans : forall a b c, os_eqv a b -> os_eqv b c -> os_eqv a c.
  Proof. intros [a |] [b |] [c |]; simpl; try tauto. apply eqY_trans. Qed.

  Lemma os_prefix : AdmPrefix os_adm.
  Proof.
    intros t w H. destruct t as [| x [| y t]]; simpl; [exact I | | ].
    - destruct w; [exact H | destruct w; simpl in H; contradiction].
    - simpl in H. exact H.
  Qed.

  Lemma os_snoc : forall t e, os_adm (t ++ [e]) -> t = [].
  Proof.
    intros [| x t] e H; [reflexivity |]. destruct t; simpl in H; contradiction.
  Qed.

  Lemma os_whisk : forall a b, Whisk os_gen a b -> os_adm a ->
    exists t t', a = [t] /\ b = [t'] /\ G t t'.
  Proof.
    intros a b (p & u & v & w & [-> (t & t' & -> & -> & Hg)] & -> & ->) Ha.
    destruct w; [| simpl in Ha; contradiction]. exists t, t'. split; [reflexivity | split; [reflexivity | exact Hg]].
  Qed.

  Lemma os_peq : forall a b, PEq os_adm os_gen a b ->
    (a = [] /\ b = []) \/ exists t t', a = [t] /\ b = [t'] /\ AC Adm G t t'.
  Proof.
    intros a b H. induction H as [a Ha | a b Ha Hb Hw | a b _ IH | a b c _ IH1 _ IH2].
    - destruct a as [| t [| y a]]; [left; split; reflexivity | | contradiction].
      right. exists t, t. split; [reflexivity | split; [reflexivity |]]. apply ac_refl. exact Ha.
    - destruct (os_whisk a b Hw Ha) as (t & t' & -> & -> & Hg). right. exists t, t'.
      split; [reflexivity | split; [reflexivity |]]. apply ac_gen; assumption.
    - destruct IH as [[-> ->] | (t & t' & -> & -> & H)]; [left; split; reflexivity |].
      right. exists t', t. split; [reflexivity | split; [reflexivity |]]. apply ac_sym. exact H.
    - destruct IH1 as [[-> ->] | (t & t' & -> & -> & H1)];
        destruct IH2 as [[E ->] | (t2 & t3 & E & -> & H2)]; try discriminate.
      + left. split; reflexivity.
      + injection E as <-. right. exists t, t3. split; [reflexivity | split; [reflexivity |]].
        eapply ac_trans; eassumption.
  Qed.

  Lemma ac_os : forall t t', AC Adm G t t' -> PEq os_adm os_gen [t] [t'].
  Proof.
    intros t t' H. induction H as [t Ht | t t' Ht Ht' Hg | t t' _ IH | t t' t'' _ IH1 _ IH2].
    - apply ac_refl. exact Ht.
    - apply ac_gen; [exact Ht | exact Ht' |]. exists [], [t], [t'], [].
      split; [split; [reflexivity | exists t, t'; tauto] | split; reflexivity].
    - apply ac_sym. exact IH.
    - eapply ac_trans; eassumption.
  Qed.

  (* CanonicalExecution.history_descent_exact, recovered from P1. *)
  Theorem history_descent_recovered : Adequate Adm G SemEq ->
    (HistoryDescent Adm SemEq sem eqY <-> GenDescent Adm G sem eqY).
  Proof.
    intros HA.
    assert (S1 : HistoryDescent Adm SemEq sem eqY <-> PInv os_adm os_gen os_sem os_eqv).
    { split.
      - intros H a b E. destruct (os_peq a b E) as [[-> ->] | (t & t' & -> & -> & Hac)];
          [exact I |].
        destruct (ac_adm' Adm G t t' Hac) as [Ht Ht']. simpl.
        apply H; [exact Ht | exact Ht' |]. apply (proj2 (HA t t' Ht Ht')). exact Hac.
      - intros H t u Ht Hu Hs. apply (H [t] [u]). apply ac_os. exact (proj1 (HA t u Ht Hu) Hs). }
    assert (S2 : PInv os_adm os_gen os_sem os_eqv <-> PSeedOK os_adm os_gen os_sem os_eqv).
    { apply local_exact_all; [exact os_eqv_refl | exact os_eqv_sym | exact os_eqv_trans
                              | exact os_prefix |].
      intros t t' e H1 H2 _. rewrite (os_snoc t e H1), (os_snoc t' e H2). apply os_eqv_refl. }
    rewrite S1, S2. split.
    - intros H t t' Ht Ht' Hg.
      exact (H [] [t] [t'] (conj eq_refl (ex_intro _ t (ex_intro _ t' (conj eq_refl (conj eq_refl Hg)))))
               Ht Ht').
    - intros H p u v [-> (t & t' & -> & -> & Hg)] Ht Ht'. exact (H t t' Ht Ht' Hg).
  Qed.
End OneStep.

(* AC is monotone in the generators. *)
Lemma ac_impl : forall {T : Type} (Adm : T -> Prop) (G1 G2 : T -> T -> Prop),
  (forall t u, Adm t -> Adm u -> G1 t u -> G2 t u) -> forall t u, AC Adm G1 t u -> AC Adm G2 t u.
Proof.
  intros T Adm G1 G2 HG t u H. induction H as [t Ht | t u Ht Hu Hg | t u _ IH | t u v _ IH1 _ IH2].
  - apply ac_refl. exact Ht.
  - apply ac_gen; [exact Ht | exact Hu | apply HG; assumption].
  - apply ac_sym. exact IH.
  - eapply ac_trans; eassumption.
Qed.

(* Equality of a state machine run respects the future. *)
Lemma msem_eq_resp : forall {L S : Type} (step : L -> S -> S) (s0 : S) (t t' : list L) e,
  msem step (fun x => x) s0 t = msem step (fun x => x) s0 t' ->
  msem step (fun x => x) s0 (t ++ [e]) = msem step (fun x => x) s0 (t' ++ [e]).
Proof. intros L S step s0 t t' e H. rewrite !msem_snoc. unfold msem in H. rewrite H. reflexivity. Qed.

(* ============================================================================================ *)
(* 4b. Free delivery with adjacent swaps: ReconfigurationClosure's pair closure, through P2      *)
(* ============================================================================================ *)

Definition fs_adm {E : Type} (_ : list E) : Prop := True.
Definition fs_gen {E : Type} (_ u v : list E) : Prop := exists a b, u = [a; b] /\ v = [b; a].

Lemma fs_prefix : forall {E : Type}, AdmPrefix (@fs_adm E).
Proof. intros E t w _. exact I. Qed.

(* With free delivery and adjacent swaps the generated equivalence is Permutation. *)
Theorem swap_peq_perm : forall {E : Type} (t t' : list E),
  PEq fs_adm fs_gen t t' <-> Permutation t t'.
Proof.
  intros E t t'. split.
  - intros H. induction H as [t _ | t t' _ _ (p & u & v & w & (a & b & -> & ->) & -> & ->)
                             | t t' _ IH | t t' t'' _ IH1 _ IH2].
    + apply Permutation_refl.
    + apply Permutation_app_head. simpl. apply perm_swap.
    + apply Permutation_sym. exact IH.
    + eapply Permutation_trans; eassumption.
  - intros P.
    assert (K : forall l l' : list E, Permutation l l' -> forall p, PEq fs_adm fs_gen (p ++ l) (p ++ l')).
    { intros l l' Q. induction Q as [| x l l' Q IH | x y l | l l' l'' Q1 IH1 Q2 IH2]; intros p.
      - apply ac_refl. exact I.
      - replace (p ++ x :: l) with ((p ++ [x]) ++ l) by (rewrite <- app_assoc; reflexivity).
        replace (p ++ x :: l') with ((p ++ [x]) ++ l') by (rewrite <- app_assoc; reflexivity).
        apply IH.
      - apply ac_gen; [exact I | exact I |]. exists p, [y; x], [x; y], l.
        split; [exists y, x; split; reflexivity | split; reflexivity].
      - eapply ac_trans; [apply IH1 | apply IH2]. }
    exact (K t t' P (@nil E)).
Qed.

Section FreeSwap.
  Context {S E O : Type}.
  Variable step : E -> S -> S.
  Variable obs : S -> O.
  Variable eqv : O -> O -> Prop.
  Hypothesis eqv_refl : forall x, eqv x x.
  Hypothesis eqv_sym : forall x y, eqv x y -> eqv y x.
  Hypothesis eqv_trans : forall x y z, eqv x y -> eqv y z -> eqv x z.
  Variable s0 : S.

  Local Notation run := (runT step).
  Local Notation PC := (ReconfigurationClosure.PC step s0).

  Lemma fs_ppc_pc : forall t t', PPC (@fs_adm E) fs_gen t t' -> PC (run t s0) (run t' s0).
  Proof.
    intros t t' H. induction H as [p u v (a & b & -> & ->) _ _ | t t' e _ IH _ _].
    - rewrite !runT_app. exact (ReconfigurationClosure.pc_seed step s0 p a b).
    - rewrite !runT_app. exact (ReconfigurationClosure.pc_step step s0 e _ _ IH).
  Qed.

  Lemma fs_pc_ppc : forall x y, PC x y ->
    exists t t', PPC (@fs_adm E) fs_gen t t' /\ x = run t s0 /\ y = run t' s0.
  Proof.
    intros x y H. induction H as [u a b | e x y _ (t & t' & P & -> & ->)].
    - exists (u ++ [a; b]), (u ++ [b; a]). split; [| rewrite !runT_app; split; reflexivity].
      apply ppc_seed; [exists a, b; split; reflexivity | exact I | exact I].
    - exists (t ++ [e]), (t' ++ [e]). split; [| rewrite !runT_app; split; reflexivity].
      apply ppc_cont; [exact P | exact I | exact I].
  Qed.

  Theorem fs_closure_iff :
    PClosOK (@fs_adm E) fs_gen (msem step obs s0) eqv <->
    ReconfigurationClosure.ClosureOK step obs eqv s0.
  Proof.
    split.
    - intros H x y P. destruct (fs_pc_ppc x y P) as (t & t' & Q & -> & ->). exact (H t t' Q).
    - intros H t t' Q. exact (H _ _ (fs_ppc_pc t t' Q)).
  Qed.

  (* Permutation invariance of obs o run is P2's invariance for the adjacent-swap presentation. *)
  Lemma fs_perm_inv : (forall u u', Permutation u u' -> eqv (obs (run u s0)) (obs (run u' s0))) <->
    PInv (@fs_adm E) fs_gen (msem step obs s0) eqv.
  Proof.
    split.
    - intros H t t' Q. apply H. apply swap_peq_perm. exact Q.
    - intros H u u' P. apply H. apply swap_peq_perm. exact P.
  Qed.

  Theorem perm_closure_recovered :
    (forall u u', Permutation u u' -> eqv (obs (run u s0)) (obs (run u' s0))) <->
    ReconfigurationClosure.ClosureOK step obs eqv s0.
  Proof.
    rewrite fs_perm_inv, (closure_exact fs_adm fs_gen (msem step obs s0) eqv eqv_refl eqv_sym eqv_trans fs_prefix).
    exact fs_closure_iff.
  Qed.

  (* The closure pairs in whiskered form: the swap condition with a continuation. *)
  Theorem perm_swap_recovered :
    (forall u u', Permutation u u' -> eqv (obs (run u s0)) (obs (run u' s0))) <->
    forall u a b w, eqv (obs (run w (step b (step a (run u s0))))) (obs (run w (step a (step b (run u s0))))).
  Proof.
    rewrite fs_perm_inv, (closure_exact fs_adm fs_gen (msem step obs s0) eqv eqv_refl eqv_sym eqv_trans fs_prefix).
    split.
    - intros H u a b w.
      assert (P : PPC (@fs_adm E) fs_gen (u ++ [a; b] ++ w) (u ++ [b; a] ++ w))
        by (apply whisk_ppc_w; [exact fs_prefix | exists a, b; split; reflexivity | exact I | exact I]).
      pose proof (H _ _ P) as K. unfold msem in K. rewrite !runT_app in K. exact K.
    - intros H t t' P. destruct (ppc_whisk _ _ t t' P) as [_ [_ (p & u & v & w & (a & b & -> & ->) & -> & ->)]].
      unfold msem. rewrite !runT_app. apply H.
  Qed.
End FreeSwap.

(* ReconfigurationClosure.amodm_closure_exact and amodm_swap_exact, from P2. The migration M is
   the observation; it is not compatible with the A-steps in general, so P1 does not apply. *)
Theorem amodm_closure_recovered : forall {SA EA SB : Type} (stepA : EA -> SA -> SA)
  (eqvB : SB -> SB -> Prop), (forall x, eqvB x x) -> (forall x y, eqvB x y -> eqvB y x) ->
  (forall x y z, eqvB x y -> eqvB y z -> eqvB x z) -> forall (M : SA -> SB) s0,
  ReconfigurationClosure.AmodM stepA eqvB M s0 <-> ReconfigurationClosure.ClosureOK stepA M eqvB s0.
Proof.
  intros SA EA SB stepA eqvB Hr Hs Ht M s0. exact (perm_closure_recovered stepA M eqvB Hr Hs Ht s0).
Qed.

Theorem amodm_swap_recovered : forall {SA EA SB : Type} (stepA : EA -> SA -> SA)
  (eqvB : SB -> SB -> Prop), (forall x, eqvB x x) -> (forall x y, eqvB x y -> eqvB y x) ->
  (forall x y z, eqvB x y -> eqvB y z -> eqvB x z) -> forall (M : SA -> SB) s0,
  ReconfigurationClosure.AmodM stepA eqvB M s0 <->
  forall u a b w, eqvB (M (runT stepA w (stepA b (stepA a (runT stepA u s0)))))
                       (M (runT stepA w (stepA a (stepA b (runT stepA u s0))))).
Proof.
  intros SA EA SB stepA eqvB Hr Hs Ht M s0. exact (perm_swap_recovered stepA M eqvB Hr Hs Ht s0).
Qed.

